// Fusion hook of the conv engines. Every kernel that writes the conv output calls an epilogue
// functor on each fp32 result before its single rounding to the output type:
//
//   chan   = epi.chan(ch, ok);                       once per output column a thread owns
//   out[o] = Elem<T>::store(epi(acc, chan, o, live)); per element
//
//   ch    the column's channel (the output channel, groups included); ok false for a column past
//         the tensor's edge (it reads channel 0's operands and its result is discarded)
//   chan  ConvEpiGen::Chan, the per-channel operands (bias, scale, ...) held in registers
//   acc   the convolution's fp32 result for one output element
//   o     its element offset in the output tensor (computed only when ConvEpiGen::NEEDS_OFFSET)
//   live  false for lanes past the tensor's edge, whose result is discarded
//
// Unset CONV_EPI: nothing. Every change a kernel makes for the hook sits under
// `#if defined(CONV_EPI) && CONV_EPI`, with the unfused text in the `#else` branch, so an unfused
// build compiles exactly the text it compiled before the hook existed: the same signature,
// argument block and instructions by construction. CONV_EPI 1: the entry point gains a second
// parameter, ConvEpiArgs (ConvEpilogueArgs.h; CONV_EPI_PARAM / CONV_EPI_ARG), device functions
// take the functor (CONV_EPI_FN_PARAM / CONV_EPI_FN_ARG), and ConvEpiGen's body is generated by
// the provider from the graph's pointwise nodes:
//
//   CONV_EPI_CHAN_FIELDS  the per-channel registers (float members)
//   CONV_EPI_CHAN_CODE    fills c from channel ch (channel 0 when not ok, a column whose
//                         result is discarded)
//   CONV_EPI_CODE         the per-element body: transforms float v and returns it
//
// The generated code reads operand tensors through e.operand[] and values through e.scalar[];
// it depends on the pattern only, never on a value. The whole chain runs in fp32 and the kernel
// rounds once. No fast-math: relu, clamp and the activations keep their NaN and infinity rules.

#pragma once

