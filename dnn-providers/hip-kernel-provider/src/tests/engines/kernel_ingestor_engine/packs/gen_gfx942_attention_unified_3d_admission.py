"""Print Gfx942AttentionUnified3dAdmissionTable.inc.

Every row is rocKE's own answer: the strided split-KV decode candidate
(``dispatch.attention.strided_decode.make_candidate()``) is asked
``admits(req)`` for one request per (graph shape, mask, kv_block_size).
TestGfx942AttentionUnified3dAdmission.cpp builds the matching hipDNN graph for
each row and asserts the engine's graph match agrees.

The request carries ``arch="gfx942"``, ``kv_layout="strided"`` and an explicit
``num_cus=304``, so ``_resolve_num_cus`` never reads the host and the table is
the same on any box.

Graph -> request mapping (what the C++ test builds for a row):

    Q [B, Hq, Sq, D], K/V [B, Hkv, Skv, D], O [B, Hq, Sq, D], dtype fp16/bf16
        -> batch=B, nhead_q=Hq, nhead_k=Hkv, seqlen_q=Sq, seqlen_k=Skv,
           hdim_q=hdim_v=D, dtype
    mask NO_MASK               -> left_bound -1, right_bound -1
    mask TOP_LEFT_CAUSAL       -> left_bound -1, right_bound 0, TOP_LEFT
    mask BOTTOM_RIGHT_CAUSAL   -> left_bound -1, right_bound 0, BOTTOM_RIGHT
    window 128 (BOTTOM_RIGHT)  -> left_bound 128, right_bound 0, BOTTOM_RIGHT
                                  (rocKE: BOTTOM_RIGHT_CAUSAL, sliding_window=128)

``kv_block_size`` has no graph spelling (a dense graph has no page size); it is
the kernel's ``block_size`` field. A row records the answer for each of 16, 32
and 64.

The build generates the table into the build tree through
gen_gfx942_attention_unified_3d_table.py (kernel_ingestor_engine/CMakeLists.txt);
it is never committed. To print it by hand, from the provider root:

    cd rocke/library && PYTHONPATH=.:../platform/python python3 \\
        ../../src/tests/engines/kernel_ingestor_engine/packs/gen_gfx942_attention_unified_3d_admission.py
"""

import itertools

from dispatch.attention.common import AttentionMaskType, AttentionRequest
from dispatch.attention.strided_decode import make_candidate

NUM_CUS = 304
BATCHES = (1, 3, 64)
# (Hq, Hkv): GQA ratios 8, 4, 3, 32, 1, 16 and 2. Every ratio the engine ships (1, 2, 4, 8,
# 16) is sampled, plus 3 (rocKE admits it, v1 refuses it) and 32 (both refuse it).
HEADS = ((8, 1), (32, 8), (12, 4), (32, 1), (16, 16), (16, 1), (8, 4))
SEQLEN_Q = (1, 2)
SEQLEN_K = (1, 64, 256, 512, 8192)
# 192: rocKE admits it, v1 refuses it. 96: both refuse it.
HEAD_SIZES = (64, 96, 128, 192, 256)
DTYPES = ("fp16", "bf16")
# (C++ mask spelling, rocKE mask type, sliding_window)
MASKS = (
    ("NO_MASK", AttentionMaskType.NO_MASK, 0),
    ("TOP_LEFT_CAUSAL", AttentionMaskType.TOP_LEFT_CAUSAL, 0),
    ("BOTTOM_RIGHT_CAUSAL", AttentionMaskType.BOTTOM_RIGHT_CAUSAL, 0),
    ("WINDOW_128", AttentionMaskType.BOTTOM_RIGHT_CAUSAL, 128),
)
KV_BLOCK_SIZES = (16, 32, 64)


def admitted(candidate, b, hq, hkv, sq, skv, d, dtype, mask, window, block):
    req = AttentionRequest(
        batch=b,
        nhead_q=hq,
        nhead_k=hkv,
        seqlen_q=sq,
        seqlen_k=skv,
        hdim_q=d,
        hdim_v=d,
        arch="gfx942",
        mask_type=mask,
        sliding_window=window,
        kv_block_size=block,
        num_cus=NUM_CUS,
        dtype=dtype,
        kv_layout="strided",
    )
    return candidate.admits(req)[0]


def main():
    candidate = make_candidate()
    print("// Generated by gen_gfx942_attention_unified_3d_admission.py; do not edit.")
    print(
        "// {batch, hq, hkv, seqlen_q, seqlen_k, head_size, dtype, mask, "
        "admitted at kv_block_size 16, 32, 64}"
    )
    for b, (hq, hkv), sq, skv, d, dtype, (name, mask, window) in itertools.product(
        BATCHES, HEADS, SEQLEN_Q, SEQLEN_K, HEAD_SIZES, DTYPES, MASKS
    ):
        flags = ", ".join(
            (
                "true"
                if admitted(candidate, b, hq, hkv, sq, skv, d, dtype, mask, window, blk)
                else "false"
            )
            for blk in KV_BLOCK_SIZES
        )
        print(
            f'{{{b}, {hq}, {hkv}, {sq}, {skv}, {d}, "{dtype}", AdmissionMask::{name}, {flags}}},'
        )


if __name__ == "__main__":
    main()
