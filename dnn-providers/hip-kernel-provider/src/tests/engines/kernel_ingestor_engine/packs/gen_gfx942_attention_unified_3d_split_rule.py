"""Print Gfx942AttentionUnified3dSplitRuleTable.inc.

Every row is rocKE's own answer: the problem is built by
``dispatch.attention.common._problem_with_num_cus`` (the body of ``_problem``
with the CU count pinned, so the table is host-independent) for a strided
single-token decode request, and the segment count is
``kernels.common.attention_unified._num_segments(problem, "gfx942")``.
TestGfx942AttentionUnified3dSplitRule.cpp asserts the C++ restatement agrees
with every row.

The build generates the table into the build tree through
gen_gfx942_attention_unified_3d_table.py (kernel_ingestor_engine/CMakeLists.txt);
it is never committed. To print it by hand, from the provider root:

    cd rocke/library && PYTHONPATH=.:../platform/python python3 \
        ../../src/tests/engines/kernel_ingestor_engine/packs/gen_gfx942_attention_unified_3d_split_rule.py
"""

import itertools

from dispatch.attention.common import (
    AttentionMaskType,
    AttentionRequest,
    _problem_with_num_cus,
)
from kernels.common.attention_unified import _num_segments

BATCHES = (1, 4, 16, 64, 256)
KV_HEADS = (1, 8)
GQA = (1, 2, 4, 8, 16)
SEQLEN_K = (1, 64, 256, 512, 2048, 8192, 32768, 131072)
HEAD_SIZES = (64, 128, 256)
BLOCK_SIZES = (16, 32, 64)
# 304: MI300X, the reference device. 228: MI300A. 76 and 38: MI300X split into
# 4 and 8 partitions (gfx942 is not floored, see _resolve_num_cus). The product
# grid runs at each, so the scorer's live-CU path is sampled beyond 304.
# 80: one more partitioned count, sampled below to cover both sides of the
# `ctas * 16 >= num_cus` scope test.
FULL_CUS = 304
GRID_CUS = (FULL_CUS, 228, 76, 38)
PARTIAL_CUS = 80
PARTIAL_ROWS = (
    # batch, hkv, gqa, skv, d, block
    (1, 1, 4, 8192, 128, 16),
    (1, 8, 4, 8192, 128, 16),
    (1, 8, 4, 32768, 128, 16),
    (4, 1, 16, 32768, 64, 16),
    (16, 8, 1, 2048, 64, 16),
    (64, 8, 4, 131072, 128, 16),
    (1, 1, 1, 512, 256, 32),
    (4, 8, 4, 8192, 128, 64),
    # ctas * 16 == num_cus exactly: pins `>=` (a `>` restatement differs).
    (5, 1, 1, 8192, 64, 16),
)
# Pinned edges at FULL_CUS that the product grid misses.
FULL_EDGE_ROWS = (
    # batch, hkv, gqa, skv, d, block
    # The D128 pre-bump clamp binds: pins its fixed _PRE_BUMP_CUS = 120 target.
    (12, 1, 4, 4096, 128, 32),
    # Few CTAs (ctas * 16 < 304) on either side of the decode rule's Skv < 8192 test
    # and its cap 64/128 step: pins the 8192 threshold.
    (1, 1, 4, 4096, 128, 16),
    (1, 8, 4, 4096, 64, 16),
    (1, 1, 4, 8191, 128, 16),
    (1, 8, 1, 8191, 64, 16),
    # Just below the D128 pre-bump clamp's Skv < 32768 bound (32768 is in the grid).
    (1, 1, 4, 32767, 128, 16),
    (1, 8, 4, 32767, 128, 32),
    # D256 block 16 rule: the floor of 2 (Skv // 32 = 1) and the Skv // 32 cap (3).
    (4, 8, 4, 32, 256, 16),
    (1, 1, 1, 96, 256, 16),
    # qpk 8 on the select_3d path: block_m 16 gives block_q 2, so num_2d =
    # (3 // 2 + 3) * 4 = 16 -> 128; a block_q of 1 would give (3 + 3) * 4 = 24 -> 64.
    # The grid's batches and KV heads cannot tell these apart.
    (3, 4, 8, 131072, 64, 32),
)


def segments(batch, hkv, gqa, skv, d, block, cus):
    req = AttentionRequest(
        batch=batch,
        nhead_q=hkv * gqa,
        nhead_k=hkv,
        seqlen_q=1,
        seqlen_k=skv,
        hdim_q=d,
        hdim_v=d,
        arch="gfx942",
        mask_type=AttentionMaskType.BOTTOM_RIGHT_CAUSAL,
        kv_block_size=block,
        num_cus=cus,
        dtype="fp16",
        kv_layout="strided",
    )
    return _num_segments(_problem_with_num_cus(req, cus), "gfx942")


def main():
    rows = [
        (b, kh, kh * g, d, blk, skv, cus)
        for cus, b, kh, g, skv, d, blk in itertools.product(
            GRID_CUS, BATCHES, KV_HEADS, GQA, SEQLEN_K, HEAD_SIZES, BLOCK_SIZES
        )
    ]
    rows += [
        (b, kh, kh * g, d, blk, skv, PARTIAL_CUS)
        for b, kh, g, skv, d, blk in PARTIAL_ROWS
    ]
    rows += [
        (b, kh, kh * g, d, blk, skv, FULL_CUS)
        for b, kh, g, skv, d, blk in FULL_EDGE_ROWS
    ]
    print("// Generated by gen_gfx942_attention_unified_3d_split_rule.py; do not edit.")
    print("// {batch, hq, hkv, head_size, block_size, seqlen_k, num_cus, num_segments}")
    for b, kh, hq, d, blk, skv, cus in rows:
        n = segments(b, kh, hq // kh, skv, d, blk, cus)
        print(f"{{{b}, {hq}, {kh}, {d}, {blk}, {skv}, {cus}, {n}}},")


if __name__ == "__main__":
    main()
