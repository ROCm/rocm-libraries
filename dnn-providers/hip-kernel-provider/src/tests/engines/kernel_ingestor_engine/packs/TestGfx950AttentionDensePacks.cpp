/// The runtime source kind every kernel of this bundle must declare once it reaches a
/// loader. A packaged bundle is lowered to a kpack archive before the runtime reads
/// it, so the authored builder kind is not what arrives.
constexpr ingestor::KernelSourceKind EXPECTED_SOURCE_KIND = ingestor::KernelSourceKind::KPACK;

/// A pack or kernel with no architecture of its own inherits/wildcards; one that names
/// architectures must name the requested one, or this shard is the wrong shard.
bool coversArch(const std::vector<std::string>& declared, const std::string& arch)
{
    return declared.empty() || std::find(declared.begin(), declared.end(), arch) != declared.end();
}

