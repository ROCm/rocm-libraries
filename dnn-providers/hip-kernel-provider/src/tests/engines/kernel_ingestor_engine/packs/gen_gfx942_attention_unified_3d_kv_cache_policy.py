"""Print Gfx942AttentionUnified3dKvCachePolicyTable.inc.

Every row is rocKE's own answer: the problem is built by
``dispatch.attention.common._problem_with_num_cus`` for a strided single-token
decode request, and the policy is
``kernels.common.attention_unified._kv_cache_policy_3d(problem, "gfx942")``.
TestGfx942AttentionUnified3dGeometry.cpp asserts gfx942KvCachePolicy() agrees
with every row.

The grid straddles the 256 MiB threshold (2 * B * Skv * Hkv * D * 2 bytes): it
holds K/V of exactly 256 MiB (B 8, Skv 8192, Hkv 8, D 128: "all", the rule is
"greater than") and the next batch up (B 9: "stream"), so moving the threshold
or turning ">" into ">=" changes a sampled row.

The build generates the table into the build tree through
gen_gfx942_attention_unified_3d_table.py (kernel_ingestor_engine/CMakeLists.txt);
it is never committed. To print it by hand, from the provider root:

    cd rocke/library && PYTHONPATH=.:../platform/python python3 \\
        ../../src/tests/engines/kernel_ingestor_engine/packs/gen_gfx942_attention_unified_3d_kv_cache_policy.py
"""

import itertools

from dispatch.attention.common import (
    AttentionMaskType,
    AttentionRequest,
    _problem_with_num_cus,
)
from kernels.common.attention_unified import _kv_cache_policy_3d

BATCHES = (1, 4, 8, 9, 16, 32, 64, 256)
KV_HEADS = (1, 8)
HEAD_SIZES = (64, 128, 256)
SEQLEN_K = (1, 512, 8191, 8192, 32768, 131072)
# The policy reads neither the query heads nor the CU count; both are fixed.
GQA = 4
NUM_CUS = 304


def policy(batch, hkv, d, skv):
    req = AttentionRequest(
        batch=batch,
        nhead_q=hkv * GQA,
        nhead_k=hkv,
        seqlen_q=1,
        seqlen_k=skv,
        hdim_q=d,
        hdim_v=d,
        arch="gfx942",
        mask_type=AttentionMaskType.BOTTOM_RIGHT_CAUSAL,
        kv_block_size=16,
        num_cus=NUM_CUS,
        dtype="fp16",
        kv_layout="strided",
    )
    return _kv_cache_policy_3d(_problem_with_num_cus(req, NUM_CUS), "gfx942")


def main():
    print(
        "// Generated by gen_gfx942_attention_unified_3d_kv_cache_policy.py; do not edit."
    )
    print("// {batch, num_kv_heads, head_size, seqlen_k, stream (1) or all (0)}")
    for b, hkv, d, skv in itertools.product(BATCHES, KV_HEADS, HEAD_SIZES, SEQLEN_K):
        p = policy(b, hkv, d, skv)
        if p not in ("stream", "all"):
            raise ValueError(f"rocKE returned kv_cache_policy {p!r}")
        print(f"{{{b}, {hkv}, {d}, {skv}, {1 if p == 'stream' else 0}}},")


if __name__ == "__main__":
    main()
