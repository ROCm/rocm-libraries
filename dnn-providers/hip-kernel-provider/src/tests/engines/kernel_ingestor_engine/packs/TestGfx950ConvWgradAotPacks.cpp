/// The engine ships a ranking model, so its score symbol must be REGISTERED, not merely
/// named: a descriptor naming an unregistered one is dropped, and the engine then ranks
/// on priority as if no model existed.
TEST_F(TestGfx950ConvWgradAotPacks, RanksThroughItsRegisteredScoreSymbol)
{
    ASSERT_TRUE(_set->heuristic.has_value());
    EXPECT_EQ(_set->heuristic->nativeSymbol, "hipkernel.gfx950_conv_wgrad_aot.score");
    EXPECT_TRUE(ingestor::ScoreRegistry::isRegistered("hipkernel.gfx950_conv_wgrad_aot.score"));
}

/// UMD policy, this engine's shape: a MULTI-pack engine carries one graph-scoped
/// operation matcher per pack, on top of the one shared kernel-scoped matcher.
TEST_F(TestGfx950ConvWgradAotPacks, CarriesOneGraphScopedMatcherPerPack)
{
    const auto graphScoped
        = std::count_if(_set->matchers.begin(), _set->matchers.end(), [](const auto& matcher) {
              return matcher.scope == ingestor::MatchScope::GRAPH;
          });
    EXPECT_EQ(static_cast<size_t>(graphScoped), _expected->packNames.size());
}

TEST_F(TestGfx950ConvWgradAotPacks, CarriesExactlyOneSharedKernelScopedMatcher)
{
    const auto kernelScoped
        = std::count_if(_set->matchers.begin(), _set->matchers.end(), [](const auto& matcher) {
              return matcher.scope == ingestor::MatchScope::KERNEL;
          });
    EXPECT_EQ(kernelScoped, 1);
}

