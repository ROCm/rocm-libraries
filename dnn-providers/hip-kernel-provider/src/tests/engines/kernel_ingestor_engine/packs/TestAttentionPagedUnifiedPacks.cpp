/// The runtime source kind every kernel must declare at the loader. A packaged bundle
/// is lowered to a kpack archive first, so the authored builder kind is not what
/// arrives.
constexpr ingestor::KernelSourceKind EXPECTED_SOURCE_KIND = ingestor::KernelSourceKind::KPACK;

class TestAttentionPagedUnifiedPacks : public ::testing::Test
{
protected:
    void SetUp() override
    {
        _arch = hipdnn_data_sdk::utilities::getEnv("HIPDNN_TEST_EXPECTED_ARCH");
        ASSERT_FALSE(_arch.empty())
            << "HIPDNN_TEST_EXPECTED_ARCH is unset, so this census has no expectation to "
               "check against. The architecture is supplied explicitly by the caller; it "
               "is never detected from a device and never taken from the descriptors "
               "being censused.";

        const auto& table = expectedByArch();
        auto row = table.find(_arch);
        if(row == table.end())
        {
            row = table.find(ARCH_WILDCARD);
        }
        ASSERT_NE(row, table.end())
            << "this bundle emitted no descriptors for architecture '" << _arch
            << "' and no architecture-independent ones either, so there is no expected "
               "identity to check. Either the wrong architecture was requested or the "
               "generation that produced this bundle did not cover it.";
        _expected = &row->second;

        const auto& sets = discoverDescriptorSets();
        const auto match = std::find_if(sets.begin(), sets.end(), [](const auto& set) {
            return set.engine.name == ATTENTION_PAGED_UNIFIED_ENGINE_NAME;
        });
        ASSERT_NE(match, sets.end())
            << "descriptor set '" << ATTENTION_PAGED_UNIFIED_ENGINE_NAME
            << "' did not load. Either its descriptors were never installed under the tree "
               "this binary reads, its UED declares a different engine name than "
               "ATTENTION_PAGED_UNIFIED_ENGINE_NAME, or its pack failed to register its "
               "native symbols and every descriptor naming one of them was dropped.";
        _set = &*match;
    }

    std::string _arch;
    const ExpectedInventory* _expected = nullptr;
    const ingestor::DescriptorSet* _set = nullptr;
};

TEST_F(TestAttentionPagedUnifiedPacks, LoadsExactlyTheEmittedPacks)
{
    std::set<std::string> loaded;
    for(const auto& pack : _set->packs)
    {
        loaded.insert(pack.name);
    }
    // Set equality, not a count: a missing pack and an extra one cancel in a count.
    EXPECT_EQ(loaded, _expected->packNames);
}

TEST_F(TestAttentionPagedUnifiedPacks, LoadsExactlyTheEmittedKernels)
{
    std::set<std::string> loaded;
    for(const auto& pack : _set->packs)
    {
        for(const auto& kernel : pack.kernels)
        {
            loaded.insert(kernel.name);
        }
    }
    EXPECT_EQ(loaded, _expected->kernelNames);
}

TEST_F(TestAttentionPagedUnifiedPacks, EveryLoadedDescriptorCoversTheRequestedArch)
{
    for(const auto& pack : _set->packs)
    {
        EXPECT_TRUE(ingestor::archSupports(pack.arch, _arch))
            << "pack '" << pack.name << "' does not cover '" << _arch
            << "', so this is not that architecture's shard";
        for(const auto& kernel : pack.kernels)
        {
            EXPECT_TRUE(ingestor::archSupports(kernel.arch, _arch))
                << "kernel '" << kernel.name << "' does not cover '" << _arch << "'";
        }
    }
}

TEST_F(TestAttentionPagedUnifiedPacks, EveryKernelDeclaresTheEmittedRuntimeSourceKind)
{
    for(const auto& pack : _set->packs)
    {
        for(const auto& kernel : pack.kernels)
        {
            EXPECT_EQ(kernel.source.kind, EXPECTED_SOURCE_KIND)
                << "kernel '" << kernel.name << "' reached the loader as a different "
                << "source kind than this bundle ships";
        }
    }
}

TEST_F(TestAttentionPagedUnifiedPacks, DeclaresTheConfiguredSdkVersion)
{
    EXPECT_EQ(_set->engine.sdkVersion, hipdnn_data_sdk::utilities::Version{std::string("1.4.0")});
}

TEST_F(TestAttentionPagedUnifiedPacks, ExposesTheConfiguredKnobs)
{
    ASSERT_EQ(_set->engine.knobs.size(), 0U);
}

/// heuristic: none. The engine ranks on priority then descriptor id, so it ships no UHD
/// and registers no score symbol. Loading cannot show the second half, so the registry
/// is asked directly.
TEST_F(TestAttentionPagedUnifiedPacks, ShipsNoHeuristicAndRegistersNoScoreSymbol)
{
    EXPECT_FALSE(_set->heuristic.has_value());
    EXPECT_FALSE(ingestor::ScoreRegistry::isRegistered("hipkernel.attention_paged_unified.score"));
}

/// UMD policy, this engine's shape: a MULTI-pack engine carries one graph-scoped
/// operation matcher per pack, on top of the one shared kernel-scoped matcher.
TEST_F(TestAttentionPagedUnifiedPacks, CarriesOneGraphScopedMatcherPerPack)
{
    const auto graphScoped
        = std::count_if(_set->matchers.begin(), _set->matchers.end(), [](const auto& matcher) {
              return matcher.scope == ingestor::MatchScope::GRAPH;
          });
    EXPECT_EQ(static_cast<size_t>(graphScoped), _expected->packNames.size());
}

TEST_F(TestAttentionPagedUnifiedPacks, CarriesExactlyOneSharedKernelScopedMatcher)
{
    const auto kernelScoped
        = std::count_if(_set->matchers.begin(), _set->matchers.end(), [](const auto& matcher) {
              return matcher.scope == ingestor::MatchScope::KERNEL;
          });
    EXPECT_EQ(kernelScoped, 1);
}

