/// The engine ships a ranking model, so its score symbol must be REGISTERED, not merely
/// named: a descriptor naming an unregistered one is dropped, and the engine then ranks
/// on priority as if no model existed.
TEST_F(TestGfx942ConvDgradAotPacks, RanksThroughItsRegisteredScoreSymbol)
{
    ASSERT_TRUE(_set->heuristic.has_value());
    EXPECT_EQ(_set->heuristic->nativeSymbol, "hipkernel.gfx942_conv_dgrad_aot.score");
    EXPECT_TRUE(ingestor::ScoreRegistry::isRegistered("hipkernel.gfx942_conv_dgrad_aot.score"));
}

/// UMD policy, this engine's shape: a SINGLE-pack engine, or one catalog sharded across
/// packs that declare no discriminator, carries no graph-scoped criterion -- its own
/// graph_match admits the node type and validates shape. Mirrors TestConvFwdPack.cpp's
/// HasAGraphMatchAndOneKernelMatcher.
TEST_F(TestGfx942ConvDgradAotPacks, CarriesNoGraphScopedMatcher)
{
    EXPECT_FALSE(_set->engine.graphMatchNativeSymbol.empty());
    const auto graphScoped
        = std::count_if(_set->matchers.begin(), _set->matchers.end(), [](const auto& matcher) {
              return matcher.scope == ingestor::MatchScope::GRAPH;
          });
    EXPECT_EQ(graphScoped, 0);
}

TEST_F(TestGfx942ConvDgradAotPacks, CarriesExactlyOneSharedKernelScopedMatcher)
{
    const auto kernelScoped
        = std::count_if(_set->matchers.begin(), _set->matchers.end(), [](const auto& matcher) {
              return matcher.scope == ingestor::MatchScope::KERNEL;
          });
    EXPECT_EQ(kernelScoped, 1);
}

