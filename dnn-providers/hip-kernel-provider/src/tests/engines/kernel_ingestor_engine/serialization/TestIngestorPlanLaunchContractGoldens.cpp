// Decodes a sample and hands back the dispatch contract it carries. The code object is
// checked as well, so a sample that decoded partly does not reach the value assertions.
template <size_t SIZE>
SavedLaunchInputs readSample(const std::array<uint8_t, SIZE>& golden)
{
    const serialization::IngestorPlanPayload payload
        = serialization::decodeIngestorPlan(golden.data(), golden.size());
    EXPECT_EQ(payload.codeObject,
              std::vector<uint8_t>(SAMPLE_CODE_OBJECT.begin(), SAMPLE_CODE_OBJECT.end()));
    return SavedLaunchInputs{payload.dispatchSymbol, payload.launchValues};
}

