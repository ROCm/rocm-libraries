// The launch a restored gfx942 plan configures, as makePreparedAttentionDense and
// PreparedAttentionDense compute it from the saved values: the CTA size, the grid (the
// arch geometry's on qb_minor, the block order's or num_persistent CTAs otherwise), and on
// the persistent grid the fast-division divisors, in kernarg order, and their magic/shift
// pairs. None of these is saved, so a value whose meaning changes lands here.
struct Gfx942SampleLaunch
{
    unsigned blockX = 0;
    std::array<int64_t, 3> grid{};
    std::vector<std::string> fastDivDivisors;
    std::vector<AttentionDenseFastDivPair> fastDiv;
};

Gfx942SampleLaunch gfx942SampleLaunch(const Gfx942AttentionDenseLaunchInputs& launch)
{
    const Gfx942AttentionDenseGeometry geometry
        = gfx942AttentionDenseGeometry(launch.blockM,
                                       launch.problem.seqLenQ,
                                       launch.problem.numQueryHeads,
                                       launch.problem.batch,
                                       "launch contract sample");
    const AttentionDenseGridShape shape = attention_dense::gridShape(launch);
    const auto illegal = attention_dense::gridIllegality(launch.grid, shape);
    EXPECT_FALSE(illegal.has_value()) << illegal.value_or("");

    Gfx942SampleLaunch sample;
    sample.blockX = geometry.blockX;
    sample.grid = launch.grid.order == AttentionDenseGridOrder::QB_MINOR
                      ? std::array<int64_t, 3>{geometry.gridX, geometry.gridY, geometry.gridZ}
                      : attention_dense::gridDims(launch.grid, shape);
    if(launch.grid.persistent())
    {
        for(const auto divisor : attention_dense::fastDivDivisors(launch.grid.decode))
        {
            sample.fastDivDivisors.emplace_back(attention_dense::divisorName(divisor));
        }
    }
    sample.fastDiv = attention_dense::fastDivKernargs(launch.grid, shape);
    return sample;
}

