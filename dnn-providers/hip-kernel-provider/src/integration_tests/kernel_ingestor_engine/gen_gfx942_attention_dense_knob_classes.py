"""Render IntegrationGpuGfx942AttentionDenseKnobClasses.inc: one row per kernel of the
shipped gfx942 dense selection (configs/gfx942_attention_dense.yaml).

A row is what the knob suite forces one graph onto: head size, dtype, mask cell (causal,
sliding window), the stats output, the tile, the launch grid and the body levers, which are
engine knobs too, so each row selects exactly one kernel. The suite runs every row against
the CPU reference, and its coverage test checks the rows' classes are exactly the runtime
catalog's, so a reduction that changes the catalog fails until this is rerun.

    projects/hipdnn/tools/IngestorGenerator/.venv/bin/python \\
        dnn-providers/hip-kernel-provider/src/integration_tests/kernel_ingestor_engine/gen_gfx942_attention_dense_knob_classes.py

tests/test_attention_dense_goldens.py renders it and fails if the checked-in table is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_REPO = _HERE.parents[4]
_GENERATOR = _REPO / "projects" / "hipdnn" / "tools" / "IngestorGenerator"
SELECTION = _GENERATOR / "configs" / "gfx942_attention_dense.yaml"
OUT = _HERE / "IntegrationGpuGfx942AttentionDenseKnobClasses.inc"


# Body levers, in the KnobClass field order; each is an engine knob.
LEVERS = (
    "lds_row_pad",
    "pv_priority",
    "lds_num_buffers",
    "v_reg_prefetch",
    "causal_diag_split",
    "o_store_width",
    "pv_loop_order",
    "use_cfvst",
    "use_exp2_fast",
    "lds_k_group_pad",
)


def classes() -> list:
    """Sorted rows (head_size, dtype, causal, window, emit_lse, block_m, block_n,
    persistent, grid order, *LEVERS), one per kernel of the selection."""
    if str(_GENERATOR) not in sys.path:
        sys.path.insert(0, str(_GENERATOR))
    from codegen.config_loader import load_config

    rows = set()
    for kernel in load_config(SELECTION).packs[0].kernels:
        m = kernel.metadata
        persistent = bool(m["persistent"])
        rows.add(
            (
                int(m["head_size"]),
                str(m["dtype"]),
                bool(m["causal"]),
                int(m["sliding_window"]),
                bool(m["emit_lse"]),
                int(m["block_m"]),
                int(m["block_n"]),
                persistent,
                str(m["persist_decode"] if persistent else m["nonpersist_decode"]),
                *(
                    m[lever] if isinstance(m[lever], str) else int(m[lever])
                    for lever in LEVERS
                ),
            )
        )
    return sorted(rows)


def _cpp(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def render() -> str:
    rows = classes()
    lines = [
        "// Copyright © Advanced Micro Devices, Inc., or its affiliates.",
        "// SPDX-License-Identifier:  MIT",
        "",
        "// Generated by gen_gfx942_attention_dense_knob_classes.py from",
        "// projects/hipdnn/tools/IngestorGenerator/configs/gfx942_attention_dense.yaml.",
        "// Do not edit; rerun the generator after the selection changes.",
        "",
        "// {head_size, dtype, causal, window, emit_lse, block_m, block_n, persistent, order,",
        "//  {" + ", ".join(LEVERS) + "}}",
        f"constexpr std::array<KnobClass, {len(rows)}> KNOB_CLASSES{{{{",
    ]
    lines += [
        "    {"
        + ", ".join(_cpp(v) for v in row[:9])
        + ", {"
        + ", ".join(_cpp(v) for v in row[9:])
        + "}},"
        for row in rows
    ]
    lines.append("}};")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"{len(classes())} kernels -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
