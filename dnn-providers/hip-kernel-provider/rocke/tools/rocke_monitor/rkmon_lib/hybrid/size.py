"""Effective size of a review round: what a reviewer must read, with no model call (ported from the v2 harness).

- First round: the PR's own change, its merge base to its head.
- Follow-up: the interdiff since our previous reviewed head, the PR's own changes only. Each head's diff is taken
  against that head's own merge base with develop, so develop merged into the branch drops out; the two diffs are then
  compared per file and per hunk (a multiset of changed lines per file: lines new at this head, plus lines of the old
  diff the head no longer has).
- Renames are detected (`-M`). A pure rename counts as zero lines, with an integrity check (the same blob, or the
  similarity score); a rename with edits counts its edited lines only.
- Generated, golden and data files (`*.json` goldens, emitted parity sources, `*.ll`, data tables, `.dvc` pointers,
  lockfiles, binaries) are classed apart: they go to the scripted gates (the golden gate, byte identity) and a small
  sampled look, not to the judges line by line. By content too: a file whose first added lines say it is generated,
  and a large addition that is nearly all literals (a dispatch table, a selector model) whatever its extension. Merge
  leftovers (`*.orig`, `*.rej`) are classed `stray` and reported as facts.

All git calls are read only on the mirror: no fetch, lazy fetches off (GIT_NO_LAZY_FETCH), SHAs only.
"""

import collections
import re


from .common import git, is_test_path

REVIEWED = ("code", "test", "doc")
GATED = ("golden", "generated", "data", "dvc", "lock", "binary")
TIERS = ((1500, "<1.5k"), (10000, "1.5k-10k"), (None, "10k+"))
LOCKFILES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "uv.lock",
    "cargo.lock",
    "pipfile.lock",
    "composer.lock",
    "gemfile.lock",
    "conda-lock.yml",
}
GENERATED_EXT = (".ll", ".s", ".hsaco", ".bc", ".co", ".o", ".so", ".a")
DATA_EXT = (
    ".csv",
    ".tsv",
    ".npy",
    ".npz",
    ".dat",
    ".bin",
    ".parquet",
    ".pkl",
    ".h5",
    ".hdf5",
    ".db",
    ".sqlite",
)
DOC_EXT = (".md", ".rst", ".adoc")
STRAY_EXT = (".orig", ".rej", ".bak", ".swp", ".swo")
GOLDEN_DIR = re.compile(
    r"(^|/)(golden|goldens|expected|baselines?|reference_outputs?|snapshots?)(/|$)",
    re.I,
)
EMITTED = re.compile(r"(^|/)parity/[^/]*_emit\.(c|cc|cpp|h|hpp|ll|s)$", re.I)
DATA_DIR = re.compile(r"(^|/)(data|tables|datasets|testdata)(/|$)", re.I)
DATA_NAME = re.compile(r"(\.model\.txt|\.manifest|_tables?\.inc)$", re.I)
GEN_MARK = re.compile(
    r"(auto-?generated|[@]generated|do not edit|this file (is|was) (auto-?)?generated|"
    r"generated (file|code)\b|generated by \S*(script|tool|\.py|\.sh)|code generated by)",
    re.I,
)
DATA_MIN_LINES = 1000  # an addition this large is checked for being a table
GEN_MIN_LINES = 300  # a new file this large whose header comment says it is generated
DATA_SHARE = 0.85  # of its non-blank, non-comment added lines that are literals only
STRING = re.compile(r"\"(?:[^\"\\]|\\.)*\"|'(?:[^'\\]|\\.)*'")
IDENT = re.compile(r"(?<![\w.])(?!0x)[A-Za-z_]\w*")
COMMENT = re.compile(r"^\s*(#|//|/\*|\*|--)")


def tier(lines: int) -> str:
    for lim, name in TIERS:
        if lim is None or lines < lim:
            return name
    return TIERS[-1][1]


def by_content(f: dict) -> str | None:
    """generated or data from a file's added lines, or None."""
    added = [x[1:] for h in f["hunks"] for x in h["lines"] if x[:1] == "+"]
    if (
        f["st"] == "A"
        and len(added) >= GEN_MIN_LINES
        and any(
            GEN_MARK.search(x)
            and (COMMENT.match(x) or x.lstrip()[:3] in ('"' * 3, "'" * 3))
            for x in added[:12]
        )
    ):
        return "generated"
    if len(added) < DATA_MIN_LINES:
        return None
    share = literal_share(added)
    return "data" if share is not None and share >= DATA_SHARE else None


def literal_share(lines: list[str]) -> float | None:
    """The share of the non-blank, non-comment lines that hold only literals (numbers, strings, at most one name),
    or None when there are none."""
    body = [x for x in lines if x.strip() and not COMMENT.match(x)]
    if not body:
        return None
    lit = 0
    for x in body:
        s = STRING.sub('""', x)
        idents = [
            t
            for t in IDENT.findall(s)
            if t not in ("True", "False", "None", "true", "false", "nullptr")
            and not re.fullmatch(r"[eE]\d*", t)
        ]
        if len(idents) <= 1 and re.search(r"[\d\"']", s):
            lit += 1
    return lit / len(body)


def classify(path: str, binary: bool = False) -> str:
    p = path.replace("\\", "/")
    base = p.rsplit("/", 1)[-1].lower()
    ext = ("." + base.rsplit(".", 1)[-1]) if "." in base else ""
    if base.endswith(STRAY_EXT) or base.endswith("~"):
        return "stray"
    if binary:
        return "binary"
    if ext == ".dvc":
        return "dvc"
    if base in LOCKFILES or ext == ".lock":
        return "lock"
    if (
        ext in GENERATED_EXT
        or "/generated/" in p
        or "_generated." in base
        or ".gen." in base
    ):
        return "generated"
    if (
        ext in (".json", ".txt", ".yaml", ".yml", ".ll", ".mlir")
        and GOLDEN_DIR.search(p)
    ) or EMITTED.search(p):
        return "golden"
    if (
        ext in DATA_EXT
        or DATA_NAME.search(base)
        or (ext in (".json", ".yaml", ".yml") and DATA_DIR.search(p))
    ):
        return "data"
    if is_test_path(p):
        return "test"
    if ext in DOC_EXT:
        return "doc"
    return "code"


# --- the diff ---------------------------------------------------------------------------------------------------------

HUNK = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")


def parse_patch(text: str) -> list[dict]:
    """[{p, op, st, sim, ob, nb, bin, a, d, hunks: [{h, ns, nl, os, ol, lines}]}] from `git diff -M --full-index`."""
    files, cur, hunk = [], None, None
    left_old = left_new = 0
    for line in text.splitlines():
        if hunk is not None and (left_old > 0 or left_new > 0):
            # inside a hunk, counted by its header: a removed "-- x" line is not a file header
            if line.startswith("\\"):
                continue
            t = line[:1]
            if t == "+":
                left_new -= 1
                cur["a"] += 1
            elif t == "-":
                left_old -= 1
                cur["d"] += 1
            else:
                left_old -= 1
                left_new -= 1
            hunk["lines"].append(line)
            continue
        if line.startswith("diff --git "):
            m = re.match(r"diff --git a/(.+?) b/(.+)$", line)
            a, b = (m.group(1), m.group(2)) if m else (line[11:], line[11:])
            cur = {
                "p": b,
                "op": a,
                "st": "M",
                "sim": None,
                "ob": "",
                "nb": "",
                "bin": False,
                "a": 0,
                "d": 0,
                "hunks": [],
            }
            files.append(cur)
            hunk = None
            continue
        if cur is None:
            continue
        if hunk is None:
            if line.startswith("new file mode"):
                cur["st"] = "A"
            elif line.startswith("deleted file mode"):
                cur["st"] = "D"
            elif line.startswith("rename from "):
                cur["st"], cur["op"] = "R", line[12:]
            elif line.startswith("rename to "):
                cur["p"] = line[10:]
            elif line.startswith("copy from "):
                cur["st"], cur["op"] = "C", line[10:]
            elif line.startswith("copy to "):
                cur["p"] = line[8:]
            elif line.startswith(("similarity index ", "dissimilarity index ")):
                cur["sim"] = int(re.sub(r"\D", "", line) or 0)
            elif line.startswith("index "):
                m = re.match(r"index ([0-9a-f]+)\.\.([0-9a-f]+)", line)
                if m:
                    cur["ob"], cur["nb"] = m.groups()
            elif line.startswith("Binary files ") or line.startswith(
                "GIT binary patch"
            ):
                cur["bin"] = True
        if line.startswith("@@"):
            m = HUNK.match(line)
            if not m:
                continue
            os_, ol, ns, nl = m.groups()
            hunk = {
                "h": line,
                "os": int(os_),
                "ol": int(ol) if ol is not None else 1,
                "ns": int(ns),
                "nl": int(nl) if nl is not None else 1,
                "lines": [],
            }
            left_old, left_new = hunk["ol"], hunk["nl"]
            cur["hunks"].append(hunk)
    for f in files:
        f["cls"] = classify(f["p"], f["bin"])
        if f["cls"] in ("code", "test", "doc"):
            f["cls"] = by_content(f) or f["cls"]
        for h in f["hunks"]:
            h["n"] = sum(1 for x in h["lines"] if x[:1] in "+-")
    return files


def changed(h: dict) -> list[str]:
    return [x for x in h["lines"] if x[:1] in "+-"]


def file_lines(f: dict) -> int:
    return sum(h["n"] for h in f["hunks"] if not h.get("skip"))


def pr_diff(repo: str, head: str, dev: str) -> tuple[list[dict] | None, str, str]:
    """(files, merge base, note): the PR's own change at head, from the mirror. None when an object is missing."""
    rc, mb = git(repo, "merge-base", head, dev)
    mb = mb.strip()
    if rc != 0 or not mb:
        return None, "", f"no merge base for {head[:10]} and {dev[:10]} in the mirror"
    rc, out = git(
        repo,
        "-c",
        "diff.renameLimit=20000",
        "diff",
        "-M",
        "--full-index",
        "--no-color",
        "--no-ext-diff",
        mb,
        head,
        timeout=900,
    )
    if rc != 0:
        return (
            None,
            mb,
            f"git diff {mb[:10]}..{head[:10]} failed (objects missing from the mirror?)",
        )
    return parse_patch(out), mb, ""


def interdiff(old: list[dict], new: list[dict]) -> dict:
    """The follow-up delta: per file the multiset of changed lines new at head plus those the head dropped; each new
    hunk carrying a new line is flagged `dl` (the reviewer reads it)."""
    by_old = {f["p"]: f for f in old}
    out = {"lines": 0, "files": [], "hunks": 0, "dropped": []}
    seen = set()
    for f in new:
        seen.add(f["p"])
        o = by_old.get(f["p"]) or by_old.get(f.get("op", ""))
        if o is not None:
            seen.add(o["p"])
        newc = collections.Counter(x for h in f["hunks"] for x in changed(h))
        oldc = collections.Counter(
            x for h in (o["hunks"] if o else []) for x in changed(h)
        )
        added, removed = newc - oldc, oldc - newc
        n = sum(added.values()) + sum(removed.values())
        if o is not None and f["nb"] and o["nb"] == f["nb"] and o["p"] == f["p"]:
            n, added, removed = 0, collections.Counter(), collections.Counter()
        left = collections.Counter(added)
        dl_hunks = 0
        for h in f["hunks"]:
            idx = []
            for k, x in enumerate(h["lines"]):
                if x[:1] in "+-" and left[x] > 0:
                    left[x] -= 1
                    idx.append(k)
            h["dl"] = 1 if idx else 0
            h["dl_idx"] = idx
            dl_hunks += h["dl"]
        f["dl_lines"] = n
        f["dl_removed"] = sum(removed.values())
        if n:
            out["files"].append(f["p"])
            out["lines"] += n
            out["hunks"] += dl_hunks
    for o in old:
        if o["p"] not in seen:
            n = sum(h["n"] for h in o["hunks"])
            out["dropped"].append({"p": o["p"], "cls": o["cls"], "lines": n})
            out["lines"] += n
    return out


# --- the measure ------------------------------------------------------------------------------------------------------


def summarize(files: list[dict], key=file_lines) -> dict:
    cl: dict[str, dict] = {}
    for f in files:
        c = cl.setdefault(f["cls"], {"files": 0, "lines": 0})
        c["files"] += 1
        c["lines"] += key(f)
    return cl


def renames(files: list[dict]) -> dict:
    items, pure, edited, lines = [], 0, 0, 0
    for f in files:
        if f["st"] != "R":
            continue
        n = sum(h["n"] for h in f["hunks"])
        same = (bool(f["ob"]) and f["ob"] == f["nb"]) or (
            f["sim"] == 100 and n == 0
        )  # git prints 100% for
        # identical blobs only, and then no index line
        if n == 0:
            pure += 1
        else:
            edited += 1
            lines += n
        items.append(
            {
                "from": f["op"],
                "to": f["p"],
                "sim": f["sim"],
                "same_blob": same,
                "lines": n,
                "ok": same or (f["sim"] or 0) >= 50,
            }
        )
    return {
        "n": len(items),
        "pure": pure,
        "edited": edited,
        "lines": lines,
        "failed_integrity": [i for i in items if not i["ok"]][:20],
        "items": items[:50],
    }


def measure(
    repo: str, head: str, dev: str, old: str = "", rnd: str = ""
) -> tuple[dict, list[dict], list[dict]]:
    """(the size record, the PR's files at head, the reviewed files of this round). A follow-up (old given) flags the
    delta hunks (`dl`) and reviews those; a first round reviews every hunk."""
    rnd = rnd or ("fu" if old else "fr")
    rec = {
        "v": 1,
        "rnd": rnd,
        "head": head,
        "dev": dev,
        "mb": "",
        "old": old or "",
        "old_mb": "",
        "src": "mirror",
        "notes": [],
    }
    files, mb, note = pr_diff(repo, head, dev)
    if files is None:
        rec.update(src="unknown", notes=[note])
        return rec, [], []
    rec["mb"] = mb
    delta = None
    if rnd == "fu" and old:
        ofiles, omb, onote = pr_diff(repo, old, dev)
        if ofiles is None:
            rec["notes"].append(
                f"old head: {onote}; the delta is unknown, the whole PR is counted"
            )
        else:
            rec["old_mb"] = omb
            delta = interdiff(ofiles, files)
    return finish(rec, files, delta)


def focus(files: list[dict], ctx: int = 8) -> list[dict]:
    """A follow-up's view: copies of the files whose changed hunks are cut down to windows of `ctx` lines around the
    lines new since our last review (a new file is one hunk: a three-line edit in it is not its whole length). Other
    hunks are kept, marked skip. The input is not changed (the cost model reuses it as the next round's old diff).
    """
    out = []
    for f in files:
        hunks = []
        for h in f["hunks"]:
            idx = h.get("dl_idx") or []
            if not h.get("dl") or not idx:
                hunks.append(dict(h, skip=True))
                continue
            wins = []
            for k in idx:
                lo, hi = max(k - ctx, 0), min(k + ctx, len(h["lines"]) - 1)
                if wins and lo <= wins[-1][1] + 1:
                    wins[-1][1] = max(wins[-1][1], hi)
                else:
                    wins.append([lo, hi])
            if len(wins) == 1 and wins[0] == [0, len(h["lines"]) - 1]:
                hunks.append(dict(h, skip=False))
                continue
            o, n, pos = h["os"], h["ns"], 0
            for lo, hi in wins:
                for x in h["lines"][pos:lo]:
                    o += x[:1] != "+"
                    n += x[:1] != "-"
                part = h["lines"][lo : hi + 1]
                co = sum(1 for x in part if x[:1] != "+")
                cn = sum(1 for x in part if x[:1] != "-")
                hunks.append(
                    dict(
                        h,
                        h=f"@@ -{o},{co} +{n},{cn} @@ (since our last review)",
                        os=o,
                        ol=co,
                        ns=n,
                        nl=cn,
                        lines=part,
                        n=sum(1 for x in part if x[:1] in "+-"),
                        skip=False,
                        dl_idx=[k - lo for k in idx if lo <= k <= hi],
                    )
                )
                o, n, pos = o + co, n + cn, hi + 1
        out.append(dict(f, hunks=hunks))
    return out


def finish(
    rec: dict, files: list[dict], delta: dict | None
) -> tuple[dict, list[dict], list[dict]]:
    orig = files
    if delta is not None:
        files = focus(files)
    reviewed = [f for f in files if f["cls"] in REVIEWED and file_lines(f) > 0]
    raw_a, raw_d = sum(f["a"] for f in orig), sum(f["d"] for f in orig)
    whole = {
        c: v
        for c, v in summarize(
            orig, key=lambda f: sum(h["n"] for h in f["hunks"])
        ).items()
    }
    pr_eff = sum(v["lines"] for c, v in whole.items() if c in REVIEWED)
    eff = sum(file_lines(f) for f in reviewed)
    rec.update(
        {
            "raw": {
                "a": raw_a,
                "d": raw_d,
                "lines": raw_a + raw_d,
                "files": len(files),
            },
            "pr_eff": pr_eff,
            "eff": eff,
            "tier": tier(eff),
            "classes": whole,
            "renames": renames(orig),
            "gates": [
                {"p": f["p"], "cls": f["cls"], "lines": f["a"] + f["d"]}
                for f in orig
                if f["cls"] in GATED
            ][:200],
            "stray": [f["p"] for f in orig if f["cls"] == "stray"],
        }
    )
    if delta is not None:
        rec["delta"] = {
            "lines": delta["lines"],
            "reviewed": eff,
            "files": len(delta["files"]),
            "hunks": delta["hunks"],
            "dropped": delta["dropped"][:50],
            "classes": summarize(
                [f for f in orig if f.get("dl_lines")],
                key=lambda f: f.get("dl_lines", 0),
            ),
        }
    else:
        rec["delta"] = None
    return rec, files, reviewed
