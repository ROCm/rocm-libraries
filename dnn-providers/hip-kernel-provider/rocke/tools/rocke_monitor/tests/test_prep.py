        cls.base = commit(
            origin, {"rk/a.py": "1\n", "rk/b.py": "1\n", "other/c.txt": "1\n"}, "base"
        )
        g(origin, "checkout", "-q", "-b", "pr7")
        cls.old = commit(origin, {"rk/a.py": "2\n"}, "pr: a")  # the head we reviewed
