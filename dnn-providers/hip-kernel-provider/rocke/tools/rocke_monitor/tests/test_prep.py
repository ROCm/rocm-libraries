    def state_files(self):
        return {
            p.name: p.read_bytes()
            for p in sorted(self.store.dir.iterdir())
            if p.is_file()
        }

    def test_a_follow_up(self):
        before = self.state_files()
        code, lines = self.cli("review-prep", "7")
        self.assertEqual(code, 0, lines)
        o = self.d / "tmp/v7fu2"  # we posted twice: the second follow-up
        self.assertEqual(
            self.state_files(), before
        )  # reads only: no state, ledger or journal write
        # The files: what `rk facts` and `rk classify` print, the checks' overlap section, the PR's files.
        self.assertEqual(
            (o / "facts.txt").read_text(encoding="utf-8"),
            "\n".join(self.cli("facts", "7")[1]) + "\n",
        )
        self.assertIn(
            "first line of the comment\nsecond line\n",
            (o / "facts.txt").read_text(encoding="utf-8"),
        )
        self.assertEqual(
            (o / "classify.txt").read_text(encoding="utf-8"),
            "\n".join(self.cli("classify", "7")[1]) + "\n",
        )
        c = json.loads((o / "classify.txt").read_text(encoding="utf-8"))
        self.assertEqual(
            (c["kind"], c["changed_files"]), ("substantive", ["b.py", "new.py"])
        )
        self.assertEqual(
            (o / "overlap_section.md").read_text(encoding="utf-8"),
            bash(OVERLAP, C=str(self.checks)),
        )
        self.assertTrue(
            (o / "overlap_section.md")
            .read_text(encoding="utf-8")
            .startswith("## Overlapping work")
        )
        self.assertEqual((o / "files.txt").read_text(), "rk/a.py\nrk/b.py\nrk/new.py\n")
        # The summary, line for line.
        listing = [
            str(self.d / p)
            for p in ("probes/pr7", "tmp/v7fr", "tmp/v7fu1", "tmp/v7fu2")
        ]
        listing += [
            "2026-11-03_pr7_fu1.md",
            "2026-11-04_pr7_fu1.md",
            "2026-11-05_pr7_fu2.md",
        ]
        listing += ["PR_FIRST_ROUND_7.md", "PR_FOLLOWUP_7.md", "PR_FOLLOWUP_7_2.md"]
        commits = g(
            self.mirror,
            "log",
            "--no-merges",
            "--format=%h %s",
            self.new,
            "--not",
            self.old,
            "refs/remotes/origin/develop",
        ).splitlines()
        expected = (
            [
                f"review dir {o}",
                "facts exit 0",
                "classify exit 0",
                prep.worktree_line(o),
            ]
            + self.ledger3
            + listing
            + bash(FACT_SLICES, O=str(o)).splitlines()
            + [f"substantive {self.old[:10]} -> {self.new[:10]} 2"]
            + commits
            + bash(CHECK_SLICES, C=str(self.checks)).splitlines()
            + [f"head {self.new[:10]} mb {self.base[:10]} commits 2", "3"]
        )
        self.assertEqual(lines, expected)
        self.assertEqual(
            commits, [f"{self.new[:len(commits[0].split()[0])]} pr: b and new"]
        )
        # The slices did cut: our last review's lines at 280 characters, the reviews at 24 lines (11 of the 15 threads),
        # ABI at 6 lines, the checks' merge lines at 240 characters.
        self.assertIn("N3 " + "z" * 277, lines)
        self.assertEqual(sum(1 for x in lines if x.startswith("* rk/f")), 11)
        self.assertNotIn("abi line 4", lines)
        self.assertIn("plan: families=[" + "conv," * 44 + "conv", lines)

