class TestReviewDirs(unittest.TestCase):
    def test_every_round_s_directory_of_the_pr_and_no_other(self):
        with tempfile.TemporaryDirectory() as d:
            tmp = pathlib.Path(d) / "tmp"
            for name in (
                "v12fr",
                "v12fu1",
                "v12fu2",
                "v120fr",
                "v1fr",
                "v12x",
                "v12fr_old",
                "v12fu",
            ):
                (tmp / name).mkdir(parents=True)
            self.assertEqual(
                sorted(
                    p.name for p in prep.review_dirs({"paths": {"working_dir": d}}, 12)
                ),
                ["v12fr", "v12fu1", "v12fu2"],
            )
        self.assertEqual(prep.review_dirs({}, 12), [])  # paths.tmp is not set

    def test_every_reader_of_a_review_directory_s_name_reads_prep_s_rule(self):
        """A review directory's name has one home, prep.REVIEW_DIR: review_dirs, the RAM disk's folders of a review and
        their copy on the disk (review_keep), the session's worktree guard and the reader of a subagent's brief take
        the names it takes, a round it adds too."""
        later = re.compile(rf"v(\d+)({prep.ROUND.pattern}|rr\d+)")  # one more round
        with tempfile.TemporaryDirectory() as d:
            rd = pathlib.Path(d) / "rd"
            cfg = {
                "paths": {"working_dir": d},
                "ramdisk": {"enabled": True, "path": str(rd), "size_gb": 4},
            }
            for name in ("v12fr", "v12rr1"):
                (rd / "tmp" / name).mkdir(parents=True)
                (rd / "tmp" / name / "notes.md").write_text("notes")

            def taken():
                return (
                    [p.name for p in prep.review_dirs(cfg, 12)],
                    [p.name for p in ramdisk.pipe_folders(cfg, 12)[3:]],
                    workguard.worktree_ok(f"{rd}/tmp/v12rr1/wt_v1"),
                    orchestrator.brief_pr(f"inputs in {rd}/tmp/v12rr1/facts.txt"),
                )

            self.assertEqual(taken(), (["v12fr"], ["v12fr"], False, (None, "")))
            with mock.patch.object(prep, "REVIEW_DIR", later):
                self.assertEqual(
                    taken(),
                    (["v12fr", "v12rr1"], ["v12fr", "v12rr1"], True, (12, "rr1")),
                )
                review_keep.sync(cfg, {"review_ready": [{"pr": 12}]}, mock.Mock())
            self.assertEqual(
                sorted(p.name for p in (pathlib.Path(d) / review_keep.KEEP).iterdir()),
                ["v12fr", "v12rr1"],
            )


