    def test_the_default_round_skips_rounds_already_used(self):
        # A round already used (posted, or a review directory with notes) is never the default again.
        self.assertEqual(
            prep.default_round(self.st, 7, self.cfg), "fu2"
        )  # two posts, nothing else used
        posts = self.d / "posts"
        posts.mkdir()
        self.cfg["paths"]["posts"] = str(posts)
        for name in (
            "pr7_fu.md",
            "pr7_fu2.md",
            "pr7_fu5.md",
            "pr77_fu9.md",
            "pr7_fu_ci.md",
        ):
            (posts / name).write_text("x")
        self.assertEqual(prep.default_round(self.st, 7, self.cfg), "fu6")
        (self.d / "tmp/v7fu6").mkdir(parents=True)
        self.assertEqual(
            prep.default_round(self.st, 7, self.cfg), "fu6"
        )  # a directory without notes is no round
        (self.d / "tmp/v7fu6/notes.md").write_text("x")
        self.assertEqual(prep.default_round(self.st, 7, self.cfg), "fu7")
        with mock.patch.object(prep, "review_dirs", lambda cfg, n: []):
            self.assertEqual(
                prep.default_round(self.st, 7, self.cfg), "fu6"
            )  # the review directories are the ones review_dirs finds
        self.assertEqual(
            prep.default_round(self.st, 7), "fu2"
        )  # without the config: the count alone

