def write(root: pathlib.Path, files: dict) -> None:
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(text))


def develop_cache(path: pathlib.Path, outcomes: dict) -> None:
    """A cache of develop's outcomes at one SHA, by (entry, id relative to the CTest directory), as the monitor keeps
    it (the tool only reads it: installed_tests.load_cache)."""
    path.write_text("".join(f"{e}\t{i}\t{o}\n" for (e, i), o in outcomes.items()))


def python_dir(root: pathlib.Path) -> str:
    """A bin dir whose `python` is this interpreter (ctest resolves the entries' `python` on PATH)."""
    b = root / "pybin"
    b.mkdir(exist_ok=True)
    (b / "python").write_text(f'#!/bin/sh\nexec "{sys.executable}" "$@"\n')
    (b / "python").chmod(0o755)
    return str(b)


def env_with(root: pathlib.Path) -> dict:
    tools = [python_dir(root)] + [
        os.path.dirname(x) for x in (CMAKE, CTEST, NINJA) if x
    ]
    env = dict(os.environ, PATH=os.pathsep.join(tools + [os.environ.get("PATH", "")]))
    for name in RERUN:
        env.pop(name, None)
    return env


@unittest.skipUnless(CTEST, "ctest is not available")
class TestEntriesFromTheCMakeLists(unittest.TestCase):
    """The installed CTestTestfile, read through ctest itself: CMake's variables, lists and quoting resolved."""

    def setUp(self):
        self._d = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self._d.name)
        self.bin = self.root / "inst" / "bin"
        write(
            self.bin,
            {
                "rocke/CTestTestfile.cmake": CTEST_FILE,
                "tests/core/test_core.py": "",
                "tests/build/test_hidden.py": "",
                "tests/library/tests/test_a.py": "",
                "tests/library/tests/test_pinned.py": "",
                "tests/library/tests/dispatch/attention/test_disp.py": "",
                "tests/library/tests/dispatch/attention/test_numeric.py": "",
            },
        )
        p = subprocess.run(
            [CTEST, "--show-only=json-v1"],
            cwd=self.bin / "rocke",
            capture_output=True,
            text=True,
            env=env_with(self.root),
            timeout=60,
        )
        self.assertEqual(p.returncode, 0, p.stderr)
        self.entries = {e["name"]: e for e in it.pytest_entries(p.stdout)}

    def tearDown(self):
        self._d.cleanup()

    def test_pytest_entries_with_their_paths_options_environment_labels_and_timeout(
        self,
    ):
        e = self.entries
        self.assertEqual(
            sorted(e),
            [
                "rocke_conv_gpu_gfx950_pytest",
                "rocke_library_attention_cpu_pytest",
                "rocke_library_attention_pytest",
                "rocke_library_gpu_pytest",
                "rocke_pytest",
            ],
        )
        p = e["rocke_pytest"]
        self.assertEqual(p["paths"], ["../tests"])
        self.assertEqual(p["ignores"], [str(self.bin / "tests" / "library")])
        self.assertEqual(
            p["options"],
            [
                "--ignore",
                "../tests/library",
                "-m",
                "not integration",
                "-v",
                "-rs",
                "--timeout=60",
            ],
        )
        self.assertEqual(
            p["env"], {"PYTHONPATH": ".", "ROCKE_STORAGE_TEST": "../rocke_storage"}
        )
        self.assertEqual(
            (p["labels"], p["timeout"], p["cwd"]),
            ({"ckc", "python", "quick"}, 300.0, str(self.bin / "rocke")),
        )
        cpu = e["rocke_library_attention_cpu_pytest"]
        self.assertEqual(
            cpu["paths"],
            ["../tests/library/tests/test_a.py", "../tests/library/tests/test_gone.py"],
        )
        self.assertEqual(
            cpu["missing"], ["../tests/library/tests/test_gone.py"]
        )  # a listed file the install lacks
        self.assertEqual(cpu["env"], {"PYTHONPATH": "../tests/library"})
        conv = e[
            "rocke_conv_gpu_gfx950_pytest"
        ]  # a custom option's value is not a test path
        self.assertEqual(conv["paths"], ["../tests/library/tests/test_pinned.py"])
        self.assertEqual(
            conv["options"],
            [
                "--rocke-reference-operation",
                "conv",
                "--rocke-reference-arch",
                "gfx950",
                "-v",
                "-rs",
            ],
        )
        self.assertIn("gpu", conv["labels"])

    def test_which_entries_collect_an_installed_file(self):
        t = self.bin / "tests"

        def lanes(rel):
            return sorted(
                n for n, x in self.entries.items() if it.collects(x, str(t / rel))
            )

        self.assertEqual(lanes("core/test_core.py"), ["rocke_pytest"])
        # rocke_pytest --ignore's the library tree
