class TestRunEnv(unittest.TestCase):
    def test_through_rk_pr_run_its_file_has_the_listed_names_and_the_line_the_others_set(
        self,
    ):
        """env_data: run_env's names that worker/pr_env.py lists go to the file `rk pr-run --env` reads
        (NUL-separated); the unlisted names it sets (COLUMNS, the entry's own) come back for the command line; the ones
        it keeps as they are (HOME: a re-run's slot has its own) go to neither."""
        with tempfile.TemporaryDirectory() as d, mock.patch.dict(
            os.environ, {"HOME": "/home/rkmon", "ROCKE_LLVM_FLAVOR": "llvm22"}
        ):
            for name in ("COLUMNS", "RKMON_PYEXTRA"):
                os.environ.pop(name, None)
            path = os.path.join(d, "env_e.0")
            extra = it.env_data(
                {"env": {"ROCKE_LIBRARY_ROOT": "/inst", "CK_X": "1"}},
                "/inst/site",
                "/plugins",
                path,
            )
            data = pathlib.Path(path).read_bytes()
        self.assertEqual(extra, {"CK_X": "1", "COLUMNS": "400"})
        self.assertTrue(data.endswith(b"\0"))
        env = dict(x.split(b"=", 1) for x in data.split(b"\0") if x)
        self.assertEqual(
            (
                env[b"ROCKE_LIBRARY_ROOT"],
                env[b"PYTHONPATH"],
                env[b"CUDA_VISIBLE_DEVICES"],
            ),
            (b"/inst", b"/inst/site:/plugins", b""),
        )
        for name in (b"ROCKE_LLVM_FLAVOR", b"HOME", b"COLUMNS", b"CK_X"):
            self.assertNotIn(name, env)

    def test_the_checks_exports_are_dropped_and_the_entrys_environment_wins(self):
        """CI sets none of the checks' ROCKE_* exports, and HIP_VISIBLE_DEVICES=-1 aborts this host's HIP."""
        keep = {k: v for k, v in os.environ.items()}
        try:
            os.environ.update(
                {
                    "ROCKE_LLVM_FLAVOR": "llvm22",
                    "HIP_VISIBLE_DEVICES": "-1",
                    "PYTHONPATH": "/src",
                    "TMPDIR": "/w/x",
                }
            )
            env = it.run_env(
                {"env": {"PYTHONPATH": "/inst/tests", "ROCKE_LIBRARY_ROOT": "/inst"}},
                "/inst/site",
                "/plugins",
            )
        finally:
            os.environ.clear()
            os.environ.update(keep)
        self.assertNotIn("HIP_VISIBLE_DEVICES", env)
        self.assertEqual(
            env["CUDA_VISIBLE_DEVICES"], ""
        )  # the GPU hidden as the checks hide it (rkmon_lib/nogpu.py)
