# A stand-in for develop's in-tree runner (platform/tests/in_tree/test_in_tree_suites.py): its suite list, the names it
# leaves out, and a case per test file of each suite package, run in a child pytest. CASE_IDS names the cases.
RUNNER = """\
    import importlib.util
    import os
    import subprocess
    import sys
    from pathlib import Path

    import pytest

    _SUITES = {
        "rocke.benchmark.perf.tests": (),
    }
    _EXCLUDED_FILES = ("test_pmc.py",)


    def _package_dir(package):
        return Path(next(iter(importlib.util.find_spec(package).submodule_search_locations)))


    _CASES = sorted((package, path.relative_to(_package_dir(package)).as_posix()) for package in _SUITES
                    for path in _package_dir(package).rglob("test_*.py") if path.name not in _EXCLUDED_FILES)


    @pytest.mark.parametrize(("package", "relpath"), _CASES, ids=[CASE_IDS for p, r in _CASES])
    def test_in_tree_file(package, relpath):
        child = subprocess.run([sys.executable, "-m", "pytest", str(_package_dir(package) / relpath), "-q", "-p",
                                "no:cacheprovider", "-c", os.devnull, "--rootdir", str(_package_dir(package))],
                               capture_output=True, text=True)
        assert child.returncode == 0, child.stdout[-4000:] or child.stderr[-4000:]


    def test_the_runner_itself():
        pass
    """


def runner(ids: str = 'f"{p}:{r}"') -> str:
    return RUNNER.replace("CASE_IDS", ids)


