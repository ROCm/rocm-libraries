class InstalledTrees(unittest.TestCase):
    """A merge tree configured into build/ and a develop tree committed in a git repository, as the checks have them;
    tool() runs installed_tests.py on them."""

    merge, develop = MERGE, DEVELOP

    def setUp(self):
        self._d = tempfile.TemporaryDirectory()
        self.root = r = pathlib.Path(self._d.name)
        write(r / "merge", self.merge)
        write(r / "dev", self.develop)
        self.env = env_with(r)
        self.gen = ["-G", "Ninja"] if NINJA else []
        self.configure(r / "merge", r / "build")
        git = ["git", "-C", str(r / "dev"), "-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(["git", "init", "-q", str(r / "dev")], check=True)
        subprocess.run(git + ["add", "."], check=True)
        subprocess.run(git + ["commit", "-qm", "develop"], check=True)
        self.dev_sha = subprocess.run(
            git + ["rev-parse", "HEAD"], capture_output=True, text=True
        ).stdout.strip()
        (r / "native_ok").write_text("")

    def tearDown(self):
        self._d.cleanup()

    def configure(self, src, build):
        p = subprocess.run(
            [CMAKE, "-S", str(src), "-B", str(build)] + self.gen,
            capture_output=True,
            text=True,
            env=self.env,
            timeout=120,
        )
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)

    def tool(self, *extra, files=CHANGED, build_ok="native_ok"):
        """The merge's run, with the cache of develop's outcomes at installed_develop.tsv."""
        r = self.root
        p = subprocess.run(
            [
                sys.executable,
                "-I",
                "-B",
                str(TOOL),
                "--out",
                str(r / "out"),
                "--tree",
                str(r / "merge"),
                "--build",
                str(r / "build"),
                "--prefix",
                str(r / "inst"),
                "--build-ok",
                str(r / build_ok),
                "--dev-tree",
                str(r / "dev"),
                "--cache",
                str(r / "installed_develop.tsv"),
                "--cmake",
                CMAKE,
                "--ctest",
                CTEST,
                "--budget",
                "300",
                *extra,
                *files,
            ],
            capture_output=True,
            text=True,
            env=self.env,
            timeout=600,
        )
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        return p.stdout.splitlines()

    def develop_job(self, todo: pathlib.Path) -> tuple[list[str], pathlib.Path]:
        """The develop job for the ids of `todo`, as the checks run it: its output lines and its outcomes file."""
        r = self.root
        dev_build = f"touch {r}/dev_built && {CMAKE} -S {r}/dev -B {r}/devbuild {' '.join(self.gen)} > /dev/null"
        p = subprocess.run(
            [
                sys.executable,
                "-I",
                "-B",
                str(TOOL),
                "develop",
                *("--out", str(r / "devout"), "--todo", str(todo)),
                *("--dev-tree", str(r / "dev"), "--dev-sha", self.dev_sha),
                *("--dev-build", dev_build, "--dev-core", str(r / "devbuild")),
                *("--dev-prefix", str(r / "devinst"), "--cmake", CMAKE),
                *("--ctest", CTEST, "--budget", "300"),
            ],
            capture_output=True,
            text=True,
            env=self.env,
            timeout=600,
        )
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        return p.stdout.splitlines(), r / "devout" / it.OUTCOMES_FILE

    def rows(self, out: list[str], entry: str) -> dict[str, str]:
        """The report's line for each failing id of `entry`."""
        return {
            ln.strip().split(f" [{entry}] ")[0]: ln
            for ln in out
            if f" [{entry}] (" in ln
        }


