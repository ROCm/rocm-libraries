"""The name rkmon was run by (rkmon_lib/program.py): the file's name on the PATH, else the path as typed,
and rkmon when Python runs a module, a test or -c; a text with that name in place of {program}.

No message names the program by a literal name: what docker/rkmon and the library may print (tools/doc_lints.py's
python_texts, the texts as written) takes the name from program, or in the container from doctor.wrapper(). The scan
looks for the name before one of the program's commands (the command table's, and the ones another replaced) or before
a colon, as an error's prefix; the name of the product elsewhere ("Generated by rkmon") is no command. A line the
program writes into a file (a template's header, a comment in docker/.env) names a command as the docs do, rkmon: each
such place, and any other that keeps the literal name, says why (ALLOWED). No fix's command (checks.Command, its words
the program first) has the literal name for its program either.
"""

import ast
import pathlib
import re
import sys
import unittest
from unittest import mock

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))
sys.path.insert(0, str(ROOT / "tools"))

from doc_lints import python_texts  # noqa: E402
from rkmon_lib import program  # noqa: E402
from test_commands import COMMAND_WORDS  # noqa: E402

# The program's literal name before one of its commands, or before a colon. A path that ends in the name (./rkmon,
# docker/rkmon) is the name too; a longer word (rkmon_lib, rkmon-rkmon-1) or a field ({program}) is not.
LITERAL = re.compile(
    rf"(?<![\w.<{{/=-])(?:\./|docker/)?{re.escape(program.NAME)}"
    rf"(?: (?:{'|'.join(re.escape(w) for w in sorted(COMMAND_WORDS))})(?![\w-])|: )"
)
# The places that keep the literal name: (the file, the words kept, why). Only those words are passed over: a literal
# name elsewhere on their line is still found.
ALLOWED = (
    (
        r"rkmon_lib/deploy_tree\.py",
        r"^rocKE monitor deploy settings \(.*",
        "the deploy template's header, in your settings file",
    ),
    (
        r"rkmon_lib/deploy_plan\.py",
        r"^# .*",
        "the comment lines of docker/.env and the override file, which deliver writes",
    ),
    (
        r"rkmon_lib/gh\.py",
        r"\(rkmon login\)",
        "the list of GitHub calls (CALLS), which says where each call is made and which no command prints",
    ),
    (
        r"rkmon_lib/features\.py",
        r"rkmon rk (?:prioritize|clear N)",
        "the capabilities' descriptions (CAPABILITIES), which only the docs' generated tables show",
    ),
)


def scanned() -> list:
    """(path in the package, source) of each file the scan reads: docker/rkmon and the library's modules."""
    files = [ROOT / "docker" / "rkmon", *sorted((ROOT / "rkmon_lib").glob("*.py"))]
    return [
        (f.relative_to(ROOT).as_posix(), f.read_text(encoding="utf-8")) for f in files
    ]


def literal_names(rel: str, source: str) -> list[str]:
    """Each line of what the module REL, of SOURCE, may print that names the program literally: `file:line: text`."""
    out = []
    for t in python_texts(rel, source):
        for i, line in enumerate(t.text.split("\n")):
            rest = line
            for where, words, _why in ALLOWED:
                if re.fullmatch(where, rel):
                    rest = re.sub(words, "\0", rest)
            if LITERAL.search(rest):
                out.append(f"{rel}:{t.line + i}: {line.strip()[:110]}")
    return out


# The program's literal name as a command's first word: the name, or a path that ends in it.
NAMED = re.compile(rf"(?:\./|docker/)?{re.escape(program.NAME)}")


def literal_commands(rel: str, source: str) -> list[str]:
    """Each fix of the module REL, of SOURCE, whose command (checks.Command, written with its words) has the literal
    name for its program: `file:line: the words`."""
    out = []
    for node in ast.walk(ast.parse(source)):
        if not (isinstance(node, ast.Call) and node.args):
            continue
        called = getattr(node.func, "attr", getattr(node.func, "id", ""))
        words = node.args[0]
        if called != "Command" or not isinstance(words, (ast.Tuple, ast.List)):
            continue
        first = words.elts[0] if words.elts else None
        if isinstance(first, ast.Constant) and NAMED.fullmatch(str(first.value)):
            out.append(f"{rel}:{node.lineno}: {ast.unparse(words)}")
    return out


class TestName(unittest.TestCase):
    def test_on_the_path_its_name(self):
        with mock.patch.object(program.shutil, "which", return_value="/opt/bin/rkmon"):
            self.assertEqual(program.name("/opt/bin/rkmon"), "rkmon")

    def test_else_the_path_as_typed(self):
        with mock.patch.object(program.shutil, "which", return_value=None):
            self.assertEqual(program.name("./rkmon"), "./rkmon")
        with mock.patch.object(program.shutil, "which", return_value="/opt/bin/rkmon"):
            self.assertEqual(program.name("../docker/rkmon"), "../docker/rkmon")

    def test_python_running_a_module_a_test_or_c(self):
        for argv0 in (
            "",
            "-c",
            "-m",
            "/x/tests/test_commands.py",
            "rkmon.py",
            "python3 -m unittest",
        ):
            self.assertEqual(program.name(argv0), "rkmon", argv0)

    def test_from_the_command_line_it_was_run_by(self):
        with mock.patch.object(sys, "argv", ["./rkmon", "next"]), mock.patch.object(
            program.shutil, "which", return_value=None
        ):
            self.assertEqual(program.name(), "./rkmon")
            self.assertEqual(program.named("{program} resume"), "./rkmon resume")

    def test_run_by_another_folder_s_rkmon(self):
        """Inside run_by's block, name() is the rkmon it names, the innermost block's; None changes nothing; after the
        block, however it ends, the name is the one the command was run by again."""
        with mock.patch.object(sys, "argv", ["./rkmon", "package"]), mock.patch.object(
            program.shutil, "which", return_value=None
        ):
            with program.run_by("~/old/docker/rkmon"):
                self.assertEqual(
                    program.named("{program} confirm"), "~/old/docker/rkmon confirm"
                )
                with program.run_by("~/other/docker/rkmon"):
                    self.assertEqual(program.name(), "~/other/docker/rkmon")
                with program.run_by(None):
                    self.assertEqual(program.name(), "~/old/docker/rkmon")
                self.assertEqual(program.name(), "~/old/docker/rkmon")
                self.assertEqual(program.name("../docker/rkmon"), "../docker/rkmon")
            self.assertEqual(program.name(), "./rkmon")
            with self.assertRaises(KeyError), program.run_by("~/old/docker/rkmon"):
                raise KeyError("stopped")
            self.assertEqual(program.name(), "./rkmon")

    def test_named(self):
        with mock.patch.object(program, "name", return_value="./rkmon"):
            self.assertEqual(
                program.named("run {program} resume, then {program} status"),
                "run ./rkmon resume, then ./rkmon status",
            )
        self.assertEqual(program.named("no name here"), "no name here")


class TestNoLiteralName(unittest.TestCase):
    def test_no_message_names_the_program_literally(self):
        found = []
        for rel, source in scanned():
            found += literal_names(rel, source) + literal_commands(rel, source)
        self.assertEqual(
            found, [], "name it with {program} (program.named), or doctor.wrapper()"
        )

    def test_each_allowance_keeps_words_a_line_of_its_file_has(self):
        """An allowance whose words no line of its files has is stale, and is taken out."""
        texts = {rel: python_texts(rel, source) for rel, source in scanned()}
        for where, words, _why in ALLOWED:
            lines = [
                line
                for rel, found in texts.items()
                if re.fullmatch(where, rel)
                for t in found
                for line in t.text.split("\n")
            ]
            with self.subTest(where=where, words=words):
                self.assertTrue(any(re.search(words, line) for line in lines))

    def test_a_fix_whose_command_has_the_literal_name(self):
        for source, found in (
            (
                'Command(("rkmon", "secret", name))',
                ["x.py:1: ('rkmon', 'secret', name)"],
            ),
            ('checks.Command(["./rkmon", "login"])', ["x.py:1: ['./rkmon', 'login']"]),
            ("Command(('docker/rkmon',))", ["x.py:1: ('docker/rkmon',)"]),
            ('Command((program.name(), "secret", name))', []),
            ('Command(("rk", "doctor"))', []),
            ('Command(("docker", "compose", "ls"))', []),
            ('Command(("rkmon-rkmon-1",))', []),
            ("Command(words)", []),
            ('Edit("rkmon", "f.yaml", 1)', []),
        ):
            with self.subTest(source=source):
                self.assertEqual(literal_commands("x.py", source + "\n"), found)

    def test_what_the_scan_finds_and_what_it_passes_over(self):
        def scan(rel, text):
            return literal_names(rel, f"print({text!r})\n")

        for sample in (
            "run rkmon check --settings f.yaml",
            "then ./rkmon start",
            "docker/rkmon image load m.tgz",
            "rkmon: cannot read f.yaml",
            "rkmon first-tick --timeout-minutes 5",
            "rkmon guide",
            "the summary:\nrun rkmon next",
        ):
            with self.subTest(sample=sample):
                self.assertTrue(scan("rkmon_lib/x.py", sample))
        for fine in (
            "run {program} check --settings FILE",
            "Generated by rkmon from GitHub reads",
            'Basic realm="rkmon admin dashboard"',
            "the older layout (rkmon_settings: 1)",
            "the container rkmon-rkmon-1",
            "the rkmon_lib folder",
            "rk doctor checks it",
            "rkmon checks each one",
        ):
            with self.subTest(fine=fine):
                self.assertEqual(scan("rkmon_lib/x.py", fine), [])
        # An allowance passes over its own words in its own file, and over nothing else.
        mark = "# Written by rkmon settings from your settings file"
        self.assertEqual(scan("rkmon_lib/deploy_plan.py", mark), [])
        self.assertTrue(scan("rkmon_lib/deploy_plan.py", "(rkmon settings wrote it)"))
        self.assertTrue(scan("rkmon_lib/x.py", mark))
        self.assertEqual(scan("rkmon_lib/gh.py", "a login, made (rkmon login)"), [])
        self.assertTrue(scan("rkmon_lib/gh.py", "(rkmon login); then rkmon start"))
        # A docstring is not printed; a line is named by its line in the file.
        self.assertEqual(
            literal_names("rkmon_lib/x.py", 'def f():\n    """Run rkmon check."""\n'),
            [],
        )
        self.assertEqual(
            literal_names("rkmon_lib/x.py", 'x = 1\nprint("""a\nrun rkmon next""")\n'),
            ["rkmon_lib/x.py:3: run rkmon next"],
        )


if __name__ == "__main__":
    unittest.main()
