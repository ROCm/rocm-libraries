"""The C++20 keywords and alternative operator tokens.

The words of the standard's [lex.key] and [lex.digraph] tables. The HIP
lowering prints the names an author picks for values (kernel parameters, loop
induction variables, loop-carried values) unchanged, as C++ identifiers, so
both engines refuse such a name when it is one of these words.

This is the one list of them. ``rocke.core.ir`` reads it, and the build turns
it into the C++ engine's copy (``tools/gen_cxx_keywords_cpp.py``). The module
imports nothing, so the generator can load it by path without importing the
``rocke`` package.
"""

