"""Which build of the C++ engine this Python tree expects.

A native engine artifact (the shared ``librocke``, the portable-IR replay CLI)
stamps the build ID of the sources it was built from (``rocke_build_id()``,
generated by ``cmake/rocke_build_id.cmake``). A loader compares that stamp with
the ID this tree expects, so an engine built from other sources is refused
rather than compared with this tree's Python engine:

- in a source checkout, the ID of the sources beside this package
  (:func:`source_build_id`);
- in an installed tree, which has no engine sources, the ID the build recorded
  in a provenance manifest that ``ROCKE_PROVENANCE_MANIFEST`` names
  (:func:`provenance_manifest`);
- otherwise nothing: :func:`expected_build_id` is None and freshness cannot be
  established locally.

Standard library only: the build-time import paths load this module.
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path

from ..assets import beside_package, platform_root

__all__ = [
    "PROVENANCE_MANIFEST_ENV",
    "expected_build_id",
    "provenance_manifest",
    "source_build_id",
]

#: The environment variable naming an installed tree's provenance manifest.
PROVENANCE_MANIFEST_ENV = "ROCKE_PROVENANCE_MANIFEST"

# The source files the ID covers besides the engine's C++ sources and the
# generated tables' JSON inputs, relative to the platform root. Mirrors
# rocke_build_id_inputs in cmake/rocke_build_id.cmake.
_SOURCE_INPUTS = (
    "python/rocke/core/arch/data/arch_domain_waivers.json",
    "python/rocke/core/arch/domain.py",
    "tools/gen_arch_domain_cpp.py",
    "python/rocke/core/cxx_keywords.py",
    "tools/gen_cxx_keywords_cpp.py",
    "tests/portable_ir/replay_cli.cpp",
    "CMakeLists.txt",
    "tests/CMakeLists.txt",
    "tests/cmake/PortableIrTests.cmake",
    "cmake/rocke_build_id.cmake",
    "cmake/generate_rocke_build_id.cmake",
)


def source_build_id(root: str | os.PathLike[str] | None = None) -> str | None:
    """The CMake-compatible build ID of the engine sources under the platform
    ``root`` (default: this tree's, ``rocke.assets.platform_root()``).

    The ID covers repository-owned inputs that determine the shared engine and
    replay CLI: engine sources/headers, the library-owned C++ mirrors in
    ``../library/cpp`` when present, the CLI source, their CMake recipes, and
    the inputs of the generated arch-domain and C++ keyword tables. It is a
    source/build-recipe ID, not a compiler or binary identity. An installed
    tree carries no engine sources: None.
    """
    root = Path(root) if root is not None else platform_root()
    bindings = root / "cpp" / "bindings"
    files = list((root / "cpp").rglob("*.cpp"))
    files += list((root / "cpp").rglob("*.h"))
    files += list((root / "cpp").rglob("*.hpp"))
    files = [path for path in files if bindings not in path.parents]
    if not files:
        return None
    # Library-owned C++ mirrors beside the platform tree (rocke_build_id.cmake
    # hashes them whenever present; keep the two mirrored).
    library_cpp = root.parent / "library" / "cpp"
    if (library_cpp / "CMakeLists.txt").is_file():
        skipped = (library_cpp / "bindings", library_cpp / "tests")
        for pattern in ("*.cpp", "*.h", "*.hpp"):
            files += [
                path
                for path in library_cpp.rglob(pattern)
                if not any(part in path.parents for part in skipped)
            ]
        files.append(library_cpp / "CMakeLists.txt")
    data = root / "python" / "rocke" / "core" / "arch" / "data"
    files += list(data.glob("intrinsic_arch_domain.*.json"))
    files += [root / relative for relative in _SOURCE_INPUTS]
    lines = []
    for path in files:
        if not path.is_file():
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        relative = Path(os.path.relpath(path, root)).as_posix()
        lines.append(f"{relative}:{digest}")
    blob = "\n".join(sorted(lines)).encode()
    return hashlib.sha256(blob).hexdigest()[:16]


def provenance_manifest(
    path: str | os.PathLike[str] | None = None,
) -> tuple[str, str] | None:
    """The ``(version, build ID)`` an installed tree's build recorded: read
    from ``path``, else from the manifest ``ROCKE_PROVENANCE_MANIFEST`` names;
    None when neither names one.

    A source checkout computes its expectation directly. Relocated tests have no
    native sources, so their build installs this manifest beside the prebuilt
    replay CLI. A relative ``ROCKE_PROVENANCE_MANIFEST`` is the installed
    tree's own name for it, relative to the directory holding the ``rocke``
    package (``rocke.assets.beside_package``), not to the working directory.
    """
    if path is not None:
        manifest = Path(path)
    else:
        named = os.environ.get(PROVENANCE_MANIFEST_ENV)
        if not named:
            return None
        manifest = beside_package(named)
    if not manifest.is_file():
        raise FileNotFoundError(
            f"portable-IR provenance manifest not found at {str(manifest)!r}"
        )
    parts = manifest.read_text().strip().split()
    if len(parts) != 2:
        raise RuntimeError(
            f"invalid portable-IR provenance manifest at {str(manifest)!r}"
        )
    return parts[0], parts[1]


def expected_build_id() -> str | None:
    """The build ID an engine artifact must carry here: the sources', else the
    provenance manifest's; None when there is neither. A manifest that
    disagrees with the sources beside it is itself an error."""
    source_id = source_build_id()
    installed = provenance_manifest()
    if installed is not None and source_id is not None and installed[1] != source_id:
        raise RuntimeError(
            "portable-IR provenance manifest does not match the current source: "
            f"manifest={installed[1]}, source={source_id}"
        )
    return source_id or (installed[1] if installed is not None else None)
