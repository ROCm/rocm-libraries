# gen_arch_domain_cpp.py -- generate the C++ engine's copy of the intrinsic
# arch-domain table from the committed columns.
#
# The committed columns under python/rocke/core/arch/data/ are the one source of
# truth. The Python engine reads them at lowering time through
# rocke.core.arch.domain. The C++ engine reads no files when it lowers, so CMake
# runs this script at build time to turn the same columns into a C++ data file.
# Its output lives in the build tree and is never committed: regenerating a
# column (tools/gen_arch_domain.py) is the only step, and the next build of
# either engine sees it.
#
# Two engines interpreting one artifact can still disagree about what it says,
# so this script does not read the JSON itself. It loads domain.py -- by path,
# since that module imports only the standard library -- and asks it:
# domain.load() parses and validates each column, and domain.is_negative()
# decides which cells the C++ engine gets. Only negative cells are emitted,
# each with whether domain.waivers() exempts it, plus domain.DEFAULT_MODE. The
# C++ engine needs the answers, not the policy, so changing the policy stays a
# change to Python alone.
#
# Usage (normally run by CMake, see CMakeLists.txt):
#   python rocke/platform/tools/gen_arch_domain_cpp.py --out <file.inc>

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path
from types import ModuleType

HERE = Path(__file__).resolve().parent
DOMAIN_PY = HERE.parent / "python" / "rocke" / "core" / "arch" / "domain.py"


def load_domain(path: Path = DOMAIN_PY) -> ModuleType:
    """Import ``domain.py`` from its file, without importing the ``rocke`` package.

    The package pulls in the whole lowerer; the build only needs the reader,
    and must not depend on anything the reader does not.
    """
    spec = importlib.util.spec_from_file_location("_rocke_arch_domain", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load the arch-domain reader from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def c_string(text: str) -> str:
    """``text`` as a C string literal.

    Octal escapes rather than ``\\x``: a hex escape swallows every hex digit
    that follows it, so ``\\x41B`` would be one character, not two.
    """
    out = []
    for ch in text:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.extend(f"\\{byte:03o}" for byte in ch.encode("utf-8"))
    return '"' + "".join(out) + '"'


def negative_cells(domain: ModuleType, flavor: str) -> list:
    """Every cell of ``flavor``'s column that ``domain.is_negative`` accepts.

    Sorted by (key, arch) for the C++ binary search. That order is only the
    order ``strcmp`` uses if both fields are ASCII, so anything else is refused
    rather than emitted into a table the lookup would then search wrongly.
    """
    table = domain.load(flavor)
    if table is None:
        raise RuntimeError(f"no committed arch-domain column for {flavor}")
    cells = []
    for key in table.keys():  # noqa: SIM118 -- ArchDomain is not a mapping
        for arch in sorted(table.arches(key)):
            cell = table.lookup(key, arch)
            if cell is None or not domain.is_negative(cell.status):
                continue
            for field in (key, arch):
                if not field.isascii():
                    raise ValueError(
                        f"{flavor}: non-ASCII {field!r} would break the C++ "
                        "lookup's strcmp ordering"
                    )
            if not cell.evidence.isascii():
                # The engine cuts a message at a byte count and Python at a
                # character count; they agree only while the text is ASCII.
                raise ValueError(
                    f"{flavor}: non-ASCII evidence {cell.evidence!r} would make "
                    "the two engines cut the same refusal at different places"
                )
            waived = domain.is_waived(key, arch, flavor)
            cells.append((key, arch, cell.status, cell.evidence, waived))
    return sorted(cells)


def render(domain: ModuleType) -> str:
    """The generated C++ data file, as text."""
    flavors = domain.committed_flavors()
    lines = [
        "// GENERATED by tools/gen_arch_domain_cpp.py -- do not edit.",
        "//",
        "// The C++ engine's copy of the intrinsic arch-domain table: every cell",
        "// rocke.core.arch.domain.is_negative() calls negative, taken from the",
        (
            "// committed columns python/rocke/core/arch/data/"
            "intrinsic_arch_domain.<flavor>.json."
        ),
        "// CMake regenerates it whenever a column, the waiver list, domain.py or",
        "// the generator changes. Included only by cpp/core/arch/domain.cpp.",
        "",
        "/* domain.DEFAULT_MODE: what an unset or empty ROCKE_ARCH_DOMAIN means. */",
        f"const char* const ROCKE_ARCH_DOMAIN_DEFAULT_MODE = {c_string(domain.DEFAULT_MODE)};",
        "",
    ]
    columns = []
    for flavor in flavors:
        cells = negative_cells(domain, flavor)
        name = "ROCKE_ARCH_DOMAIN_" + "".join(
            ch.upper() if ch.isalnum() else "_" for ch in flavor
        )
        if not cells:
            # A zero-length array is ill-formed C++; an empty column is NULL.
            columns.append((flavor, "nullptr", 0))
            continue
        lines.append(
            f"/* {flavor}: {len(cells)} negative cells, sorted by (key, arch). */"
        )
        lines.append(f"const rocke_arch_domain_cell_t {name}[] = {{")
        for key, arch, status, evidence, waived in cells:
            lines.append(
                f"    {{{c_string(key)}, {c_string(arch)}, "
                f"{c_string(status)}, {c_string(evidence)}, {int(waived)}}},"
            )
        lines.append("};")
        lines.append("")
        columns.append((flavor, name, len(cells)))
    if not columns:
        raise RuntimeError("no committed arch-domain column to generate from")
    lines.append("const column_t ROCKE_ARCH_DOMAIN_COLUMNS[] = {")
    for flavor, name, count in columns:
        lines.append(f"    {{{c_string(flavor)}, {name}, {count}}},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="generate the C++ engine's arch-domain table"
    )
    ap.add_argument("--out", required=True, type=Path, help="the .inc file to write")
    args = ap.parse_args(argv)
    text = render(load_domain())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    # Always written, even when unchanged: CMake reruns this when an input is
    # newer than the output, so skipping the write would rerun it every build.
    args.out.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
