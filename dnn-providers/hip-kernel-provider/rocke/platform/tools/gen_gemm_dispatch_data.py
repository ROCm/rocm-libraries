def _kind(cls, f) -> str:
    """B / I / S / OI / OB of a dataclass field (Optional[int] / Optional[bool])."""
    hints = typing.get_type_hints(cls)
    t = hints[f.name]
    args = typing.get_args(t)
    if type(None) in args:
        inner = [a for a in args if a is not type(None)]
        if inner == [int]:
            return "OI"
        if inner == [bool]:
            return "OB"
        raise ValueError(f"{cls.__name__}.{f.name}: unsupported optional type {t}")
    if t is bool:
        return "B"
    if t is int:
        return "I"
    if t is str or typing.get_origin(t) is typing.Literal:
        return "S"
    raise ValueError(f"{cls.__name__}.{f.name}: unsupported type {t}")


def _default(kind: str, v) -> str:
    if kind in ("OI", "OB"):
        if v is not None:
            raise ValueError(f"optional field default {v!r} is not None")
        return "{}"
    if kind == "B":
        return "true" if v else "false"
    if kind == "I":
        return str(int(v))
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_fields() -> str:
    lines = _HEAD + [
        " * Generated by tools/gen_gemm_dispatch_data.py -- do not edit. The fields of the Python",
        " * TraitSpec (gemm_universal.py) and SkinnyGemmSpec (gemm_skinny.py) in dataclass order:",
        " * ROCKE_GD_TRAIT(kind, name, default) / ROCKE_GD_SKINNY(kind, name, default), kind B (bool),",
        " * I (int), S (str), OI (Optional[int]) or OB (Optional[bool]; default None = {}); then",
        " * ROCKE_GD_PYONLY(name): the levers of core.backend._PYTHON_ONLY_GEMM_LEVERS. */",
    ]
    for cls, macro in (
        (TraitSpec, "ROCKE_GD_TRAIT"),
        (SkinnyGemmSpec, "ROCKE_GD_SKINNY"),
    ):
        lines.append(f"#ifdef {macro}")
        inst = cls()
        for f in dataclasses.fields(cls):
            k = _kind(cls, f)
            lines.append(
                f"{macro}({k}, {f.name}, {_default(k, getattr(inst, f.name))})"
            )
        lines.append(f"#endif /* {macro} */")
    # the TraitSpec levers only the Python engine builds (core.backend), each off at the
    # TraitSpec default
    lines.append("#ifdef ROCKE_GD_PYONLY")
    dflt = TraitSpec()
    for name, off in _PYTHON_ONLY_GEMM_LEVERS:
        if getattr(dflt, name) != off:
            raise ValueError(
                f"python-only lever {name}: off value {off!r} is not the default"
            )
        lines.append(f"ROCKE_GD_PYONLY({name})")
    lines.append("#endif /* ROCKE_GD_PYONLY */")
    return "\n".join(lines) + "\n"


def render_tables() -> str:
    lines = _HEAD + [
        " * Generated by tools/gen_gemm_dispatch_data.py -- do not edit. The gemm_skinny configuration",
        " * tables of dispatch/gemm/skinny_table.py (SKINNY_TABLE: {dtype, M <= N, log2 bins},",
        " * {wave_m_atoms, wave_n_atoms, warp_m, warp_n, warp_k, kc, prefetch, waves_target, r}) and",
        " * dispatch/gemm/skinny_native_table.py (SKINNY_NATIVE_TABLE: {arch, layout, M <= N, ld_odd,",
        " * log2 bins}, {..., r, rx}), sorted by key. */",
        "#ifdef ROCKE_GD_SKINNY_TABLE",
    ]
    for key in sorted(SKINNY_TABLE):
        dt, mle, bs, bg, bk = key
        v = ", ".join(str(int(x)) for x in SKINNY_TABLE[key])
        lines.append(f'ROCKE_GD_SKINNY_TABLE("{dt}", {mle}, {bs}, {bg}, {bk}, {v})')
    lines.append("#endif /* ROCKE_GD_SKINNY_TABLE */")
    lines.append("#ifdef ROCKE_GD_SKINNY_NATIVE_TABLE")
    for arch in sorted(SKINNY_NATIVE_TABLE):
        table = SKINNY_NATIVE_TABLE[arch]
        for key in sorted(table):
            lay, mle, odd, bs, bg, bk = key
            v = ", ".join(str(int(x)) for x in table[key])
            lines.append(
                f'ROCKE_GD_SKINNY_NATIVE_TABLE("{arch}", "{lay}", {mle}, {int(odd)}, {bs}, '
                f"{bg}, {bk}, {v})"
            )
    lines.append("#endif /* ROCKE_GD_SKINNY_NATIVE_TABLE */")
    return "\n".join(lines) + "\n"


