def _modules() -> dict:
    import rocke.dispatch.families.tensor_gett as tg
    import rocke.dispatch.gemm.common as common
    import rocke.dispatch.gemm.skinny as skinny
    import rocke.instances.common.gemm_universal as universal
    import rocke.instances.common.tensor.gett as gett

    return {
        "common": common,
        "skinny": skinny,
        "universal": universal,
        "tg": tg,
        "gett": gett,
    }


def _const(v) -> tuple:
    """(C++ type, literal) of a Python constant (floats round-trip exactly)."""
    if isinstance(v, bool):
        return "bool", "true" if v else "false"
    if isinstance(v, int):
        return "int64_t", f"INT64_C({v})"
    if isinstance(v, float):
        r = repr(v)
        return "double", r if any(c in r for c in ".en") else r + ".0"
    raise ValueError(f"unsupported constant {v!r}")


def render_consts() -> str:
    from rocke.dispatch.gemm.selector import SELECTOR_MIN_MARGIN

    mods = _modules()

    def value(mod, expr):
        return eval(
            expr, {}, vars(mods[mod])
        )  # noqa: S307 - the fixed expressions above

    for mod, expr, want in _POLICY:
        got = value(mod, expr)
        if got != want:
            raise ValueError(
                f"{expr} = {got!r}: the C++ dispatcher / planner implements {want!r} only"
            )
    lines = _HEAD + [
        " * Generated by tools/gen_gemm_dispatch_data.py -- do not edit. ROCKE_GD_CONST(type, name,",
        " * value): the GEMM dispatcher's rule thresholds (dispatch/gemm/common.py, skinny.py) and",
        " * gemm_universal's launch limits; ROCKE_GD_MARGIN(class, value): the selector's",
        " * SELECTOR_MIN_MARGIN; ROCKE_GETT_CONST(type, name, value): the tensor GETT planner's",
        " * constants (dispatch/families/tensor_gett.py, instances/common/tensor/gett.py). */",
        "#ifdef ROCKE_GD_CONST",
    ]
    for name, mod, expr in _GD_CONSTS:
        t, lit = _const(value(mod, expr))
        lines.append(f"ROCKE_GD_CONST({t}, {name}, {lit})")
    lines.append("#endif /* ROCKE_GD_CONST */")
    lines.append("#ifdef ROCKE_GD_MARGIN")
    for cls in sorted(SELECTOR_MIN_MARGIN):
        _, lit = _const(float(SELECTOR_MIN_MARGIN[cls]))
        lines.append(f'ROCKE_GD_MARGIN("{cls}", {lit})')
    lines.append("#endif /* ROCKE_GD_MARGIN */")
    lines.append("#ifdef ROCKE_GETT_CONST")
    for name, mod, expr in _GETT_CONSTS:
        t, lit = _const(value(mod, expr))
        lines.append(f"ROCKE_GETT_CONST({t}, {name}, {lit})")
    lines.append("#endif /* ROCKE_GETT_CONST */")
    return "\n".join(lines) + "\n"


def main() -> int:
    outs = (
        (FIELDS, render_fields()),
        (TABLES, render_tables()),
        (CONSTS, render_consts()),
    )
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        rc = 0
        for path, text in outs:
            cur = path.read_text(encoding="utf-8") if path.exists() else ""
            if cur.replace("\r\n", "\n") != text:
                sys.stderr.write(
                    f"{path} is stale: regenerate it with {Path(__file__).name}\n"
                )
                rc = 1
        return rc
    for path, text in outs:
        path.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
