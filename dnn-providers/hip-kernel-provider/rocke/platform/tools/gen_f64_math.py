"""Generate the C++ mirror of the f64 math expansions.

``python/rocke/core/f64_math.py`` is the single source of the f64
``exp``/``exp2``/``log``/``log2``/``tanh``/``sqrt``/``rsqrt`` instruction
programs. The C++ LLVM lowerer walks the same programs from
``cpp/core/lower_llvm/f64_math_programs.inc``, which this tool writes, so both
engines print byte-identical IR by construction.

Usage:
  python rocke/platform/tools/gen_f64_math.py           # rewrite the .inc
  python rocke/platform/tools/gen_f64_math.py --check   # exit 1 if stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLATFORM = HERE.parent
OUT = PLATFORM / "cpp" / "core" / "lower_llvm" / "f64_math_programs.inc"
sys.path.insert(0, str(PLATFORM / "python"))

from rocke.core.f64_math import PROGRAMS  # noqa: E402 -- path bootstrap above


def _c_string(text: str) -> str:
    if '"' in text or "\\" in text:
        raise ValueError(f"unexpected quote or backslash in {text!r}")
    return f'"{text}"'


def render() -> str:
    lines = [
        "/* Copyright (c) Advanced Micro Devices, Inc., or its affiliates.",
        " * SPDX-License-Identifier: MIT */",
        "/* GENERATED by platform/tools/gen_f64_math.py from",
        " * python/rocke/core/f64_math.py -- do not hand-edit. Regenerate after",
        " * changing a program; tests/core/test_f64_math.py checks it is current.",
        " * Included by lower_llvm/arith.cpp, which defines the two row types. */",
        "",
        "// clang-format off",
    ]
    table = []
    for op_name, prog in PROGRAMS.items():
        ident = prog.name.replace(".", "_")
        keys = ", ".join(_c_string(k) for k in prog.keys)
        lines.append(
            f"static const char* const k_f64_math_keys_{ident}[] = {{{keys}}};"
        )
        lines.append(
            f"static const rocke_f64_math_step_t k_f64_math_steps_{ident}[] = {{"
        )
        for step in prog.steps:
            args = list(step.args) + [0] * (3 - len(step.args))
            lines.append(
                f"    {{{_c_string(step.hint)}, {_c_string(step.text)}, "
                f"{len(step.args)}, {{{args[0]}, {args[1]}, {args[2]}}}}},"
            )
        lines.append("};")
        table.append(
            f"    {{{_c_string(op_name)}, k_f64_math_keys_{ident}, {len(prog.keys)}, "
            f"k_f64_math_steps_{ident}, {len(prog.steps)}}},"
        )
    lines.append("static const rocke_f64_math_program_t k_f64_math_programs[] = {")
    lines.extend(table)
    lines.append("};")
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def current_text() -> str | None:
    """The committed .inc with normalised line endings (None if absent)."""
    if not OUT.exists():
        return None
    return OUT.read_bytes().decode().replace("\r\n", "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the .inc is stale")
    args = ap.parse_args()
    text = render()
    current = current_text()
    if args.check:
        if current != text:
            print(f"STALE: {OUT} (run tools/gen_f64_math.py)")
            return 1
        print(f"ok: {OUT}")
        return 0
    if current != text:
        # Text mode: the platform's native line endings, like an edited file.
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT}")
    else:
        print(f"unchanged: {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
