"""Print (or check) cpp/instances/common/gemm_traitspec_fields.inc: every field of the Python
TraitSpec (gemm_universal) with its default as the JSON text json.dumps writes.

The C++ tensor GETT spec hashes ``dataclasses.asdict(TensorGettSpec)`` into its kernel names
(``TensorGettSpec.kernel_name``), which serializes every TraitSpec field of an MN body's trait;
the C++ engine mirrors only part of the fields, the others are at their defaults (the C++ engine
refuses the Python-engine-only levers). The table keeps the two engines' kernel names equal.

  python tools/gen_traitspec_fields.py > cpp/instances/common/gemm_traitspec_fields.inc
  python tools/gen_traitspec_fields.py --check   # exit 1 when the committed table is stale
"""

import dataclasses
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "python"))

from rocke.instances.common.gemm_universal import TraitSpec  # noqa: E402

OUT = HERE.parent / "cpp" / "instances" / "common" / "gemm_traitspec_fields.inc"


def render() -> str:
    lines = [
        "/* Copyright (c) Advanced Micro Devices, Inc., or its affiliates.",
        " * SPDX-License-Identifier: MIT",
        " *",
        " * Generated by tools/gen_traitspec_fields.py -- do not edit. Every field of the",
        " * Python TraitSpec (gemm_universal.py) and its default as json.dumps text. */",
    ]
    t = TraitSpec()
    for f in dataclasses.fields(TraitSpec):
        v = json.dumps(getattr(t, f.name))
        lines.append(f'{{"{f.name}", {json.dumps(v)}}},')
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur.replace("\r\n", "\n") != text:
            sys.stderr.write(
                f"{OUT} is stale: regenerate it with {Path(__file__).name}\n"
            )
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
