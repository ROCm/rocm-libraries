# gen_cxx_keywords_cpp.py -- generate the C++ engine's copy of the C++ keyword
# list that both engines refuse as value names.
#
# python/rocke/core/cxx_keywords.py is the one list. The Python engine imports
# it; the C++ engine reads no files when it builds a kernel, so CMake runs this
# script at build time to turn the same list into a C++ data file. Its output
# lives in the build tree and is never committed.
#
# The output is the body of a C array of string literals, one per line, sorted:
#   static const char* const kCxxKeywords[] = {
#   #include "rocke/cxx_keywords.inc"
#   };
#
# Usage (normally run by CMake, see CMakeLists.txt):
#   python rocke/platform/tools/gen_cxx_keywords_cpp.py --out <file.inc>

from __future__ import annotations

import argparse
import importlib.util
import sys
from collections.abc import Iterable
from pathlib import Path
from types import ModuleType

HERE = Path(__file__).resolve().parent
KEYWORDS_PY = HERE.parent / "python" / "rocke" / "core" / "cxx_keywords.py"


def load_keywords(path: Path = KEYWORDS_PY) -> ModuleType:
    """Import ``cxx_keywords.py`` from its file, without importing the ``rocke``
    package: the build needs the list, not the lowerer the package pulls in."""
    spec = importlib.util.spec_from_file_location("_rocke_cxx_keywords", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load the C++ keyword list from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def render(keywords: Iterable[str]) -> str:
    """The generated C++ data file for ``keywords``, as text. Raises
    ``ValueError`` for a word that is not an identifier: a keyword always is,
    and only an identifier can be written as a literal without escapes."""
    words = sorted(set(keywords))
    for word in words:
        if not (word.isascii() and word.isidentifier()):
            raise ValueError(
                f"C++ keyword {word!r} is not an identifier; fix "
                "python/rocke/core/cxx_keywords.py"
            )
    lines = [
        "// GENERATED by tools/gen_cxx_keywords_cpp.py -- do not edit.",
        "//",
        "// The C++20 keywords and alternative operator tokens, from",
        "// python/rocke/core/cxx_keywords.py: the body of a C array of string",
        "// literals. CMake regenerates it whenever that list or the generator",
        "// changes.",
        *(f'"{word}",' for word in words),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="generate the C++ engine's C++ keyword table"
    )
    ap.add_argument("--out", required=True, type=Path, help="the .inc file to write")
    args = ap.parse_args(argv)
    text = render(load_keywords().CXX_KEYWORDS)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    # Always written, even when unchanged: CMake reruns this when an input is
    # newer than the output, so skipping the write would rerun it every build.
    args.out.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
