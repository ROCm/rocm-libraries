/*
 * tests/instances/test_attention_dense_spec.cpp -- C parity for the shared
 * dense attention spec contract (rocke/instance_attention_dense_spec.h).
 *
 * The validator and preflight reasons, block orders and kernel names never all
 * reach the emitted IR, so the byte-identity gate cannot see a C/Python
 * divergence in them. Both engines are pinned to one file instead:
 * platform/tests/golden/attention_dense_spec_vectors.json, embedded into this
 * binary at build time (attention_dense_spec_vectors.inc, generated by
 * tests/CMakeLists.txt). The Python side,
 * library/tests/test_attention_dense_spec_vectors.py, recomputes every case with
 * the current Python and owns regenerating the file; this test requires the same
 * answers from the C++ port. A Python change therefore fails there first, and the
 * regenerated file then fails here until the C++ port is updated to match.
 *
 * "cases" run with the base hooks: hand-picked cases, then a seeded slice drawn
 * around the auto block-order thresholds. "hook_tables" hold one table per
 * shipped subclass (gfx950, gfx942): its per-class answers go through the traits
 * struct, and each case's recorded name parts and lookahead through the
 * name-parts struct and the lookahead argument, with a preflight validator
 * context that is never the spec. A null reason (the interpreter-specific
 * ZeroDivisionError paths) compares only the verdict.
 */
