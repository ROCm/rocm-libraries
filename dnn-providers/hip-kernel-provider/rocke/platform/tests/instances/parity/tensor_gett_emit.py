def _tuned(key):
    from rocke.dispatch.families.tensor_gett import (
        TensorGettRequest,
        _tuned_plan,
        tensor_gett_route_key,
        tuned_entry_problem,
    )
    from rocke.instances.common.tensor.gett import GettKnobs, TensorGettSpec

    p = tuned_entry_problem(ARCH, key)
    if p is None:
        sys.stderr.write(f"no tuned entry {key}\n")
        sys.exit(1)
    prob = TensorGettSpec.make(
        p["modes_a"],
        p["modes_b"],
        p["modes_d"],
        p["extents"],
        dtype=p["dtype"],
        knobs=GettKnobs(bilinear=p["bilinear"]),
    )
    req = TensorGettRequest(problem=prob, arch=ARCH)
    if tensor_gett_route_key(req) != key:
        sys.stderr.write("route key mismatch\n")
        sys.exit(1)
    pl = _tuned_plan(req)
    if pl is None or pl.packs:
        sys.stderr.write("no single-launch tuned plan\n")
        sys.exit(1)
    return pl.gett.spec


def _explicit(d):
    from rocke.dispatch.gemm.selector import parse_config
    from rocke.instances.common.gemm_universal import TileSpec, TraitSpec
    from rocke.instances.common.tensor.gett import GettKnobs, TensorGettSpec

    kw = dict(d["body"])
    if d["mn"]:
        tl, tr = parse_config(d["mn"])
        kw["mn_tile"] = TileSpec(**tl)
        kw["mn_trait"] = TraitSpec(**tr)
    st = d["strides"]
    return TensorGettSpec.make(
        d["modes_a"],
        d["modes_b"],
        d["modes_d"],
        d["extents"],
        strides_a=st.get("a"),
        strides_b=st.get("b"),
        strides_d=st.get("d"),
        dtype=d["dtype"],
        knobs=GettKnobs(**d["knobs"]),
        **kw,
    )


def _spec(idx: int):
    from rocke.instances.common.tensor.gett import is_valid_spec

    if not 0 <= idx < len(ROWS):
        raise SystemExit(f"unknown config index {idx}")
    d = ROWS[idx]
    spec = _tuned(d["key"]) if d["kind"] == "tuned" else _explicit(d)
    ok, why = is_valid_spec(spec, arch=ARCH)
    if not ok:
        sys.stderr.write(f"invalid spec: {why}\n")
        sys.exit(1)
    return spec, ARCH


def _build(spec, arch):
    from rocke.instances.common.tensor.gett import build_tensor_gett

    return build_tensor_gett(spec, arch=arch)


def main() -> int:
    return run_emit(_spec, _build, usage="usage: tensor_gett_emit.py <config_index>\n")


if __name__ == "__main__":
    sys.exit(main())
