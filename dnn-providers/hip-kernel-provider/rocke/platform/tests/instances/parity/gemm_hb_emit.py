def _spec(idx: int):
    from rocke.dispatch.gemm.selector import parse_config
    from rocke.instances.common.gemm_universal import (
        DataSpec,
        TileSpec,
        TraitSpec,
        UniversalGemmSpec,
        is_valid_spec,
    )

    if not 0 <= idx < len(ROWS):
        raise SystemExit(f"unknown config index {idx}")
    name, cfg, lay, dt = ROWS[idx]
    tl, tr = parse_config(cfg)
    spec = UniversalGemmSpec(
        name=name,
        tile=TileSpec(**tl),
        trait=TraitSpec(**tr),
        data=DataSpec(dtype_a=dt, dtype_b=dt, dtype_c=dt, layout=lay),
    )
    ok, why = is_valid_spec(spec, arch=ARCH)
    if not ok:
        sys.stderr.write(f"invalid spec: {why}\n")
        sys.exit(1)
    return spec, ARCH


def _build(spec, arch):
    from rocke.instances.common.gemm_universal import build_universal_gemm

    return build_universal_gemm(spec, arch)


def main() -> int:
    return run_emit(_spec, _build, usage="usage: gemm_hb_emit.py <config_index>\n")


if __name__ == "__main__":
    sys.exit(main())
