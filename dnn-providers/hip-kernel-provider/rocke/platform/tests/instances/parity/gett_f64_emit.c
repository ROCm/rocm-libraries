static rocke_gett_digits_t dig1(long long e, long long s)
{
    rocke_gett_digits_t d;
    memset(&d, 0, sizeof d);
    d.n = 1;
    d.extent[0] = e;
    d.stride[0] = s;
    rocke_gett_digits_norm(&d);
    return d;
}

static rocke_gett_digits_t dig2(long long e0, long long s0, long long e1, long long s1)
{
    rocke_gett_digits_t d;
    memset(&d, 0, sizeof d);
    d.n = 2;
    d.extent[0] = e0;
    d.stride[0] = s0;
    d.extent[1] = e1;
    d.stride[1] = s1;
    rocke_gett_digits_norm(&d);
    return d;
}

