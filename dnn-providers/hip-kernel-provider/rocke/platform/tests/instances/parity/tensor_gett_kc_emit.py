def _spec(idx: int):
    from rocke.dispatch.gemm.selector import parse_config
    from rocke.instances.common.gemm_universal import TileSpec, TraitSpec
    from rocke.instances.common.tensor.gett import (
        GettKnobs,
        TensorGettSpec,
        is_valid_spec,
    )

    if not 0 <= idx < len(ROWS):
        raise SystemExit(f"unknown config index {idx}")
    r = ROWS[idx]
    tl, tr = parse_config(r["body"])
    kw = dict(kc_tile=TileSpec(**tl), kc_trait=TraitSpec(**tr), tile_k=r["tile_k"])
    if r["mn"]:
        tl2, tr2 = parse_config(r["mn"])
        kw.update(mn_tile=TileSpec(**tl2), mn_trait=TraitSpec(**tr2))
    spec = TensorGettSpec.make(
        r["a"],
        r["b"],
        r["d"],
        r["ext"],
        strides_d=r["strides_d"],
        dtype=r["dtype"],
        knobs=GettKnobs(**r["knobs"]),
        **kw,
    )
    ok, why = is_valid_spec(spec, arch=ARCH)
    if not ok:
        sys.stderr.write(f"invalid spec: {why}\n")
        sys.exit(1)
    return spec, ARCH


