def _spec(idx: int):
    if not 0 <= idx < len(ROWS):
        raise SystemExit(f"unknown config index {idx}")
    cls, geom = ROWS[idx]
    spec = RgettSpec(**cls)
    return (spec, None if geom is None else dict(zip(geometry_names(), geom))), "gfx950"


def _build(sg, arch=None):
    spec, geom = sg
    return build_rgett(spec.with_geom(geom), arch=arch)


def main() -> int:
    return run_emit(
        _spec, _build, usage="usage: hiptensor_aot_rgett_emit.py <config_index>\n"
    )


