"""Write (or check) platform/cpp/instances/common/hiptensor_aot_ewp_table.inc, the C++ engine's
copy of the tuned tiled elementwise route table (kernels.common.hiptensor_aot.ewp_host): per
target the classes of the kernel pack in choice order (``pack_classes``) and the routes of the
tuned problems (``routes``).

Usage:
    gen_ewp_table.py           write the file
    gen_ewp_table.py --check   exit 1 when the file differs from what this script writes
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROCKE = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(
    ROCKE, "platform", "cpp", "instances", "common", "hiptensor_aot_ewp_table.inc"
)


def _str(v):
    if v is None:
        return "nullptr"
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    sys.path.insert(0, os.path.join(ROCKE, "library"))
    sys.path.insert(0, os.path.join(ROCKE, "platform", "python"))
    from kernels.common.hiptensor_aot import ewp_host

    lines = [
        "/* Copyright (c) Advanced Micro Devices, Inc., or its affiliates.",
        " * SPDX-License-Identifier: MIT",
        " *",
        " * Generated by library/builders/hiptensor/gen_ewp_table.py from",
        " * kernels.common.hiptensor_aot.ewp_host -- do not edit. ROCKE_EWP_CLASS(arch, arity, a,",
        " * b, c, d, kinds, mode, to, tt, tw, block, nt, swz, swsh, walk, tpc, ilp, vb, rag, tb): the",
        " * classes of the target's kernel pack in choice order; ROCKE_EWP_ROUTE(arch, name, value):",
        " * the routes of its tuned problems. */",
        "#ifdef ROCKE_EWP_CLASS",
    ]
    for arch in ewp_host.ARCHES:
        for s in ewp_host.pack_classes(arch):
            f = [
                _str(arch),
                str(s.arity),
                _str(s.a),
                _str(s.b),
                _str(s.c),
                _str(s.d),
                _str(s.kinds),
                _str(s.mode),
                str(s.to),
                str(s.tt),
                str(s.tw),
                str(s.block),
                str(s.nt),
                str(s.swz),
                str(s.swsh),
                _str(s.walk),
                str(s.tpc),
                str(s.ilp),
                str(s.vb),
                str(s.rag),
                str(s.tb),
            ]
            lines.append("ROCKE_EWP_CLASS(" + ", ".join(f) + ")")
    lines += ["#endif", "#ifdef ROCKE_EWP_ROUTE"]
    for arch in ewp_host.ARCHES:
        for k, v in sorted(ewp_host.routes(arch).items()):
            lines.append(f"ROCKE_EWP_ROUTE({_str(arch)}, {_str(k)}, {_str(v)})")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur.replace("\r\n", "\n") != text:
            print(f"{OUT} is stale: run gen_ewp_table.py", file=sys.stderr)
            return 1
        print("ewp table OK")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
