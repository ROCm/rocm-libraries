"""The gfx11-generic SDPA backward verdict table (``tests/data/sdpa_bwd_gfx11_verdicts.csv``).

The table is generated by ``tools/sdpa_bwd_verdicts.py`` from the RDNA bundle's routing and the matcher's rule
documentation, never from engine code. These tests pin the table against the vendored routing entries
(``sdpa_bwd_gfx11_selection.csv``, the bundle's ``selection.json``) with a classification of the rows that does not
call the generator's expectation logic, and against the installed gfx11-generic content. Host-only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

FLYDSL = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FLYDSL / "tools"))
import sdpa_bwd_verdicts as sv  # noqa: E402

# The H1 table contract (Plans/sdpa-bwd-gfx11-testing.md), in order.
CONTRACT_COLUMNS = [
    "id", "source", "dtype", "dqk", "dv", "mask", "window_left", "window_right", "dropout", "bias", "dbias", "varlen",
    "hq", "hk", "b", "sq", "sk", "stride_qk", "stride_v", "seed_form", "verdict", "prep", "dkdv", "dq", "reduce", "rule",
    "basis",
]  # fmt: skip
LADDER = (
    16,
    32,
    48,
    64,
    80,
    96,
    128,
    160,
    192,
    224,
    256,
)  # the bundle contract's 11 rungs


@pytest.fixture(scope="module")
def rows():
    return sv.read_csv()


@pytest.fixture(scope="module")
def entries():
    return sv.load_selection()


@pytest.fixture(scope="module")
def installed():
    return sv.in_tree_hashes()


def rung_of(d):
    return next(r for r in LADDER if r >= d)


def served(rows):
    return [r for r in rows if r["verdict"] == "served"]


def klass(r):
    if r["bias"] != "none":
        return "bias"
    windowed = r["window_left"] != -1 or r["window_right"] != -1
    return "causal" if r["mask"] != "none" or windowed else "plain"


def test_header_is_the_contract():
    first = (sv.VERDICTS_CSV).read_text().splitlines()[0]
    assert first.split(",") == CONTRACT_COLUMNS
    assert list(sv.COLUMNS) == CONTRACT_COLUMNS


def test_csv_equals_regeneration():
    assert sv.VERDICTS_CSV.read_text() == sv.render(sv.generate())
    assert sv.main(["--check"]) == 0


def test_ids_unique_and_sources_known(rows):
    assert len({r["id"] for r in rows}) == len(rows)
    assert {r["source"] for r in rows} == {
        "selection",
        "boundary",
        "refusal",
        "layout",
        "bias",
        "unmodelled",
    }
    assert {r["verdict"] for r in rows} == {"served", "declined"}


def test_every_selection_entry_is_reproduced(rows, entries):
    """Each of the bundle's 666 entries: a graph that takes its `exact: false` row and one that takes its default row,
    both carrying the routed hash in the entry's slot."""
    assert len(entries) == 666
    hit = {}
    for r in served(rows):
        tile = rung_of(max(r["dqk"], r["dv"]))
        exact = r["dqk"] == r["dv"] == tile
        cls, drop = klass(r), r["dropout"]
        store_db = ("requested" if r["dbias"] else "null") if cls == "bias" else ""
        for kernel in ("prep", "dkdv", "dq"):
            slot_tile = (
                rung_of(r["dv"]) if kernel == "prep" else tile
            )  # contract: prep's tile is the rung >= Dv
            slot_exact = r["dqk"] == r["dv"] == slot_tile
            key = (
                kernel,
                r["dtype"],
                slot_tile,
                cls,
                drop,
                store_db if kernel == "dq" else "",
            )
            hit.setdefault((key, slot_exact), set()).add(r[kernel])
        if r["reduce"]:
            hit.setdefault(
                (("dbias_reduce", r["dtype"], 0, "bias", drop, ""), exact), set()
            ).add(r["reduce"])
    missing = []
    for key, (padded_hash, default_hash) in entries.items():
        if padded_hash not in hit.get((key, False), ()):
            missing.append((key, "exact:false", padded_hash))
        if default_hash not in hit.get((key, True), ()):
            missing.append((key, "default", default_hash))
    assert not missing, missing[:5]
    # one hash per entry row set: a graph never gets two objects for one slot
    for (key, exact), hashes in hit.items():
        assert hashes == {entries[key][0 if not exact else 1]}, (key, exact, hashes)


def test_every_refusal_code_appears_or_is_not_a_graph(rows):
    in_basis = {
        code
        for code in sv.REASONS
        if any(f"check_request:{code}" in r["basis"] for r in rows)
    }
    assert set(sv.REASONS) - in_basis == set(sv.NOT_A_ROW)
    for code in in_basis:
        assert all(
            r["verdict"] == "declined"
            for r in rows
            if f"check_request:{code}" in r["basis"]
        )


def test_declined_rows_name_a_rule_or_the_bundle(rows):
    for r in rows:
        if r["verdict"] == "declined":
            assert not any(r[c] for c in sv.SLOT_COLUMNS), r["id"]
            assert r["rule"] in sv.RULE_CAUSE or (
                r["rule"] == sv.NO_ROW and "check_request:hd_gt_256" in r["basis"]
            ), r["id"]
        else:
            assert r["rule"] == "" and r["prep"] and r["dkdv"] and r["dq"], r["id"]
            assert r["basis"].startswith("selection:"), r["id"]
    used = {r["rule"] for r in rows if r["rule"] not in ("", sv.NO_ROW)}
    assert used == set(sv.RULE_CAUSE)
    assert any(
        r["rule"] == sv.NO_ROW for r in rows
    )  # every documented decline rule has a row


def test_reduce_only_for_broadcast_dbias(rows):
    for r in served(rows):
        broadcast = r["dbias"] and (
            (r["bias"] in ("b", "bh") and r["b"] > 1)
            or (r["bias"] in ("h", "bh") and r["hq"] > 1)
        )
        assert bool(r["reduce"]) == bool(broadcast), r["id"]


def test_axes_are_covered(rows):
    by_id = {r["id"]: r for r in rows}
    dims = {(r["dqk"], r["dv"]) for r in rows}
    for rung in LADDER:
        assert (rung, rung) in dims and (rung + 1, rung + 1) in dims
    assert {(1, 1), (255, 255), (256, 256), (257, 257)} <= dims
    assert any(a != b and max(a, b) <= 256 for a, b in dims) and any(
        a != b and max(a, b) > 256 for a, b in dims
    )
    assert {r["bias"] for r in rows} == {"none", "full", "b", "h", "bh", "q"}
    assert {(r["bias"], r["dbias"]) for r in rows if r["bias"] == "q"} == {
        ("q", 0),
        ("q", 1),
    }
    assert {r["mask"] for r in rows} == {"none", "causal_tl", "causal_br"}
    assert {r["varlen"] for r in rows} == {"none", "padded", "packed"}
    assert {r["seed_form"] for r in rows if r["dropout"]} == {"host", "device"}
    assert {r["dtype"] for r in rows} == {"f16", "bf16", "fp32"}
    # layout: pad8 stride serves an odd D, a tight stride does not
    assert (
        by_id["lay-f16-d20-pad8"]["verdict"] == "served"
        and by_id["lay-f16-d20-tight"]["verdict"] == "declined"
    )
    assert {r["rule"] for r in rows if r["source"] == "layout" and r["rule"]} == {
        "DT-8",
        "DT-9",
        "LY-3",
        "LY-6",
    }


def test_hashes_resolve_to_installed_objects(rows, entries, installed):
    content = sv.CONTENT
    files = {}
    for op, slot in (
        ("sdpa_bwd_prep", "prep"),
        ("sdpa_bwd_dkdv", "dkdv"),
        ("sdpa_bwd_dq", "dq"),
    ):
        manifest = json.loads(
            (content / op / "gfx11-generic" / "manifest.json").read_text()
        )
        files[slot] = {
            i["spec_hash"]: content / op / "gfx11-generic" / i["file"]
            for i in manifest["instances"]
        }
        if slot == "dq":
            files["reduce"] = {
                c["hash"]: content / op / "gfx11-generic" / c["file"]
                for c in manifest["companions"]
            }
    for r in rows:
        for slot in sv.SLOT_COLUMNS:
            if r[slot]:
                assert r[slot] in files[slot], (r["id"], slot, r[slot])
                assert files[slot][r[slot]].is_file()
    for (kernel, *_), hashes in entries.items():
        slot = "reduce" if kernel == "dbias_reduce" else kernel
        assert set(hashes) <= set(files[slot])
    assert set(installed) == set(files)
