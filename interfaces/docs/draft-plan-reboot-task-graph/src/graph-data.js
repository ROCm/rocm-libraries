let nextTestNumber=1;
const node = (id, label, type, phase, status, summary, details, exit, pr = null, tests = []) => {
  const items=tests.map((test) => {
    if (test.itemId) return {...test,outcome:test.outcome ?? testOutcomeByCategory[test.category]};
    const testId=test.testId ?? `test-${nextTestNumber}`;
    const number=Number.parseInt(testId.replace('test-',''),10);
    nextTestNumber=Number.isFinite(number) ? Math.max(nextTestNumber,number+1) : nextTestNumber+1;
    return {...test,testId,itemId:testId,outcome:test.outcome ?? testOutcomeByCategory[test.category]};
  });
  return {
    id,
    label,
    type,
    phase,
    status,
    summary,
    details,
    exit:exit.map((item,index) => typeof item === 'string'
      ? {doneId:`${id}-d${String(index+1).padStart(2,'0')}`,text:item,testIds:[],specifications:[]}
      : {doneId:item.doneId ?? `${id}-d${String(index+1).padStart(2,'0')}`,text:item.text,testIds:item.testIds ?? [],specifications:item.specifications ?? []}),
    pr,
    specifications:taskSpecifications[id] ?? [],
    tests:items,
  };
};

