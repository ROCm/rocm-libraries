/*
 * ===========================================================================
 *    unmtr_hb2st is not intended for inclusion in the public API.
 *    It is used as a step in eigenvalue solvers (heev*).
 * ===========================================================================
 */

//------------------------------------------------------------------------------
// The unmtr_hb2st functions multiply a unitary matrix Q, as generated by hb2st,
// with a general m-by-n matrix C.
//
// The matrix Q is applied in one of the following forms, depending on the
// values of ``side`` and ``trans``:
//
//      C := Q C    no transpose from the left,
//      C := Q^H C  conjugate-transpose from the left,
//      C := C Q    no transpose from the right, and
//      C := C Q^H  conjugate-transpose from the right.
//
// The order q of the unitary matrix Q is q = ``m`` if applying from the left,
// or q = ``n`` if applying from the right. The matrix Aband that was input to
// hb2st is therefore q-by-q.
//
//  handle      rocblas_handle.
//  side        Specifies on which side to apply Q or Q^H.
//  trans       Specifies whether the matrix Q or Q^H is to be applied.
//  m           Number of rows of matrix C. m >= 0.
//  n           Number of columns of matrix C. n >= 0.
//  kd          Bandwidth of matrix A, as given to hb2st. kd >= 1.
//  V           Array of Householder vectors, as generated by hb2st;
//              see hb2st for dimensions.
//  ldv         Leading dimension of V. ldv >= 2*kd - 1.
//  tau         Vector of Householder tau factors, as generated by hb2st;
//              see hb2st for dimensions.
//  C           On input, the matrix C. On output, it is overwritten
//              with Q C, Q^H C, C Q, or C Q^H.
//  ldc         Leading dimension of C. ldc >= m.
//
template <typename T, typename I = rocblas_int, bool COMPLEX = rocblas_is_complex<T>>
rocblas_status rocsolver_ormtr_unmtr_hb2st_impl(rocblas_handle handle,
                                                const rocblas_side side,
                                                const rocblas_operation trans,
                                                const I m,
                                                const I n,
                                                const I kd,
                                                T* V,
                                                const I ldv,
                                                T* tau,
                                                T* C,
                                                const I ldc)
try
{
    const char* name = (!rocblas_is_complex<T> ? "ormtr_sb2st" : "unmtr_hb2st");
    ROCSOLVER_ENTER_TOP(name, "--side", side, "--trans", trans, "-m", m, "-n", n, "--kd", kd,
                        "--ldv", ldv, "--ldc", ldc);

    if(!handle)
        return rocblas_status_invalid_handle;

    // argument checking
    rocblas_status st = rocsolver_ormtr_unmtr_hb2st_argCheck<COMPLEX, T*, T*, I>(
        handle, side, trans, m, n, kd, V, ldv, tau, C, ldc);
    if(st != rocblas_status_continue)
        return st;

    // working with unshifted arrays
    I shiftV = 0;
    I shiftC = 0;

    // normal (non-batched non-strided) execution
    rocblas_stride strideV = 0;
    rocblas_stride strideTau = 0;
    rocblas_stride strideC = 0;
    I batch_count = 1;
    I max_parallel = 1;

    // memory workspace sizes:
    size_t size_scalars;
    size_t size_Tr, size_W, size_Z;
    size_t size_work, size_workArr;
    rocsolver_ormtr_unmtr_hb2st_getMemorySize<false, T, I>(
        side, trans, m, n, kd, batch_count, &max_parallel, &size_scalars, &size_Tr, &size_W,
        &size_Z, &size_work, &size_workArr);

    if(rocblas_is_device_memory_size_query(handle))
    {
        return rocblas_set_optimal_device_memory_size(handle, size_scalars, size_Tr, size_W, size_Z,
                                                      size_work, size_workArr);
    }

    // memory workspace allocation
    rocblas_device_malloc mem(handle, size_scalars, size_Tr, size_W, size_Z, size_work, size_workArr);
    if(!mem)
        return rocblas_status_memory_error;

    T* scalars = (T*)mem[0];
    T* Tr = (T*)mem[1];
    T* W = (T*)mem[2];
    T* Z = (T*)mem[3];
    T* work = (T*)mem[4];
    T** workArr = (T**)mem[5];
    if(size_scalars > 0)
        init_scalars(handle, scalars);

    // execution
    return rocsolver_ormtr_unmtr_hb2st_template<false, false, T, T*, I>(
        handle, side, trans, m, n, kd, V, shiftV, ldv, strideV, tau, strideTau, C, shiftC, ldc,
        strideC, batch_count, max_parallel, scalars, Tr, W, Z, work, workArr);
}
catch(...)
{
    return exception2rocblas_status();
}

