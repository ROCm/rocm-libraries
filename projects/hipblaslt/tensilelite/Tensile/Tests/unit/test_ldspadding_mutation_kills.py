# --- survivors of get_fp32_mt_config ---
class TestGetFp32MtConfigXf32EmuPack:
    """Pin get_fp32_mt_config for FP32/XF32 ds_load_b32.

    All three surviving mutants only alter the xf32EmuPack value that is
    forwarded into _compute_fp32_config (default False->True; value->None;
    argument omitted->callee default False). These tests characterize the
    real outputs and, in test_..._invariant_to_xf32EmuPack, pin the observed
    fact that xf32EmuPack has no effect on the returned config: the emulation
    pack changes the ds_load_b32 instruction offsets fed to the bank-conflict
    solver, but the minimal (perBlock, pad) it selects is identical for
    True/False/None/omitted across the whole realistic input domain. This is
    why the three mutants are observationally equivalent through this public
    selector (see dispositions).
    """

    # (mt, vw, lrvw, wg, mipt, wt) -> (perBlock, pad), values derived from
    # the current unmutated _compute_fp32_config logic.
    _CASES = [
        (64, 4, 1, 2, 4, 4, 256, 1),
        (128, 2, 1, 1, 4, 2, 512, 1),
        (256, 4, 2, 2, 8, 4, 1024, 1),
        (96, 2, 1, 1, 4, 2, 0, 0),
        (512, 4, 4, 2, 8, 4, 0, 0),
    ]

    @pytest.mark.parametrize(
        "mt,vw,lrvw,wg,mipt,wt,exp_perBlock,exp_pad",
        _CASES,
        ids=[f"mt{c[0]}_vw{c[1]}_lrvw{c[2]}_wg{c[3]}_ipt{c[4]}_wt{c[5]}"
             for c in _CASES],
    )
    def test_get_fp32_mt_config_values(self, mt, vw, lrvw, wg, mipt, wt,
                                       exp_perBlock, exp_pad):
        assert L.get_fp32_mt_config(mt, "perBlock", vw, lrvw, wg, mipt, wt) == exp_perBlock
        assert L.get_fp32_mt_config(mt, "pad", vw, lrvw, wg, mipt, wt) == exp_pad

    @pytest.mark.parametrize(
        "mt,vw,lrvw,wg,mipt,wt,exp_perBlock,exp_pad",
        _CASES,
        ids=[f"mt{c[0]}_vw{c[1]}_lrvw{c[2]}_wg{c[3]}_ipt{c[4]}_wt{c[5]}"
             for c in _CASES],
    )
    def test_get_fp32_mt_config_invariant_to_xf32EmuPack(
        self, mt, vw, lrvw, wg, mipt, wt, exp_perBlock, exp_pad
    ):
        for key, expected in (("perBlock", exp_perBlock), ("pad", exp_pad)):
            omitted = L.get_fp32_mt_config(mt, key, vw, lrvw, wg, mipt, wt)
            false_ = L.get_fp32_mt_config(mt, key, vw, lrvw, wg, mipt, wt, xf32EmuPack=False)
            true_ = L.get_fp32_mt_config(mt, key, vw, lrvw, wg, mipt, wt, xf32EmuPack=True)
            none_ = L.get_fp32_mt_config(mt, key, vw, lrvw, wg, mipt, wt, xf32EmuPack=None)
            assert omitted == expected
            assert false_ == expected
            assert true_ == expected
            assert none_ == expected
