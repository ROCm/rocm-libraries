# --- survivors of b128_check ---
class Test_b128_check_survivors:
    """White-box kills for `_b128_check` mutation survivors (slice 6b).

    `_b128_check(half, B, P, wOffsets, instOffs)` returns True iff, for every
    (wOff, instOff) combination, the padded per-thread b128 addresses are all
    16-byte aligned and every thread's 4 consecutive banks are collectively
    distinct (16 threads * 4 banks == 64 distinct banks). All expected values
    were verified against the unmutated source.
    """

    # A canonical conflict-free layout: 16 threads at 16*k give quad bases
    # 4k (k=0..15), covering all 64 banks with no conflict -> True.
    CF16 = [16 * k for k in range(16)]

    @pytest.mark.parametrize(
        "half,B,P,wOffsets,instOffs,expected",
        [
            # base True case: kills %->/ , %16->%17, ==0->==1, >>2 sign/shift,
            # range(4)->range(5), bk=None, in->not in, return True->False
            (CF16, 0, 0, (0,), (0,), True),
            # a>>2 >= 64 forces the %64 wrap that (a>>2)/64 (mutmut_19) drops:
            # thread bases collide under % but not under / -> orig False.
            ([0, 1024], 0, 0, (0,), (0,), False),
            # empty instOffs: original falls back to (0,) (aligned -> True);
            # mutmut_5 falls back to (1,) which misaligns every address.
            (CF16, 0, 0, (0,), (), True),
            # instOff=256 pushes a>>2 into the wrap range so base%64 vs base%65
            # (mutmut_22) diverge, while the layout stays conflict-free -> True.
            (CF16, 0, 0, (0,), (256,), True),
            # addresses all == 4 (mod 16); instOff=12 aligns them (a+io True),
            # mutmut_8 computes a-io == 8 (mod 16) -> misaligned -> False.
            ([4, 68, 132, 196], 0, 0, (0,), (12,), True),
            # same asymmetry via wOff: a+wOff aligned; mutmut_9 uses a-wOff.
            ([4, 68, 132, 196], 0, 0, (12,), (0,), True),
            # B=16,P=16 pad shifts addresses to distinct quads (True); the
            # mutmut_1 minus-sign pad collapses both to 0 -> bank conflict.
            ([192, 208], 16, 16, (0,), (0,), True),
        ],
        ids=[
            "cf16_true", "wrap_conflict_false", "empty_instoffs_true",
            "instoff256_true", "instoff_align_asym", "woff_align_asym",
            "pad_sign_true",
        ],
    )
    def test_b128_check_behavior(self, half, B, P, wOffsets, instOffs, expected):
        assert L._b128_check(half, B, P, wOffsets, instOffs) is expected

    def test_b128_check_range5_extra_bank_conflicts(self):
        # Guards mutmut_24 (range(4)->range(5)): the conflict-free CF16 layout
        # tiles all 64 banks exactly; a 5th bank per thread must collide.
        assert L._b128_check(self.CF16, 0, 0, (0,), (0,)) is True

    def test_b128_check_return_true_not_false(self):
        # Guards mutmut_32 (final `return True`->`return False`): a fully
        # conflict-free, aligned layout must return True.
        assert L._b128_check(self.CF16, 0, 0, (0,), (0,)) is True


