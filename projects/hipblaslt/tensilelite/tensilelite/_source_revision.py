"""Find the rocm-libraries commit a TensileLite tree was built from.

The commit pairs the ``tensilelite`` package with a ``tensilelite-client``
built from the same source. ``setup.py`` loads this file by path, so it must
use only the standard library and must not import the rest of the package.

The value is the full ``git rev-parse HEAD`` of the containing repository. A
repository with uncommitted changes anywhere gets ``<sha>.dirty.<digest>``,
where the digest fingerprints tracked changes and nonignored untracked
metadata, so repeated ``setup.py`` runs on an unchanged tree agree. Tracked
contents are streamed; untracked contents are never read. Their sorted records
contain the Git-relative path, file type, size and integer ``st_mtime_ns`` from
``lstat()`` (no symlink traversal). Python supplies this integer on Linux and
Windows; its units do not guarantee the filesystem's timestamp precision.
Untracked files with the same path, type, size and observed timestamp can collide,
and copied dirty checkouts can differ. This is a build-pairing fingerprint, not
a cryptographic attestation of every source byte.

Lookup order, for the project root that holds ``setup.py``:

1. An unpacked sdist (``PKG-INFO`` at the root) uses only the value saved in
   ``tensilelite/_build_info.py`` when the sdist was made.
2. Git, if ``setup.py`` is tracked by the repository that contains the root.
   A copy of the tree placed inside some other checkout gets no value.
3. ``TENSILELITE_SOURCE_REVISION``, for builds of a tree without git.
4. Nothing: the build has no revision, and its version carries no label.

``TENSILELITE_SOURCE_REVISION`` never overrides a value from steps 1 or 2. If it
names a different commit, the build fails.
"""

from __future__ import annotations

import ast
import hashlib
import os
from pathlib import Path
import re
import stat
import subprocess
from typing import Mapping, Optional

ENV_VAR = "TENSILELITE_SOURCE_REVISION"
BUILD_INFO_RELPATH = Path("tensilelite") / "_build_info.py"

_COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
_REVISION_RE = re.compile(r"^(?P<commit>[0-9a-f]{40})(?:\.dirty\.(?P<digest>[0-9a-f]{12}))?$")
_BUILD_INFO_TEMPLATE = '''\
# Generated by TensileLite's setup.py. Do not edit; it is not tracked.

SOURCE_REVISION = {revision!r}
'''


class SourceRevisionError(RuntimeError):
    """The source revision cannot be determined consistently."""


def parse_revision(value: str) -> str:
    """Return ``value`` if it is a valid revision, otherwise raise."""
    if not _REVISION_RE.fullmatch(value):
        raise SourceRevisionError(
            f"{ENV_VAR} must be a 40-character lowercase git commit, optionally "
            f"followed by '.dirty.<12 hex digits>'; got {value!r}"
        )
    return value


def commit_of(revision: str) -> str:
    """Return the commit part of a revision, without any dirty suffix."""
    return parse_revision(revision)[:40]


def is_dirty(revision: str) -> bool:
    return parse_revision(revision) != revision[:40]


def version_label(revision: Optional[str]) -> Optional[str]:
    """Return the PEP 440 local label for ``revision``: ``g<sha>[.dirty]``.

    The digest is left out on purpose. PEP 440 strips leading zeros from
    all-digit segments, and the label only needs to say the tree was dirty.
    """
    if revision is None:
        return None
    label = f"g{commit_of(revision)}"
    return f"{label}.dirty" if is_dirty(revision) else label


def render_build_info(revision: Optional[str]) -> str:
    return _BUILD_INFO_TEMPLATE.format(revision=revision)


def read_build_info(path: Path) -> Optional[str]:
    """Read ``SOURCE_REVISION`` from a generated ``_build_info.py`` without importing it."""
    tree = ast.parse(Path(path).read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "SOURCE_REVISION"
        ):
            value = ast.literal_eval(node.value)
            if value is None:
                return None
            if not isinstance(value, str):
                break
            return parse_revision(value)
    raise SourceRevisionError(f"{path} does not define SOURCE_REVISION")


def _git(root: Path, *args: str, text: bool = True):
    # Copied packages can live inside repositories we do not own. Ownership
    # checks bypass safe.directory, but must not execute their fsmonitor hooks.
    # Empty disables the hook on old Git too; those versions treat "false" as
    # a hook pathname. This is not a general sandbox for untrusted Git config.
    return subprocess.run(
        ["git", "-c", "safe.directory=*", "-c", "core.fsmonitor=", "-C", str(root), *args],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=text,
        check=False,
    )


def _dirty_digest(toplevel: Path) -> Optional[str]:
    """Hash the repository's uncommitted changes, or return None if there are none.

    The scope is the whole repository, the same scope as the commit it
    qualifies: the client and hipBLASLt sources paired with this package live
    outside TensileLite's directory.
    """
    # Raw, NUL-delimited records are independent of patch presentation. Disable
    # user helpers and renames so each record has exactly one repository path.
    # Porcelain diff refreshes the index: touching tracked files is not a change.
    diff = _git(toplevel, "diff", "--raw", "-z", "--no-abbrev", "--no-renames",
                "--no-ext-diff", "--no-textconv", "--ignore-submodules=none", "HEAD", "--", text=False)
    if diff.returncode != 0:
        raise SourceRevisionError(f"'git diff' failed in {toplevel}")
    untracked = _git(toplevel, "ls-files", "-z", "--others", "--exclude-standard", text=False)
    if untracked.returncode != 0:
        raise SourceRevisionError(f"'git ls-files' failed in {toplevel}")
    paths = sorted(p for p in untracked.stdout.split(b"\0") if p)
    if not diff.stdout and not paths:
        return None

    digest = hashlib.sha256()

    def record(*fields: bytes):
        # Length prefixes prevent paths or binary contents from aliasing records.
        for field in fields:
            digest.update(len(field).to_bytes(8, "big"))
            digest.update(field)

    tokens = diff.stdout.split(b"\0")
    for header, rel in sorted(zip(tokens[0:-1:2], tokens[1:-1:2]), key=lambda item: item[1]):
        old_mode, new_mode, old_object, new_object, status = header[1:].split()
        record(b"tracked", rel, old_mode, new_mode, old_object, status)
        if new_mode == b"000000":
            continue
        path = toplevel / os.fsdecode(rel)
        if new_mode == b"160000":
            # A gitlink records the nested checkout's commit and dirty state,
            # not the directory timestamp. Include changes within it as well.
            nested = _git(path, "rev-parse", "--show-toplevel")
            if nested.returncode == 0 and Path(nested.stdout.strip()).resolve() == path.resolve():
                head = _git(path, "rev-parse", "HEAD")
                if head.returncode != 0:
                    raise SourceRevisionError(f"cannot read gitlink HEAD in {path}")
                record(head.stdout.strip().encode("ascii"), (_dirty_digest(path) or "").encode("ascii"))
            else:
                # An uninitialized gitlink has only its index object ID. Do not
                # accidentally recurse into the parent repository through it.
                record(new_object)
        elif new_mode == b"120000":
            record(os.fsencode(os.readlink(path)))
        else:
            content = hashlib.sha256()
            with path.open("rb") as stream:
                for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                    content.update(chunk)
            record(content.digest())
    for rel in paths:
        path = toplevel / os.fsdecode(rel)
        metadata = path.lstat()
        record(b"untracked", rel, str(stat.S_IFMT(metadata.st_mode)).encode("ascii"),
               str(metadata.st_size).encode("ascii"), str(metadata.st_mtime_ns).encode("ascii"))
    return digest.hexdigest()[:12]


def from_git(root: Path) -> Optional[str]:
    """Return the revision of ``root`` from git, or None if git does not own it."""
    root = Path(root)
    try:
        owned = _git(root, "ls-files", "--error-unmatch", "setup.py")
    except OSError:
        return None
    if owned.returncode != 0:
        return None
    head = _git(root, "rev-parse", "HEAD")
    commit = head.stdout.strip() if head.returncode == 0 else ""
    if not _COMMIT_RE.fullmatch(commit):
        return None
    toplevel = _git(root, "rev-parse", "--show-toplevel")
    if toplevel.returncode != 0 or not toplevel.stdout.strip():
        raise SourceRevisionError(f"'git rev-parse --show-toplevel' failed in {root}")
    digest = _dirty_digest(Path(toplevel.stdout.strip()))
    return commit if digest is None else f"{commit}.dirty.{digest}"


def resolve(root: Path, environ: Optional[Mapping[str, str]] = None) -> Optional[str]:
    """Return the source revision for the project rooted at ``root``."""
    root = Path(root)
    environ = os.environ if environ is None else environ
    explicit = environ.get(ENV_VAR) or None
    if explicit is not None:
        explicit = parse_revision(explicit)

    if (root / "PKG-INFO").is_file():
        build_info = root / BUILD_INFO_RELPATH
        saved = read_build_info(build_info) if build_info.is_file() else None
        if explicit is not None and (saved is None or commit_of(explicit) != commit_of(saved)):
            raise SourceRevisionError(
                f"{ENV_VAR}={explicit} does not match the revision this sdist was "
                f"made from ({saved})"
            )
        return saved

    found = from_git(root)
    if found is None:
        return explicit
    if explicit is not None and commit_of(explicit) != commit_of(found):
        raise SourceRevisionError(
            f"{ENV_VAR}={explicit} names a different commit than git in {root} ({found})"
        )
    return found


def distribution_version(component_version: str, revision: Optional[str]) -> str:
    """Return the version for a build that makes no ROCm claim."""
    label = version_label(revision)
    return component_version if label is None else f"{component_version}+{label}"
