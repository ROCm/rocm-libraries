"""Writes the logic file that makes the skinny MXFP8 GEMM kernels hipBLASLt solutions.

The file holds the pool of SkinnyGEMM knob sets, each in both useBeta variants and
each a custom kernel solution with a generator block, so that TensileCreateLibrary emits and links them like
any other solution. A Range library lists solutions through its rows only, so
the file has two kinds of rows:

  * routing rows, read from a rows file, that send a range of problems to one
    knob set, always its useBeta=false variant (the benched grid cells);
  * one enumeration-only row per pool entry, with an empty range that no
    problem matches: the default heuristic never picks it, but the enumeration
    of all solutions (hipblaslt-bench --requested_solution -1, tuning) lists it.

Routing targets the useBeta=false variant only, whose AssertBetaZero predicate
rejects beta != 0. A Range table returns on the first row whose range matches, so
a rejected solution yields no solution, and ExactLogicLibrary falls through to the
next library (Origami). The useBeta=true variants are reachable only through the
enumeration and explicit selection.

The header, including the ProblemType, is copied from the Origami logic of the
same problem type, so the file matches the same library placeholder.

Run from the repository (the pool is derived from the pickConfig defaults of
the NumPy harness, which is loaded read-only):

    cd projects/hipblaslt/tensilelite && \
        python -m tensilelite.KernelGenerators.SkinnyGEMMLogic [--rows ROWS.yaml] [--output PATH] [--list]

The rows default to data/SkinnyGEMMRows.yaml, which SkinnyGEMMTune.py writes (see the
README of this directory), so the plain command reproduces the committed logic file;
an empty rows file gives the pool only. A rows file is a YAML list; one row routes a
range of problems (batch fixed to 1, -1 is an unbounded upper end) to one knob set, without useBeta:

    - range: [m_lo, m_hi, n_lo, n_hi, 1, 1, k_lo, k_hi]
      params: {bm: 1, tn: 1, lanesK: 16, waves: 1, prefetch: 1, upIters: 0, partialSteps: 1, group: 1, numXcds: 1, grid3d: true}
"""

import argparse
import importlib.util
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from . import SkinnyGEMM

_PROBLEM_FILE = "gfx950_Cijk_Alik_Bljk_F8BS_MXAE8B32_MXBE8B32_BH_Bias_HA_S_SAB_SAV_UserArgs"
_HIPBLASLT_DIR = Path(__file__).resolve().parents[3]
_TENSILELITE_DIR = Path(__file__).resolve().parents[2]

LOGIC_DIR = _HIPBLASLT_DIR / "library/src/amd_detail/rocblaslt/src/Tensile/Logic/asm_full/gfx950/gfx950"
ORIGAMI_LOGIC = LOGIC_DIR / "Origami" / f"{_PROBLEM_FILE}.yaml"
DEFAULT_ROWS = Path(__file__).resolve().parent / "data" / "SkinnyGEMMRows.yaml"
OUTPUT_LOGIC = LOGIC_DIR / "Range" / f"{_PROBLEM_FILE}_SkinnyGEMM.yaml"
SUPPORT_MODULE = _TENSILELITE_DIR / "tests/tensilelite/bindings/skinny_gemm_support.py"

HEADER_KEYS = ("MinimumRequiredVersion", "ScheduleName", "ArchitectureName", "CUCount", "DeviceNames", "ProblemType")
GENERATED_NOTE = "# Generated by tensilelite/tensilelite/KernelGenerators/SkinnyGEMMLogic.py; do not edit by hand."

# Lower bound 1 above upper bound 0: no problem matches, but the row lists its solution.
EMPTY_RANGE = [1, 0, 1, 0, 1, 0, 1, 0]
MAX_KNOB_SETS = 100
# Every knob set is in the pool with and without useBeta.
MAX_POOL = 2 * MAX_KNOB_SETS
MAX_REASON_SHAPES = 3

# The four knob sets of the vLLM baseline table: (lanesK, waves, prefetch, upIters).
BASELINE_PARAMS = tuple((1, 1, lanesK, waves, prefetch, upIters, 0, 1, 1, True, False)
                        for lanesK, waves, prefetch, upIters in ((64, 4, 2, 2), (16, 1, 1, 0), (16, 1, 2, 5), (16, 4, 3, 5)))

RING_LANES_K = (8, 16, 64)
RING_WAVES = (1, 2, 4)
RING_PREFETCH = (1, 2, 3)
WIDE_TILE_WAVES = (1, 4)
WIDE_TILE_PREFETCH = (1, 2)
UP_FRONT_WAVES = (1, 4)
UP_FRONT_PREFETCH = (1, 2, 3)

# Largest skinny extent of the neighbouring shapes that are measured.
_MAX_SKINNY = 16

Knobs = Tuple[Any, ...]
Pool = Dict[Knobs, List[str]]
RoutingRow = Tuple[List[int], int]

_BM, _TN, _LANES_K, _WAVES, _PREFETCH, _UP_ITERS, _PARTIAL_STEPS, _GROUP, _NUM_XCDS, _GRID3D, _USE_BETA = range(11)


def asParams(knobs: Knobs) -> Dict[str, Any]:
    return dict(zip(SkinnyGEMM.PARAMETERS, knobs))


def to_knobs(params: Dict[str, Any]) -> Knobs:
    return tuple(params[key] for key in SkinnyGEMM.PARAMETERS)


@lru_cache(maxsize=None)
def _support():
    spec = importlib.util.spec_from_file_location("skinny_gemm_support", SUPPORT_MODULE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def measuredShapes() -> List[Tuple[int, int, int]]:
    """The shapes the pool is built for: the benched targets, their transposes and the skinny neighbours."""
    support = _support()
    shapes = [support.PRIMARY_SHAPE] + list(support.VLLM_SHAPES)
    shapes += [(n, m, k) for m, n, k in shapes]
    for _, wide, k in support.VLLM_SHAPES:
        for skinny in range(1, _MAX_SKINNY + 1):
            shapes += [(wide, skinny, k), (skinny, wide, k)]
    return list(dict.fromkeys(shapes))


def pickedKnobs(m: int, n: int, k: int) -> Knobs:
    problem = _support().noKnobProblem(m, n, k)
    return (problem.bm, problem.tn, problem.lanes_k, problem.waves, problem.pf, problem.up_iters,
            problem.partial_steps, problem.group, problem.xcds, problem.grid3d, False)


def _pickedByShape() -> Dict[Knobs, List[Tuple[int, int, int]]]:
    picked: Dict[Knobs, List[Tuple[int, int, int]]] = {}
    for shape in measuredShapes():
        picked.setdefault(pickedKnobs(*shape), []).append(shape)
    return picked


def _pickReason(shapes: Sequence[Tuple[int, int, int]]) -> str:
    names = [f"{m}x{n}x{k}" for m, n, k in shapes[:MAX_REASON_SHAPES]]
    more = len(shapes) - len(names)
    return "pickConfig: " + ", ".join(names) + (f" (+{more} more)" if more > 0 else "")


def _ringTwin(knobs: Knobs) -> Knobs:
    twin = list(knobs)
    twin[_UP_ITERS] = 0
    twin[_PARTIAL_STEPS] = 1
    return tuple(twin)


def _singleColumn(tn: int, lanesK: int, waves: int, prefetch: int, upIters: int = 0, partialSteps: int = 1) -> Knobs:
    return (1, tn, lanesK, waves, prefetch, upIters, partialSteps, 1, 1, True, False)


def _ringNeighbourhood() -> List[Knobs]:
    return [_singleColumn(1, lanesK, waves, prefetch)
            for lanesK in RING_LANES_K for waves in RING_WAVES for prefetch in RING_PREFETCH]


def _wideTile() -> List[Knobs]:
    return [_singleColumn(2, 16, waves, prefetch) for waves in WIDE_TILE_WAVES for prefetch in WIDE_TILE_PREFETCH]


def _upFrontNeighbourhood(picked: Sequence[Knobs]) -> List[Knobs]:
    entries = []
    for knobs in picked:
        if knobs[_BM] != 1 or knobs[_UP_ITERS] == 0:
            continue
        for waves in UP_FRONT_WAVES:
            for prefetch in UP_FRONT_PREFETCH:
                if prefetch > knobs[_UP_ITERS]:
                    continue
                entry = list(knobs)
                entry[_WAVES] = waves
                entry[_PREFETCH] = prefetch
                entries.append(tuple(entry))
    return entries


def withBeta(knobs: Knobs, useBeta: bool) -> Knobs:
    return knobs[:_USE_BETA] + (useBeta,)


def usesBeta(knobs: Knobs) -> bool:
    return knobs[_USE_BETA]


def buildPool() -> Pool:
    """Maps every knob set of the pool, in both useBeta variants, to the reasons it is there.

    The pool is sorted, so the useBeta=false variant precedes the useBeta=true one of the same knob set.
    """
    picked = _pickedByShape()
    pool: Pool = {}

    def add(knobs: Knobs, reason: str) -> None:
        reasons = pool.setdefault(knobs, [])
        if reason not in reasons:
            reasons.append(reason)

    for knobs, shapes in picked.items():
        add(knobs, _pickReason(shapes))
    for knobs in BASELINE_PARAMS:
        add(knobs, "vLLM baseline")
    for knobs in list(pool):
        add(_ringTwin(knobs), "ring twin")
    for knobs in _ringNeighbourhood():
        add(knobs, "ring neighbourhood")
    for knobs in _wideTile():
        add(knobs, "ring neighbourhood (tn 2)")
    for knobs in _upFrontNeighbourhood(list(picked)):
        add(knobs, "up-front neighbourhood")
    assert len(pool) <= MAX_KNOB_SETS, f"the pool has {len(pool)} knob sets, the limit is {MAX_KNOB_SETS}"
    pool.update({withBeta(knobs, True): list(reasons) for knobs, reasons in pool.items()})
    for knobs in pool:
        SkinnyGEMM.validateParams(asParams(knobs))
    assert len(pool) <= MAX_POOL, f"the pool has {len(pool)} entries, the limit is {MAX_POOL}"
    return dict(sorted(pool.items()))


def kernelStep(knobs: Knobs) -> int:
    return 64 * knobs[_LANES_K]


def kCoverage(knobs: Knobs) -> str:
    """The K values the entry serves; mirrors SkinnyGEMM._asserts."""
    step = kernelStep(knobs)
    upIters = knobs[_UP_ITERS]
    window = "(0, 2^20]" if upIters == 0 else f"({(upIters - 1) * step}, {upIters * step}]"
    return window + (f", K % {step} == 0" if knobs[_PARTIAL_STEPS] == 0 else "")


def _checkRowKey(index: int, key: Any) -> List[int]:
    label = f"routing row {index}"
    if not isinstance(key, list) or len(key) != 8 or not all(isinstance(v, int) and not isinstance(v, bool) for v in key):
        raise ValueError(f"{label} range must be a list of 8 ints, got {key!r}")
    if key[4:6] != [1, 1]:
        raise ValueError(f"{label} batch bounds must be exactly 1 and 1, got {key[4:6]}")
    for lower, upper in zip(key[0::2], key[1::2]):
        if lower < 1:
            raise ValueError(f"{label} lower bounds must be at least 1, got {key}")
        if upper != -1 and upper < lower:
            raise ValueError(f"{label} has an upper bound below its lower bound: {key}")
    return list(key)


def _routingParams(index: int, params: Any) -> Any:
    """The generator params of a routing row, which names the knobs only: it always routes to useBeta=false."""
    if not isinstance(params, dict):
        return params
    if "useBeta" in params:
        raise ValueError(f"routing row {index} must not set useBeta: routing always targets the useBeta=false variant")
    return {**params, "useBeta": False}


def readRoutingRows(path: Path, pool: Pool) -> List[RoutingRow]:
    """Reads a rows file into (range key, solution index) pairs, in file order."""
    import yaml

    with open(path, encoding="utf-8") as stream:
        rows = yaml.safe_load(stream) or []
    indexOf = {knobs: index for index, knobs in enumerate(pool)}
    routing = []
    for number, row in enumerate(rows):
        if not isinstance(row, dict) or set(row) != {"range", "params"}:
            raise ValueError(f"routing row {number} must have exactly the keys range and params")
        key = _checkRowKey(number, row["range"])
        knobs = to_knobs(SkinnyGEMM.validateParams(_routingParams(number, row["params"])))
        if knobs not in indexOf:
            raise ValueError(f"routing row {number} names a knob set that is not in the pool: {row['params']}")
        routing.append((key, indexOf[knobs]))
    return routing


def headerLines(path: Path) -> List[str]:
    """The lines of the top-level header keys of a logic file, copied verbatim."""
    lines = []
    seen = set()
    keep = False
    with open(path, encoding="utf-8") as stream:
        for line in stream:
            if line[:1].isalpha():
                key = line.split(":", 1)[0]
                keep = key in HEADER_KEYS
                seen.add(key)
            if keep:
                lines.append(line.rstrip("\n"))
    missing = [key for key in HEADER_KEYS if key not in seen]
    if missing:
        raise ValueError(f"{path} is missing the header keys {', '.join(missing)}")
    return lines


def flow_list(values: Sequence[Any]) -> str:
    return "[" + ", ".join(str(value) for value in values) + "]"


def _renderFlowMap(params: Dict[str, Any]) -> str:
    items = (f"{key}: {str(value).lower() if isinstance(value, bool) else value}" for key, value in params.items())
    return "{" + ", ".join(items) + "}"


def render_params(knobs: Knobs) -> str:
    return _renderFlowMap(asParams(knobs))


def render_routing_params(knobs: Knobs) -> str:
    """The params of a routing row, which has no useBeta key."""
    params = asParams(knobs)
    del params["useBeta"]
    return _renderFlowMap(params)


def _renderSolution(index: int, knobs: Knobs) -> List[str]:
    return [f"- SolutionIndex: {index}",
            "  CustomKernel:",
            "    generator: SkinnyGEMM",
            f"    generatorParams: {render_params(knobs)}"]


def _renderRow(key: Sequence[int], index: int) -> List[str]:
    return [f"- - {flow_list(key)}", f"  - [{index}, 0.0]"]


def renderLogic(header: Sequence[str], pool: Pool, routingRows: Sequence[RoutingRow]) -> str:
    lines = ["# Copyright Advanced Micro Devices, Inc., or its affiliates.",
             "# SPDX-License-Identifier: MIT",
             GENERATED_NOTE]
    lines += header
    lines.append("Solutions:")
    for index, knobs in enumerate(pool):
        lines += _renderSolution(index, knobs)
    lines += [f"IndexOrder: {flow_list(range(8))}", "ExactLogic:"]
    for key, index in routingRows:
        lines += _renderRow(key, index)
    for index in range(len(pool)):
        lines += _renderRow(EMPTY_RANGE, index)
    lines += ["RangeLogic: null", "TileSelectionIndices: null", "PerfMetric: DeviceEfficiency", "LibraryType: Range"]
    return "\n".join(lines) + "\n"


def renderTable(pool: Pool) -> str:
    columns = " | ".join(("bm", "tn", "lanesK", "waves", "prefetch", "upIters", "partialSteps", "group", "numXcds", "grid3d", "useBeta"))
    lines = [f"| index | {columns} | KI | K coverage | reasons |",
             "|" + "---|" * (len(SkinnyGEMM.PARAMETERS) + 4)]
    for index, (knobs, reasons) in enumerate(pool.items()):
        values = " | ".join(str(value).lower() if isinstance(value, bool) else str(value) for value in knobs)
        lines.append(f"| {index} | {values} | {kernelStep(knobs)} | {kCoverage(knobs)} | {'; '.join(reasons)} |")
    return "\n".join(lines) + "\n"


def _parseArgs(argv: Optional[Sequence[str]]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Write the skinny MXFP8 GEMM logic file.")
    parser.add_argument("--origami", type=Path, default=ORIGAMI_LOGIC, help="Origami logic that provides the header")
    parser.add_argument("--output", type=Path, default=OUTPUT_LOGIC, help="logic file to write")
    parser.add_argument("--rows", type=Path, default=DEFAULT_ROWS, help="YAML file of routing rows")
    parser.add_argument("--list", action="store_true", help="print the pool as a Markdown table and exit")
    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> None:
    args = _parseArgs(argv)
    pool = buildPool()
    if args.list:
        print(renderTable(pool), end="")
        return
    routingRows = readRoutingRows(args.rows, pool)
    text = renderLogic(headerLines(args.origami), pool, routingRows)
    args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
