"""Rows file, report tables and the post-rebuild validation of the skinny GEMM routing."""

import csv
import io
import math
import random
import statistics
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from . import SkinnyGEMMLogic
from .SkinnyGEMMBench import Knobs, Point, RunRecord, SolutionTable
from .SkinnyGEMMCells import (HeldOutResult, Measurements, Route, Thresholds, find_route, in_noise_band, routes_from,
                              vote)

LICENSE_LINES = ("# Copyright Advanced Micro Devices, Inc., or its affiliates.", "# SPDX-License-Identifier: MIT")
VALIDATE_ROUTED_CAP = 200
VALIDATE_UNROUTED = 50

Table = Tuple[List[str], List[List[Any]]]


# ---------------------------------------------------------------------------
# The rows file.


def describe_rows(grid_name: str, limits: Thresholds) -> str:
    return (f"# Generated by SkinnyGEMMTune.py from {grid_name} (margin {limits.margin}, tolerance "
            f"{limits.tolerance}, regression {limits.regression}); do not edit by hand.")


def render_rows(routes: Sequence[Route], description: str) -> str:
    lines = [*LICENSE_LINES, description]
    for route in routes:
        lines += [f"- range: {SkinnyGEMMLogic.flow_list(route.key)}",
                  f"  params: {SkinnyGEMMLogic.render_routing_params(route.knobs)}"]
    return "\n".join(lines) + "\n"


def read_routes(path: Path, pool: SkinnyGEMMLogic.Pool) -> List[Route]:
    """The routes of a rows file; the logic generator's reader validates it."""
    knobs_of = list(pool)
    return routes_from((tuple(key), knobs_of[index], 0) for key, index in SkinnyGEMMLogic.readRoutingRows(path, pool))


# ---------------------------------------------------------------------------
# Tables.


def _fmt(value: Any) -> str:
    if isinstance(value, float):
        return "inf" if math.isinf(value) else "" if math.isnan(value) else f"{value:.3f}"
    return "" if value is None else str(value)


def markdown_table(table: Table) -> str:
    headers, rows = table
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(_fmt(value) for value in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def csv_text(table: Table) -> str:
    headers, rows = table
    stream = io.StringIO()
    writer = csv.writer(stream, lineterminator="\n")
    writer.writerow(headers)
    writer.writerows([[_fmt(value) for value in row] for row in rows])
    return stream.getvalue()


def knobs_label(knobs: Knobs) -> str:
    bm, tn, lanesK, waves, prefetch, upIters, partialSteps, group, numXcds, grid3d, _ = knobs
    return (f"bm{bm} tn{tn} lk{lanesK} w{waves} pf{prefetch} up{upIters} ps{partialSteps} "
            f"g{group} x{numXcds} {'3d' if grid3d else 'persistent'}")


def point_table(routes: Sequence[Route], measurements: Measurements) -> Table:
    headers = ["phase", "m", "n", "k", "ld", "old index", "old us", "routed", "routed us", "speedup", "cell"]
    rows = []
    for (phase, point), measurement in sorted(measurements.items(), key=lambda item: (item[0][0], item[0][1])):
        route = find_route(routes, point)
        time = measurement.old_time if route is None else measurement.gen.get(route.knobs, math.nan)
        speedup = 1.0 if route is None else measurement.old_time / time
        rows.append([phase, point.m, point.n, point.k, point.ld, measurement.old_index, measurement.old_time,
                     "Origami" if route is None else knobs_label(route.knobs), time, speedup,
                     "" if route is None else route.cell_id])
    return headers, rows


def speedup_stats(speedups: Sequence[float]) -> str:
    finite = [value for value in speedups if not math.isinf(value) and not math.isnan(value)]
    if not finite:
        return "n/a"
    return f"min {min(finite):.3f}, median {statistics.median(finite):.3f}, max {max(finite):.3f} ({len(finite)} points)"


def cell_table(routes: Sequence[Route], points: Table) -> Table:
    headers = ["cell", "m range", "n range", "k range", "knobs", "corners", "points", "min", "median", "max"]
    by_speedup: Dict[str, List[float]] = {}
    for row in points[1]:
        if row[-1]:
            by_speedup.setdefault(row[-1], []).append(row[-2])
    rows = []
    for route in routes:
        finite = [v for v in by_speedup.get(route.cell_id, []) if not math.isinf(v) and not math.isnan(v)]
        rows.append([route.cell_id, f"{route.key[0]}-{route.key[1]}", f"{route.key[2]}-{route.key[3]}",
                     f"{route.key[6]}-{route.key[7]}", knobs_label(route.knobs), route.corners, len(finite),
                     min(finite, default=math.nan), statistics.median(finite) if finite else math.nan,
                     max(finite, default=math.nan)])
    return headers, rows


def held_out_lines(results: Sequence[HeldOutResult]) -> List[str]:
    regressions = [r for r in results if r.regression]
    lines = [f"- grid-only cells on {len(results)} measured held-out points: {len(regressions)} regressions",
             f"- held-out speedup: {speedup_stats([r.speedup for r in results if r.speedup is not None])}"]
    lines += [f"  - regression: {r.point.key} cell {r.cell_id} {knobs_label(r.knobs)} old {r.old_time:.2f} us, "
              f"entry {_fmt(r.gen_time)} us" for r in regressions]
    return lines


def point_stats(points: Table, phase: str) -> List[str]:
    rows = [row for row in points[1] if row[0] == phase]
    routed = [row[-2] for row in rows if row[-1]]
    return [f"- {phase} points: {len(rows)}, routed: {len(routed)}",
            f"  - speedup, all points (non-routed count as 1.0): {speedup_stats([row[-2] for row in rows])}",
            f"  - speedup, routed points only: {speedup_stats(routed)}",
            f"  - points the old default does not support (excluded above): {sum(math.isinf(v) for v in routed)}"]


# ---------------------------------------------------------------------------
# Validation after the rebuild: the library's own default pick against the old default.


@dataclass(frozen=True)
class ValidationRow:
    point: Point
    routed: Optional[Route]
    old_index: Optional[int]
    old_time: float
    new_index: int
    new_knobs: Optional[Knobs]
    new_time: float
    pick_ok: bool

    @property
    def speedup(self) -> float:
        return self.old_time / self.new_time

    def regression(self, limits: Thresholds) -> bool:
        return self.new_time > limits.regression * self.old_time


def _sample(points: List[Point], cap: int, rng: random.Random) -> List[Point]:
    return sorted(rng.sample(points, cap)) if len(points) > cap else points


def validation_points(measurements: Measurements, routes: Sequence[Route], seed: int) -> List[Point]:
    """Every held-out point, up to 200 routed and 50 non-routed lattice points (a deterministic sample)."""
    rng = random.Random(seed)
    held_out = sorted(point for phase, point in measurements if phase == "held_out")
    lattice = sorted(point for phase, point in measurements if phase == "grid")
    routed = [point for point in lattice if find_route(routes, point)]
    unrouted = [point for point in lattice if not find_route(routes, point)]
    return held_out + _sample(routed, VALIDATE_ROUTED_CAP, rng) + _sample(unrouted, VALIDATE_UNROUTED, rng)


def _campaign(measurements: Measurements, point: Point):
    return measurements.get(("grid", point)) or measurements.get(("held_out", point))


def _validate(point: Point, runs: Sequence[RunRecord], measurements: Measurements, routes: Sequence[Route],
              table: SolutionTable) -> Optional[ValidationRow]:
    campaign = _campaign(measurements, point)
    if campaign is None:
        return None
    new = vote([run.first_index for run in runs])
    new_time = min(run.times[new] for run in runs if new in run.times)
    old = campaign.old_index
    old_time = min((run.times[old] for run in runs if old in run.times), default=math.inf)
    route, new_knobs = find_route(routes, point), table.knobs(new)
    pick_ok = new_knobs == route.knobs if route else (new == old or old is None)
    return ValidationRow(point, route, old, old_time, new, new_knobs, new_time, pick_ok)


def analyze_validation(records: Sequence[RunRecord], measurements: Measurements, routes: Sequence[Route],
                       table: SolutionTable, phase: str = "validate") -> List[ValidationRow]:
    """Pairs, per point, the new default with the old default index timed in the same processes."""
    groups: Dict[Point, List[RunRecord]] = {}
    for run in records:
        if run.phase == phase and run.return_code == 0:
            groups.setdefault(run.point, []).append(run)
    rows = (_validate(point, runs, measurements, routes, table) for point, runs in sorted(groups.items()))
    return [row for row in rows if row is not None]


def validation_refinement(rows: Sequence[ValidationRow]) -> List[Point]:
    """Routed points whose new to old ratio is inside the noise band."""
    return [row.point for row in rows if row.routed and not math.isinf(row.old_time) and in_noise_band(row.speedup)]


def validation_table(rows: Sequence[ValidationRow], limits: Thresholds) -> Table:
    headers = ["m", "n", "k", "ld", "cell", "old index", "old us", "new index", "new", "new us", "speedup",
               "pick ok", "regression"]
    body = [[r.point.m, r.point.n, r.point.k, r.point.ld, r.routed.cell_id if r.routed else "", r.old_index,
             r.old_time, r.new_index, knobs_label(r.new_knobs) if r.new_knobs else "Origami", r.new_time, r.speedup,
             r.pick_ok, r.regression(limits)] for r in rows]
    return headers, body


def validation_summary(rows: Sequence[ValidationRow], limits: Thresholds) -> List[str]:
    routed = [r for r in rows if r.routed]
    flagged = [r for r in rows if r.regression(limits) or not r.pick_ok]
    lines = [f"- validated points: {len(rows)} ({len(routed)} routed, {len(rows) - len(routed)} non-routed)",
             f"- speedup, routed points: {speedup_stats([r.speedup for r in routed])}",
             f"- speedup, all points: {speedup_stats([r.speedup if r.routed else 1.0 for r in rows])}",
             f"- unexpected picks: {sum(not r.pick_ok for r in rows)}",
             f"- regressions (new > {limits.regression} x old): {sum(r.regression(limits) for r in rows)}"]
    lines += [f"  - {r.point.key}: old {r.old_time:.2f} us, new {r.new_time:.2f} us, pick ok {r.pick_ok}" for r in flagged]
    return lines
