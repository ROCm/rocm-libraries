@pytest.mark.parametrize("source_link", [None, "symlink", "hardlink"])
@pytest.mark.parametrize("legacy_tarfile", [False, True], ids=["native", "python-3.10.8"])
def test_wheel_built_from_sdist_keeps_the_revision(project, tmp_path, monkeypatch, legacy_tarfile, source_link):
    if legacy_tarfile:
        # Math CI's Python 3.10.8 has neither data_filter nor the filter keyword.
        # Exercise that interface on newer interpreters while still extracting
        # the real sdist and building a wheel from it.
        extractall = tarfile.TarFile.extractall

        def extractall_without_filter(self, path=".", members=None, *, numeric_owner=False):
            return extractall(self, path=path, members=members, numeric_owner=numeric_owner)

        trusted = getattr(tarfile, "fully_trusted_filter", None)
        if trusted is not None:
            # Python 3.14 defaults to the data_filter that this fixture removes.
            monkeypatch.setattr(tarfile.TarFile, "extraction_filter", staticmethod(trusted))
        monkeypatch.delattr(tarfile, "data_filter", raising=False)
        monkeypatch.setattr(tarfile.TarFile, "extractall", extractall_without_filter)

    alias = project / "tensilelite" / "revision_alias.py"
    original = project / "tensilelite" / "_source_revision.py"
    if source_link:
        try:
            if source_link == "symlink":
                alias.symlink_to(original.name)
            else:
                os.link(original, alias)
        except OSError as error:
            pytest.skip(f"filesystem does not support {source_link}: {error}")
        _git(project, "add", str(alias))
        _git(project, "commit", "-qm", "source link")
    head = _git(project, "rev-parse", "HEAD")
    sdist = _backend(project, "build_sdist", tmp_path / "sdist")
    _assert_tree_unchanged(project)

    with tarfile.open(sdist) as archive:
        # setuptools must dereference source links in the release tree. Keep
        # archives link-free so extraction is equally safe on older Python.
        assert not any(member.issym() or member.islnk() for member in archive.getmembers())
        if source_link:
            member = next(m for m in archive.getmembers() if m.name.endswith("/tensilelite/revision_alias.py"))
            assert member.isfile()
            assert archive.extractfile(member).read() == original.read_bytes()
        _safe_extractall(archive, tmp_path / "unpacked")
    (unpacked,) = (tmp_path / "unpacked").iterdir()
    assert _RESOLVER["read_build_info"](unpacked / "tensilelite" / "_build_info.py") == head

    wheel = _backend(unpacked, "build_wheel", tmp_path / "wheel")
    assert _version_of(wheel) == f"5.0.0+g{head}"
    assert _stamped_revision(_wheel_stamp(wheel)[0]) == head


