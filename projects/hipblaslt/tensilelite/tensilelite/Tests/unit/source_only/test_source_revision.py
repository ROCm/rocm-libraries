@pytest.mark.parametrize("change", ["size", "mtime"])
def test_untracked_metadata_changes_the_revision_without_reading_contents(project, monkeypatch, change):
    path = project / "new.py"
    path.write_bytes(b"first")
    first_stat = path.lstat()
    first = _RESOLVER["resolve"](project, {})
    if change == "size":
        path.write_bytes(b"longer contents")
        os.utime(path, ns=(first_stat.st_atime_ns, first_stat.st_mtime_ns))
    else:
        # Two seconds also works on filesystems with coarse mtime resolution.
        os.utime(path, ns=(first_stat.st_atime_ns, first_stat.st_mtime_ns + 2_000_000_000))
        assert path.lstat().st_mtime_ns != first_stat.st_mtime_ns

    original_open = Path.open

    def no_untracked_reads(self, *args, **kwargs):
        if self == path:
            pytest.fail("resolver read untracked contents")
        return original_open(self, *args, **kwargs)

    monkeypatch.setattr(Path, "open", no_untracked_reads)
    second = _RESOLVER["resolve"](project, {})
    assert second != first
    assert _RESOLVER["resolve"](project, {}) == second


def test_untracked_same_size_and_mtime_is_an_accepted_collision(project):
    path = project / "new.py"
    path.write_bytes(b"first")
    before = path.lstat()
    first = _RESOLVER["resolve"](project, {})
    path.write_bytes(b"other")
    os.utime(path, ns=(before.st_atime_ns, before.st_mtime_ns))
    assert path.lstat().st_mtime_ns == before.st_mtime_ns
    assert _RESOLVER["resolve"](project, {}) == first


def test_untracked_mtime_uses_integer_nanoseconds(project, monkeypatch):
    path = project / "new.py"
    path.write_bytes(b"first")
    original_lstat = Path.lstat
    timestamp = 1_700_000_000_123_456_789

    class Metadata:
        st_mode = stat.S_IFREG | 0o644
        st_size = 5

        @property
        def st_mtime_ns(self):
            return timestamp

        @property
        def st_mtime(self):
            pytest.fail("resolver used floating-point mtime")

    monkeypatch.setattr(Path, "lstat", lambda self: Metadata() if self == path else original_lstat(self))
    first = _RESOLVER["resolve"](project, {})
    timestamp += 1
    assert _RESOLVER["resolve"](project, {}) != first


@pytest.mark.parametrize("change", ["content", "addition", "deletion", "mode", "symlink"])
def test_tracked_change_records_are_stable_across_staging(project, change):
    head = _git(project, "rev-parse", "HEAD")
    path = project / "tensilelite" / "__init__.py"
    if change == "content":
        path.write_bytes(b"binary\0change\n")
    elif change == "addition":
        path = project / "new tracked file.py"
        path.write_text("NEW = True\n")
        _git(project, "add", str(path))
    elif change == "deletion":
        path.unlink()
    elif change == "mode":
        if _git(project, "config", "core.filemode") != "true":
            pytest.skip("filesystem does not track executable modes")
        path.chmod(path.stat().st_mode | stat.S_IXUSR)
    else:
        path.unlink()
        try:
            path.symlink_to("_source_revision.py")
        except OSError as error:
            pytest.skip(f"filesystem does not support symlinks: {error}")

    first = _RESOLVER["resolve"](project, {})
    assert first.startswith(f"{head}.dirty.")
    assert _RESOLVER["resolve"](project, {}) == first
    _git(project, "add", "-A")
    assert _RESOLVER["resolve"](project, {}) == first


