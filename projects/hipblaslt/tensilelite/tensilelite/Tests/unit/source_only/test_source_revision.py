@pytest.mark.parametrize("helper_kind", ["external", "textconv", "fsmonitor"])
@pytest.mark.parametrize("owned", [True, False])
def test_git_helpers_cannot_run_during_resolution(project, helper_kind, owned):
    marker = project / ".git" / "helper-ran"
    helper = project / ".git" / "helper.py"
    helper.write_text(f"from pathlib import Path\nPath({str(marker)!r}).touch()\n")
    command = f'"{sys.executable}" "{helper}"'
    if helper_kind == "external":
        _git(project, "config", "diff.external", command)
    elif helper_kind == "textconv":
        (project / ".gitattributes").write_text("*.py diff=hidden\n")
        _git(project, "add", ".gitattributes")
        _git(project, "commit", "-qm", "attributes")
        _git(project, "config", "diff.hidden.textconv", command)
    else:
        _git(project, "config", "core.fsmonitor", command)
    head = _git(project, "rev-parse", "HEAD")
    target = project / "tensilelite" / "__init__.py"
    with target.open("a") as stream:
        stream.write("# changed\n")
    root = project if owned else _copy_project(project / "copied")

    revision = _RESOLVER["resolve"](root, {})

    assert not marker.exists()
    if owned:
        assert revision.startswith(f"{head}.dirty.")
        with target.open("a") as stream:
            stream.write("# changed again\n")
        assert _RESOLVER["resolve"](root, {}) != revision
    else:
        assert revision is None


