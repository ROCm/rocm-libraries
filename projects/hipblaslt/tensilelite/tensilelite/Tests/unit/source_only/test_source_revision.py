def test_dirty_scope_is_the_whole_repository(nested_project):
    """The commit names the whole repository, so changes anywhere in it count."""
    repo, root = nested_project
    head = _git(repo, "rev-parse", "HEAD")
    assert _RESOLVER["resolve"](root, {}) == head

    (root / "tensilelite" / "new_module.py").write_text("VALUE = 1\n")
    inside = _RESOLVER["resolve"](root, {})
    assert inside.startswith(f"{head}.dirty.")
    (root / "tensilelite" / "new_module.py").unlink()

    (repo / "shared" / "untracked.cpp").write_text("int untracked();\n")
    outside = _RESOLVER["resolve"](root, {})
    assert outside.startswith(f"{head}.dirty.")
    assert outside != inside
    (repo / "shared" / "untracked.cpp").unlink()
    assert _RESOLVER["resolve"](root, {}) == head

    with open(repo / "shared" / "library.cpp", "a") as stream:
        stream.write("int changed();\n")
    assert _RESOLVER["resolve"](root, {}).startswith(f"{head}.dirty.")


