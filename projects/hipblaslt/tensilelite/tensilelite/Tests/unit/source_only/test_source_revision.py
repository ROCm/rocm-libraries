def _build_env(**extra):
    env = {k: v for k, v in os.environ.items()
           if k not in ("ROCM_PATH", "ROCM_VERSION", "TENSILELITE_SOURCE_REVISION")}
    env.update(extra)
    return env


def _pip_wheel(source, out, **env):
    """Build like a plain ``pip install <path>``: pip runs setup.py three times."""
    subprocess.run(
        [sys.executable, "-m", "pip", "wheel", "--no-build-isolation", "--no-deps",
         "--disable-pip-version-check", "-q", "--wheel-dir", str(out), str(source)],
        env=_build_env(**env),
        check=True,
        capture_output=True,
        text=True,
    )
    (wheel,) = Path(out).glob("*.whl")
    return wheel


def _backend(source, hook, out, **env):
    out.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [sys.executable, "-c",
         f"import sys; from setuptools import build_meta; print(build_meta.{hook}(sys.argv[1]))",
         str(out)],
        cwd=source,
        env=_build_env(**env),
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return out / result.stdout.strip().splitlines()[-1]


def _wheel_stamp(wheel):
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
        stamp = archive.read("tensilelite/_build_info.py").decode() if (
            "tensilelite/_build_info.py" in names) else None
        record = archive.read(next(n for n in names if n.endswith(".dist-info/RECORD"))).decode()
    return stamp, record


def _stamped_revision(text):
    namespace = {}
    exec(text, namespace)  # noqa: S102 - generated by setup.py in this test
    return namespace["SOURCE_REVISION"]


def _version_of(wheel):
    return Path(wheel).name.split("-")[1]


def _assert_tree_unchanged(root):
    assert _git(root, "status", "--porcelain", "--untracked-files=all") == ""
    assert not (root / "tensilelite" / "_build_info.py").exists()


