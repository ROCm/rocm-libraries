// Golden generator for the LogicalScheduler pass-pipeline snapshot test.
//
// Emits scheduler_pass_goldens.inc: a {"<config>/<method>" -> output} map of
// the C++ pass-pipeline print_* output for every config in
// scheduler_pass_configs.hpp. This is a developer tool, NOT part of the test
// target. Regenerate (and review the diff) deliberately, only when the pass
// pipeline output intentionally changes:
//
//   cmake --build build_tests --target gen_scheduler_goldens
//   ./build_tests/gen_scheduler_goldens > cpp/tests/scheduler_pass_goldens.inc
//
// The committed .inc is cross-checked against the Python LogicalScheduler
// (byte-identical print_* output) at generation time; see the grc.97 handoff.

#include <iostream>
#include <string>

#include "scheduler_pass_configs.hpp"
#include "tensile_writer/logical_scheduler_passes.hpp"

int main() {
  using namespace tw_test;
  std::cout << "// AUTO-GENERATED by gen_scheduler_goldens.cpp — do not edit by "
               "hand.\n";
  std::cout << "// Regenerate: build the gen_scheduler_goldens target and "
               "redirect stdout here.\n";
  std::cout << "static const std::map<std::string, std::string> kPassGoldens = "
               "{\n";
  for (const auto& spec : passConfigs()) {
    for (const auto& method : printMethods()) {
      tw::subtile::lsched::passes::LogicalScheduler sched(makePassConfig(spec));
      std::string out = runPrint(sched, method);
      std::cout << "    {\"" << spec.name << "/" << method << "\", R\"GOLDEN("
                << out << ")GOLDEN\"},\n";
    }
  }
  std::cout << "};\n";
  return 0;
}
