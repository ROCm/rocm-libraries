"""Run two small GEMMs under the rocjitsu race detector, without a GPU.

One GEMM runs through hipblaslt-bench and one is generated by TensileLite and
run by tensilelite-client. The race detector reports reads of registers or LDS
that are not ordered after the write they depend on by the required s_waitcnt
or s_barrier, within one workgroup. A workload fails if it fails by itself,
if the detector reports a race, or if it never reaches a matrix instruction
(in which case the detector saw nothing relevant).

This script is installed with the hipBLASLt clients in
<prefix>/share/hipblaslt/rocjitsu and by default tests the ROCm installation at
<prefix>, which must also contain the rocjitsu launcher, its race and logging
plugins and its device configs. TensileLite's test requirements must be
installed in the Python environment.
"""

import argparse
import json
import os
import platform
import shlex
import signal
import subprocess
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_ROCM_PATH = SCRIPT_DIR.parents[2]
TENSILELITE_CONFIG = SCRIPT_DIR / "rocjitsu_race_smoke_tensilelite.yaml"
# Each workload takes a few seconds. Together these limits must stay well
# below the CI step timeout (15 minutes in TheRock) so a hang is reported here.
HIPBLASLT_BENCH_TIMEOUT_SECONDS = 60
TENSILELITE_TIMEOUT_SECONDS = 120

# AMDGPU family prefix -> (GPU target, rocjitsu device config).
TARGETS = {
    "gfx94": ("gfx942", "gfx942_cdna3_kmd.json"),
    "gfx950": ("gfx950", "gfx950_mi350x_kmd.json"),
}


def select_target(amdgpu_families):
    for prefix, target in TARGETS.items():
        if amdgpu_families.startswith(prefix):
            return target
    raise SystemExit(
        f"no rocjitsu race check for AMDGPU family '{amdgpu_families}'; "
        f"supported prefixes are {sorted(TARGETS)}"
    )


def require(path, description):
    if not path.exists():
        raise SystemExit(f"{description} not found: {path}")
    return path


def find_libomp_dir(rocm_path):
    # The LLVM runtime directory is flat unless per-target runtime directories
    # are enabled.
    llvm_lib = rocm_path / "lib" / "llvm" / "lib"
    for directory in (llvm_lib, llvm_lib / f"{platform.machine()}-unknown-linux-gnu"):
        if (directory / "libomp.so").exists():
            return directory
    raise SystemExit(f"libomp.so not found under {llvm_lib}")


def workload_failures(returncode, output):
    """Return the reasons a workload failed, given its exit status (None after
    a timeout) and its console output, which includes the race and logging
    plugin messages."""
    failures = []
    if returncode is None:
        failures.append("timed out")
    elif returncode != 0:
        failures.append(f"exited with status {returncode}")
    if "[rocjitsu] Kernel dispatch:" not in output:
        failures.append("race detector recorded no kernel dispatch")
    races = output.count("RACE kernel=")
    if races:
        failures.append(f"race detector reported {races} race(s)")
    if "[rocjitsu] mfma detected in dispatch " not in output:
        failures.append("no MFMA dispatch reached; the race check is inconclusive")
    return failures


def run_with_timeout(cmd, cwd, env, timeout):
    """Run cmd and return its exit status (None on timeout) and output.

    The workload starts processes of its own (TensileLite runs a compiler and
    tensilelite-client), so on timeout the whole process group is killed."""
    proc = subprocess.Popen(
        cmd,
        cwd=cwd,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        errors="replace",
        start_new_session=True,
    )
    try:
        output, _ = proc.communicate(timeout=timeout)
        return proc.returncode, output
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL)
        output, _ = proc.communicate()
        return None, output


def run_under_rocjitsu(name, rocjitsu, base_config, workload, env, timeout, report_dir):
    """Run one workload; return its failures and output."""
    work_dir = report_dir / name
    work_dir.mkdir(parents=True, exist_ok=True)
    config = json.loads(base_config.read_text())
    config.setdefault("plugins", {}).update({"race": {}, "logging": {}})
    # Plugin messages go to the console only. File sinks are reopened, and
    # truncated, by every process the workload starts.
    config["sinks"] = {"types": ["stderr"]}
    run_config = work_dir / "rocjitsu.json"
    run_config.write_text(json.dumps(config, indent=2) + "\n")

    cmd = [str(rocjitsu), "--config", str(run_config), "--", *workload]
    print(f"++ Exec [{work_dir}]$ {shlex.join(cmd)}", flush=True)
    returncode, output = run_with_timeout(cmd, work_dir, env, timeout)
    print(output, flush=True)
    return workload_failures(returncode, output), output


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rocm-path", type=Path, default=DEFAULT_ROCM_PATH)
    parser.add_argument(
        "--amdgpu-families",
        default=os.environ.get("AMDGPU_FAMILIES", ""),
        help="AMDGPU family to emulate, for example gfx950-dcgpu "
        "(default: $AMDGPU_FAMILIES)",
    )
    parser.add_argument(
        "--report-dir", type=Path, default=Path("rocjitsu-race-reports")
    )
    args = parser.parse_args()

    rocm_path = args.rocm_path.resolve()
    report_dir = args.report_dir.resolve()
    gpu_target, config_name = select_target(args.amdgpu_families)
    bin_dir = rocm_path / "bin"
    rocjitsu = require(bin_dir / "rocjitsu", "rocjitsu launcher")
    base_config = require(
        rocm_path / "share" / "rocjitsu" / "configs" / config_name, "rocjitsu config"
    )
    bench = require(bin_dir / "hipblaslt-bench", "hipblaslt-bench")
    tensilelite_root = require(
        rocm_path / "share" / "hipblaslt" / "tensilelite", "TensileLite test tree"
    )
    tensile = require(tensilelite_root / "tensilelite" / "bin" / "Tensile", "Tensile")
    client = require(
        rocm_path / "libexec" / "hipblaslt" / "tensilelite" / "tensilelite-client",
        "tensilelite-client",
    )
    cxx = require(bin_dir / "amdclang++", "amdclang++")

    env = os.environ.copy()
    env["ROCM_PATH"] = str(rocm_path)
    env["PATH"] = os.pathsep.join(
        [str(bin_dir), str(rocm_path / "lib" / "llvm" / "bin"), env.get("PATH", "")]
    )
    env["LD_LIBRARY_PATH"] = os.pathsep.join(
        filter(
            None,
            [
                str(rocm_path / "lib"),
                str(rocm_path / "lib" / "rocm_sysdeps" / "lib"),
                str(rocm_path / "lib" / "llvm" / "lib"),
                str(find_libomp_dir(rocm_path)),
                env.get("LD_LIBRARY_PATH", ""),
            ],
        )
    )
    env["PYTHONPATH"] = os.pathsep.join(
        filter(None, [str(tensilelite_root), env.get("PYTHONPATH", "")])
    )
    env["HSA_ENABLE_SDMA"] = "1"

    report_dir.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(rocjitsu), "--version"], env=env, check=True)

    # Run both workloads even if the first fails, so one attempt shows both.
    results = {}
    results["hipblaslt-bench"], _ = run_under_rocjitsu(
        "hipblaslt-bench",
        rocjitsu,
        base_config,
        # HPL initialization also exercises the device-side fill kernels.
        [str(bench), "--precision", "f32_r", "--initialization", "hpl", "--verify"]
        + ["-m", "128", "-n", "128", "-k", "128", "--iters", "1", "--cold_iters", "0"],
        env,
        HIPBLASLT_BENCH_TIMEOUT_SECONDS,
        report_dir,
    )
    output_dir = report_dir / "tensilelite" / "output"
    failures, output = run_under_rocjitsu(
        "tensilelite",
        rocjitsu,
        base_config,
        [sys.executable, str(tensile), str(TENSILELITE_CONFIG), str(output_dir)]
        + ["--prebuilt-client", str(client), "--gpu-targets", gpu_target]
        + ["--library-format", "msgpack", "--cxx-compiler", str(cxx)],
        env,
        TENSILELITE_TIMEOUT_SECONDS,
        report_dir,
    )
    if ",PASSED," not in output:
        failures.append("TensileLite did not report a passing validation")
    results["tensilelite"] = failures

    failed = False
    for name, failures in results.items():
        for failure in failures:
            print(f"error: {name}: {failure}", file=sys.stderr)
            failed = True
    if failed:
        return 1
    print("rocjitsu race checks passed without race reports")
    return 0


if __name__ == "__main__":
    sys.exit(main())
