"""Generate a link-time completeness check for the hipTensor stub.

Parses the public header for every function declared with HIPTENSOR_EXPORT and
emits a small C++ translation unit that takes the address of each one. When this
unit is linked against ONLY the stub object (library/stub/hiptensor_stub.cpp), a
public API function the stub does not implement becomes an unresolved external
symbol, so the build fails. Because the source is regenerated from the header at
configure time, a newly added public API is covered automatically: it gets a new
address reference that the stub must satisfy.
"""

import argparse
import re
import sys
from pathlib import Path


def parse_exported_functions(header: Path) -> list[str]:
    """Return the sorted list of function names declared with HIPTENSOR_EXPORT."""
    text = header.read_text()
    # Drop comments so documentation prose cannot introduce phantom names.
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)

    names: set[str] = set()
    # Each exported declaration looks like:
    #   HIPTENSOR_EXPORT <return type> hiptensorXxx( ... );
    for decl in re.findall(r"HIPTENSOR_EXPORT\b(.*?);", text, flags=re.DOTALL):
        match = re.search(r"(hiptensor[A-Za-z0-9_]*)\s*\(", decl)
        if match:
            names.add(match.group(1))
    return sorted(names)


_TEMPLATE = """\
// Auto-generated by generate_api_coverage.py. Do not edit.
//
// Link-time completeness check for the hipTensor stub. References the address of
// every HIPTENSOR_EXPORT function in the public header. Linked against only the
// stub object, any public API function the stub fails to implement becomes an
// unresolved symbol and the build fails. This guarantees, at build time and for
// any GPU_TARGETS, that the stub implements the entire public API.

#include <hiptensor/hiptensor.h>

namespace
{{
    // Taking each function's address forces the linker to resolve the symbol.
    void* const kPublicApiSymbols[] = {{
{symbol_rows}
    }};
}}

// Referenced from main so the table (and thus every symbol) is not stripped.
const void* const* hiptensor_stub_api_coverage_symbols()
{{
    return kPublicApiSymbols;
}}

int main()
{{
    return hiptensor_stub_api_coverage_symbols() != nullptr ? 0 : 1;
}}
"""


def render(names: list[str]) -> str:
    rows = ",\n".join(
        f"        reinterpret_cast<void*>(&{name})" for name in names
    )
    return _TEMPLATE.format(symbol_rows=rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--header", required=True, type=Path, help="Path to public hiptensor.h"
    )
    parser.add_argument(
        "--output", required=True, type=Path, help="Path of the .cpp to generate"
    )
    args = parser.parse_args()

    names = parse_exported_functions(args.header)
    if not names:
        print(
            f"ERROR: no HIPTENSOR_EXPORT functions found in {args.header}",
            file=sys.stderr,
        )
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(names))
    print(f"Generated {args.output} referencing {len(names)} public API functions.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
