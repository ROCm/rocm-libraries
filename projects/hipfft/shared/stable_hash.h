#ifndef STABLE_HASH_H
#define STABLE_HASH_H

#include <cstdint>

// Fixed, platform-independent 64-bit mix (splitmix64 finalizer).
// Unlike std::hash, the result is defined here and does not depend on compiler,
// standard library, or process.
//
// This header deliberately has no dependencies beyond <cstdint>, so that the
// mix can be shared by callers that must not pull in the rocFFT API.
static inline uint64_t stable_hash(uint64_t z)
{
    z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
    z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
    return z ^ (z >> 31);
}

#endif // STABLE_HASH_H
