@dataclass(frozen=True)
class FmhaFwdDecodePagedKVPipeline:
    F_wave_split: str  # t: each wave runs its own pages, f: the waves share a step
    F_groups: str  # t: several clusters per (batch, kv head)
    F_page_size: int  # tokens per cache page

    @property
    def name(self) -> str:
        n = f"ps{self.F_page_size}_"
        n += "tdm_wsplit" if self.F_wave_split == "t" else "tdm_coop"
        return n


@dataclass
class FmhaFwdDecodePagedKVKernel:
    F_arch: ArchTrait
    F_idx: int  # this is not a tunable, but a counter to differentiate symbols within a file
    F_hdim: int  # hdim
    F_dtype: str  # Q/O data type
    F_num_splits: int  # splits (workgroups) per cluster
    F_pipeline: FmhaFwdDecodePagedKVPipeline

    @property
    def body(self) -> str:
        return FMHA_FWD_DECODE_PAGEDKV_KERNEL_BODY.format(
            F_idx=self.F_idx,
            F_arch=self.F_arch,
            F_hdim=self.F_hdim,
            F_dtype=DECODE_PAGEDKV_DTYPE_MAP[self.F_dtype],
            F_wave_split=BOOL_MAP[self.F_pipeline.F_wave_split],
            F_num_splits=self.F_num_splits,
            F_groups=BOOL_MAP[self.F_pipeline.F_groups],
            F_page_size=self.F_pipeline.F_page_size,
            F_occupancy=-1,
        )

    @property
    def name(self) -> str:
        # sync with FmhaFwdDecodePagedKVKernel::GetName
        return (
            f"fmha_fwd_decode_pagedkv_d{self.F_hdim}_{self.F_dtype}_fp8kv_{self.F_pipeline.name}"
            + f"_s{self.F_num_splits}"
            + ("_groups" if self.F_pipeline.F_groups == "t" else "_ngroups")
        )

    @property
    def filename(self) -> str:
        # the split counts of one variant share a file: they differ in one template argument
        return (
            f"fmha_fwd_decode_pagedkv_d{self.F_hdim}_{self.F_dtype}_fp8kv_{self.F_pipeline.name}"
            + ("_groups" if self.F_pipeline.F_groups == "t" else "_ngroups")
            + f"{self.F_arch.filename_suffix}.cpp"
        )


def get_sources(kernels: List[FmhaFwdDecodePagedKVKernel]) -> dict:
    """File name -> content, in the order of the kernels."""
    sources = dict()
    for k in kernels:
        sources.setdefault(k.filename, FMHA_FWD_DECODE_PAGEDKV_KERNEL_HEADER)
        sources[k.filename] += k.body
    return sources


class FmhaFwdDecodePagedKVApiPool:
    def __init__(self):
        # arch -> dtype -> (hdim, pipeline) -> kernels ordered by split count
        self.pool = dict()

    def register(self, k: FmhaFwdDecodePagedKVKernel) -> None:
        shapes = self.pool.setdefault(k.F_arch, dict()).setdefault(k.F_dtype, dict())
        shapes.setdefault((k.F_hdim, k.F_pipeline), list()).append(k)

    @property
    def api(self) -> str:
        per_arch = str()
        for i_arch, (arch, dtypes) in enumerate(self.pool.items()):
            per_dtype = str()
            for i_dtype, (dtype, shapes) in enumerate(dtypes.items()):
                per_shape = str()
                for i_shape, ((hdim, pipeline), kernels) in enumerate(shapes.items()):
                    inners = str()
                    for k in kernels:
                        inners += FMHA_FWD_DECODE_PAGEDKV_API_INNER_DISPATCH.format(
                            F_hdim=hdim,
                            F_dtype=DECODE_PAGEDKV_DTYPE_MAP[dtype],
                            F_page_size=pipeline.F_page_size,
                            F_wave_split=BOOL_MAP[pipeline.F_wave_split],
                            F_num_splits=k.F_num_splits,
                            F_groups=BOOL_MAP[pipeline.F_groups],
                            F_arch=arch,
                        )
                    per_shape += FMHA_FWD_DECODE_PAGEDKV_API_PER_SHAPE.format(
                        F_if=if_(i_shape),
                        F_hdim=hdim,
                        F_page_size=pipeline.F_page_size,
                        F_wave_split=BOOL_MAP[pipeline.F_wave_split],
                        F_groups=BOOL_MAP[pipeline.F_groups],
                        F_inner_dispatch=indent(inners),
                    )
                per_dtype += FMHA_FWD_DECODE_PAGEDKV_API_PER_DTYPE.format(
                    F_if=if_(i_dtype), F_dtype=dtype, F_shape_case=indent(per_shape)
                )
            per_arch += FMHA_FWD_DECODE_PAGEDKV_API_PER_ARCH.format(
                F_if=if_(i_arch), F_arch=arch, F_dtype_case=indent(per_dtype)
            )
        if not per_arch:
            # empty string we add some ignore to suppress warning in api
            per_arch += "(void)t; (void)a; (void)s;"
        return (
            FMHA_FWD_DECODE_PAGEDKV_KERNEL_HEADER
            + FMHA_FWD_DECODE_PAGEDKV_API.format(F_dispatch=indent(per_arch))
        )


class KernelComponentFactoryGfx125:
    arch = ArchTrait("gfx125")

    @staticmethod
    def get_hdims(dtype: str) -> List[int]:
        return [128] if dtype in DECODE_PAGEDKV_DTYPE_MAP else []

    @staticmethod
    def get_pipelines(dtype: str, hdim: int) -> List[FmhaFwdDecodePagedKVPipeline]:
        pipelines = []
        for page_size, wave_split, groups in itertools.product(
            [16, 64, 128], ["f", "t"], ["f", "t"]
        ):
            pipelines.append(
                FmhaFwdDecodePagedKVPipeline(wave_split, groups, page_size)
            )
        return pipelines


def get_factory(target: str):
    # the kernel needs workgroup clusters, TDM gathers and fp8 WMMA
    if target.startswith("gfx125"):
        return KernelComponentFactoryGfx125
    return None


def get_fwd_decode_pagedkv_blobs(
    targets: List[str], kernel_filter: Optional[str], receipt, optdim_list
) -> Tuple[FmhaFwdDecodePagedKVApiPool, List[FmhaFwdDecodePagedKVKernel]]:
    gen = list()
    api_pool = FmhaFwdDecodePagedKVApiPool()

    supported = [t for t in targets if get_factory(t) is not None]
    factories = get_factories_for_targets(supported, get_factory)

    for factory, dtype in itertools.product(factories, DECODE_PAGEDKV_DTYPE_MAP.keys()):
        for hdim in factory.get_hdims(dtype):
            if optdim_list != [-1] and hdim not in optdim_list:
                continue
            for pipeline in factory.get_pipelines(dtype, hdim):
                # several clusters need clusters of at least two splits
                first = 2 if pipeline.F_groups == "t" else 1
                for num_splits in range(first, MAX_CLUSTER_SPLITS + 1):
                    k = FmhaFwdDecodePagedKVKernel(
                        F_arch=factory.arch,
                        F_idx=num_splits,
                        F_hdim=hdim,
                        F_dtype=dtype,
                        F_num_splits=num_splits,
                        F_pipeline=pipeline,
                    )
                    if kernel_filter != "" and not fnmatch.fnmatch(
                        k.name, kernel_filter
                    ):
                        continue
                    api_pool.register(k)
                    gen.append(k)

    return (api_pool, gen)


def write_blobs(
    targets: List[str],
    output_dir: Path,
    kernel_filter: Optional[str],
    receipt,
    optdim_list,
    mask_impl,
) -> None:
    api_pool, kernels = get_fwd_decode_pagedkv_blobs(
        targets, kernel_filter, receipt, optdim_list
    )
    for filename, content in get_sources(kernels).items():
        update_file(output_dir / filename, content)
    update_file(output_dir / FMHA_FWD_DECODE_PAGEDKV_API_FILENAME, api_pool.api)


def list_blobs(
    targets: List[str],
    file_path: Path,
    kernel_filter: Optional[str],
    receipt,
    optdim_list,
    mask_impl,
) -> None:
    with file_path.open("a") as f:
        _, kernels = get_fwd_decode_pagedkv_blobs(
            targets, kernel_filter, receipt, optdim_list
        )
        for filename in get_sources(kernels):
            f.write((file_path.parent / GEN_DIR / filename).as_posix() + "\n")
        f.write(
            (
                file_path.parent / GEN_DIR / FMHA_FWD_DECODE_PAGEDKV_API_FILENAME
            ).as_posix()
            + "\n"
        )
