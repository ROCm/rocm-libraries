@dataclass
class CppConstraint:
    bool_expr: str = None

    def __str__(self):
        if self.bool_expr is None:
            return "true"
        else:
            return f"{self.bool_expr}"

    def __and__(self, other):
        return CppConstraint(f"({str(self)}) && ({str(other)})")


def kv_splits_targ(kv_splits: int, query_tail_rows: int = 0) -> str:
    # Trailing template arguments of the KV-split (and query-tail) instances; none for the others.
    if kv_splits == 1:
        return ""
    return f", {kv_splits}" + ("" if query_tail_rows == 0 else f", {query_tail_rows}")


@dataclass
class FmhaFwdApiTrait:
    pipeline_tag: str
    # sync with fmha_fwd_traits<>, to generate fallback calls
    hdim: str
    dtype: str  # data type
    mode: str  # value from MODE_MAP
    bm0: int  # tile size along q seqlen (block size)
    bn0: int  # tile size along qk seqlen
    bk0: int  # tile size along qk gemm unroll
    bn1: int  # tile size along v head_dim
    bk1: int  # tile size along kv gemm unroll
    bk0max: int
    vlayout: str
    logits: str
    mask: str
    bias: str  #
    lse: str  #
    dropout: str
    qscale: str  #
    spad: str
    skpad: str
    dpad: str
    dvpad: str
    sink: str  # t/f
    constraint: CppConstraint
    kv_memory_layout: str
    kv_lookup_table: str
    page_size: int = 1  # page block size
    use_global_load: bool = False  # use global_load_lds_* for >2GB KV cache
    # Host-side arch predicate mirroring a tile's device-only F_arch gate.
    # "true" means arch-agnostic (no host restriction).
    arch_host: str = "true"
    # Metadata-only hint mapped onto fmha_fwd_batch_prefill_traits_::kOccupancy;
    # keeps otherwise-identical traits DISTINCT to avoid linker collisions.
    occupancy: int = -1
    # 2: KV split + merge (gfx125x page tile, needs the caller's workspace).
    kv_splits: int = 1
    # > 0: query tail of the KV split (see FmhaFwdTileSize.F_query_tail_rows).
    query_tail_rows: int = 0

    @property
    def name(self) -> str:
        return (
            f"{self.hdim}-{self.dtype}-{self.mode}-{self.bm0}-{self.bn0}-{self.bk0}-{self.bn0}-{self.bk1}-{self.bk0max}-"
            + f"{self.vlayout}-{self.logits}-{self.mask}-{self.bias}-{self.lse}-{self.dropout}-{self.qscale}-{self.spad}-{self.skpad}-{self.dpad}-{self.dvpad}-{self.kv_memory_layout}-{self.kv_lookup_table}-ps{self.page_size}"
            + ("-gload" if self.use_global_load else "-bload")
            + ("" if self.kv_splits == 1 else f"-ks{self.kv_splits}")
            + ("" if self.query_tail_rows == 0 else f"-qt{self.query_tail_rows}")
        )

    @property
    def kv_load_mode_check(self) -> str:
        if self.pipeline_tag == "qr_tdm_sched":
            return "true"
        return (
            f"fmha_batch_prefill_select_kv_load_mode(a.page_block_size, {self.bn0}, a.num_total_pages, "
            + "a.batch_stride_k, a.batch_stride_v, kElementBytes, a.k_ptr, a.v_ptr) == "
            + KV_LOAD_MODE_ENUM_MAP[self.use_global_load]
        )

    @property
    def scheck(self) -> str:
        if self.mode == "group":
            return "true/*group mode spad always true*/"  # group mode only generate spad/skpad == true
        if self.pipeline_tag == "qr_async":
            if self.spad == "t":
                return "true"  # always support
            else:
                return "true"
        elif self.pipeline_tag in ["qr"]:
            if self.spad == "t":
                return f"true /*a.seqlen_q % {self.bm0} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.seqlen_q % {self.bm0} == 0"
        else:
            assert False

    @property
    def skcheck(self) -> str:
        if self.mode == "group":
            return "true/*group mode skpad always true*/"  # group mode only generate spad/skpad == true
        if self.pipeline_tag == "qr_async":
            if self.skpad == "t":
                return f"a.seqlen_k == 0 || a.seqlen_k % {self.bn0} != 0"
            else:
                return f"a.seqlen_k != 0 && a.seqlen_k % {self.bn0} == 0"
        elif self.pipeline_tag in ["qr", "qr_fp8"]:
            if self.skpad == "t":
                return f"true /*a.seqlen_k % {self.bn0} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.seqlen_k % {self.bn0} == 0"
        else:
            assert False

    @property
    def dcheck(self) -> str:
        if self.pipeline_tag == "qr_async":
            vec = int((32 * 4) / DTYPE_BITS[self.dtype])
            if self.dpad == "t":
                return f"a.hdim_q % {vec} == 0"
            else:
                assert False
        elif self.pipeline_tag in ["qr"]:
            bk0submax = K0_MAX_SUBMAX_MAP[self.bk0max]
            if self.dpad == "t":
                return f"true /*a.hdim_q % {bk0submax} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.hdim_q % {bk0submax} == 0"
        elif self.pipeline_tag == "qr_tdm_sched":
            assert self.dpad == "f"
            return f"a.hdim_q == {self.bk0max}"
        else:
            assert False

    @property
    def dvcheck(self) -> str:
        if self.pipeline_tag == "qr_async":
            vec = int((32 * 4) / DTYPE_BITS[self.dtype])
            if self.dvpad == "t":
                return f"a.hdim_v % {vec} == 0"
            else:
                assert False
        elif self.pipeline_tag in ["qr"]:
            bk0submax = K0_MAX_SUBMAX_MAP[self.bk0max]
            if self.dvpad == "t":
                return f"true /*a.hdim_v % {bk0submax} != 0*/"  # TODO: order of get_pipelines() matters! (ugly)
            else:
                return f"a.hdim_v % {bk0submax} == 0"
        elif self.pipeline_tag == "qr_tdm_sched":
            assert self.dvpad == "f"
            return f"a.hdim_v == {self.bn1}"
        else:
            assert False


@dataclass
class FmhaFwdPipeline:
    tag: str

    F_vlayout: str  # row/col
    F_spad: str  # true/false
    F_skpad: str  #
    F_dpad: str  #
    F_dvpad: str  #
    F_logits: str  # t/f
    F_bias: str  # true/false
    F_lse: str  #
    F_dropout: str  #
    F_qscale: str  # no/pertensor
    F_mask: str  # value from MASK_MAP
    F_sink: str  # t/f (StreamLLM sink tokens)
    F_kv_memory_layout: str  #
    F_kv_lookup_table: str  #
    F_constraint: CppConstraint = field(default_factory=lambda: CppConstraint())

    @property
    def name(self) -> str:
        def pad_name() -> str:
            n = ""
            if self.F_spad == "t":
                n += "s"
            if self.F_skpad == "t":
                n += "sk"
            if self.F_dpad == "t":
                n += "d"
            if self.F_dvpad == "t":
                n += "dv"
            if n != "":
                n = "p" + n
            return n

        pn = pad_name()
        n = f"{self.tag}_v{self.F_vlayout[0]}"
        if pn != "":
            n += f"_{pn}"
        else:
            n += "_npad"

        if self.F_logits == "t":
            n += "_logits"
        else:
            n += "_nlogits"

        if self.F_bias != "no":
            n += f"_{self.F_bias}"
        else:
            n += "_nbias"

        if self.F_mask[0:2] == "s_":
            if self.F_mask == "s_mask":
                n += "_mask"
            else:
                n += "_nmask"
        else:
            if self.F_mask != "no":
                n += f"_m{self.F_mask[0]}"
            else:
                n += "_nmask"

        if self.F_lse == "t":
            n += "_lse"
        else:
            n += "_nlse"

        if self.F_dropout == "t":
            n += "_dropout"
        else:
            n += "_ndropout"

        if self.F_qscale != "no":
            n += f"_{self.F_qscale}"
        else:
            n += "_nqscale"

        if self.F_sink == "t":
            n += "_sink"
        else:
            n += "_nsink"

        n += "_" + self.F_kv_memory_layout + "_" + self.F_kv_lookup_table
        return n


class FmhaFwdApiPool:
    def __init__(self, mask_impl):
        self.pool = dict()
        self.mask_impl = mask_impl

    def register_traits(self, trait: FmhaFwdApiTrait) -> None:
        # TODO: do we need to check duplication?
        if trait.dtype not in self.pool.keys():
            self.pool[trait.dtype] = dict()
        if trait.hdim not in self.pool[trait.dtype].keys():
            self.pool[trait.dtype][trait.hdim] = list()

        self.pool[trait.dtype][trait.hdim].append(copy.copy(trait))

    @property
    def api(self) -> str:
        per_dtypes = str()
        for i, dtype in enumerate(self.pool.keys()):
            per_hdim_case = str()
            # Ascending head dims: each case accepts t.hdim_q <= hdim.
            hdims = sorted(self.pool[dtype].keys(), key=int)
            for j, hdim in enumerate(hdims):
                traits = self.pool[dtype][hdim]
                inners = str()
                for k, trait in enumerate(traits):
                    if_k = "if" if k == 0 else "else if"
                    inners = inners + FMHA_FWD_API_INNER_DISPATCH.format(
                        F_if=if_k,
                        F_mode=MODE_MAP[trait.mode],
                        F_vlayout=LAYOUT_MAP[trait.vlayout],
                        F_pipeline_enum=PIPELINE_ENUM_MAP[trait.pipeline_tag],
                        F_logits=BOOL_MAP[trait.logits],
                        F_mask=get_mask_cpp_type(trait.mask),
                        F_mask_check=get_mask_cpp_check_expr(trait.mask),
                        F_bias_check=BIAS_CHECK_MAP[trait.bias],
                        F_bias=BIAS_MAP[trait.bias],
                        F_lse=BOOL_MAP[trait.lse],
                        F_dropout=BOOL_MAP[trait.dropout],
                        F_qscale_check=QSCALE_CHECK_MAP[trait.qscale],
                        F_qscale=QSCALE_MAP[trait.qscale],
                        F_scheck=trait.scheck,
                        F_skcheck=trait.skcheck,
                        F_dcheck=trait.dcheck,
                        F_dvcheck=trait.dvcheck,
                        F_constraint=trait.constraint,
                        F_arch_host=trait.arch_host,
                        F_spad=BOOL_MAP[trait.spad],
                        F_skpad=BOOL_MAP[trait.skpad],
                        F_dpad=BOOL_MAP[trait.dpad],
                        F_dvpad=BOOL_MAP[trait.dvpad],
                        F_bm0=trait.bm0,
                        F_bn0=trait.bn0,
                        F_bk0=trait.bk0,
                        F_bn1=trait.bn1,
                        F_bk1=trait.bk1,
                        F_bk0max=trait.bk0max,
                        F_occupancy=trait.occupancy,
                        F_hdim=hdim,
                        F_dtype=FWD_DTYPE_MAP[dtype],
                        F_kv_memory_layout=KV_MEMORY_LAYOUT_ENUM_MAP[
                            trait.kv_memory_layout
                        ],
                        F_kv_lookup_table=KV_LOOKUP_TABLE_ENUM_MAP[
                            trait.kv_lookup_table
                        ],
                        F_page_size=trait.page_size,
                        F_sink=BOOL_MAP[trait.sink],
                        F_kv_load_mode=KV_LOAD_MODE_ENUM_MAP[trait.use_global_load],
                        F_kv_load_mode_check=trait.kv_load_mode_check,
                        F_kv_splits_targ=kv_splits_targ(
                            trait.kv_splits, trait.query_tail_rows
                        ),
                    )
                if_j = "if" if j == 0 else "else if"
                per_hdim_case = per_hdim_case + FMHA_FWD_API_PER_HDIM_CASE.format(
                    F_if=if_j, F_hdim=hdim, F_hdim_v=trait.bn1, F_inner_dispatch=inners
                )
            if_i = "if" if i == 0 else "else if"
            uses_kv_load_mode = any(
                trait.pipeline_tag != "qr_tdm_sched"
                for traits in self.pool[dtype].values()
                for trait in traits
            )
            per_dtype = (
                FMHA_FWD_API_PER_DTYPE
                if uses_kv_load_mode
                else FMHA_BATCH_PREFILL_PAGE_TILE_API_PER_DTYPE
            )
            per_dtypes = per_dtypes + per_dtype.format(
                F_if=if_i,
                F_dtype=dtype,
                F_element_bytes=DTYPE_BYTES[dtype],
                F_hdim_case=per_hdim_case,
            )
        if not per_dtypes:
            # empty string we add some ignore to suppress warning in api
            per_dtypes += "    (void)t; (void)s; (void)a;"
        return FMHA_FWD_KERNEL_HEADER + FMHA_FWD_API.format(F_dispatch=per_dtypes)


@dataclass
class FmhaFwdTileSize:
    F_bm0: int  # tile size along q seqlen (block size)
    F_bn0: int  # tile size along k seqlen
    F_bk0: int  # tile size along qk gemm unroll
    F_bn1: int  # tile size along v head_dim
    F_bk1: int  # tile size along kv gemm unroll
    F_bk0max: int  # total length of K0, used for pipeline that need load Q at once (or repeately load Q as a whole tile)
    F_rm0: int  # number of warps for gemm0 along q seqlen
    F_rn0: int  # number of warps for gemm0 along k seqlen
    F_rk0: int  # number of warps for gemm0 along head dim q (not used)
    F_rm1: int  # number of warps for gemm1 along q seqlen
    F_rn1: int  # number of warps for gemm1 along head dim v
    F_rk1: int  # number of warps for gemm1 along k seqlen (not used)
    F_wm0: int  # gemm0 warp size along m
    F_wn0: int  # gemm0 warp size along n
    F_wk0: int  # gemm0 warp size along k
    F_wm1: int  # gemm1 warp size along m
    F_wn1: int  # gemm1 warp size along n
    F_wk1: int  # gemm1 warp size along k
    F_occupancy: int  # occupancy, -1 will let pipeline decide the occupancy, other value will overwrite occupancy
    F_constraint: CppConstraint = field(default_factory=lambda: CppConstraint())
    # Optional compile-time arch guard for this tile's device code. When set,
    # the kernel body is only instantiated during the device pass for matching
    # archs (host pass always keeps it so the host symbol still exists). This is
    # independent from F_constraint, which is a runtime dispatch predicate.
    F_arch: Optional[ArchTrait] = None
    # 2: the gfx125x page-tile KV split (partial kernel + merge); 1: one kernel.
    F_kv_splits: int = 1
    # > 0 (KV split only): query tail. F_main_tile runs each sequence's full tiles of this many
    # query rows, the KV split the rows past them, then the merge.
    F_query_tail_rows: int = 0
    F_main_tile: Optional["FmhaFwdTileSize"] = None

    @property
    def name(self) -> str:
        return (
            f"b{self.F_bm0}x{self.F_bn0}x{self.F_bk0}x{self.F_bn1}x{self.F_bk1}x{self.F_bk0max}"
            + f"_r{self.F_rm0}x{self.F_rn0}x{self.F_rk0}_r{self.F_rm1}x{self.F_rn1}x{self.F_rk1}"
            + f"_w{self.F_wm0}x{self.F_wn0}x{self.F_wk0}_w{self.F_wm1}x{self.F_wn1}x{self.F_wk1}"
            + ("" if self.F_occupancy == -1 else f"_o{self.F_occupancy}")
            + ("" if self.F_kv_splits == 1 else f"_ks{self.F_kv_splits}")
            + ("" if self.F_query_tail_rows == 0 else f"_qt{self.F_query_tail_rows}")
        )


@dataclass
class FmhaFwdKernel:
    F_idx: int  # this is not a tunable, but a counter to differentiate symbol
    F_hdim: int  # hdim
    F_dtype: str  # data type
    F_mode: str  # value from MODE_MAP
    F_tile: FmhaFwdTileSize
    F_pipeline: FmhaFwdPipeline
    mask_impl: str
    F_page_size: int = 1  # page block size
    F_use_global_load: bool = False  # use global_load_lds_* for >2GB KV cache

    @property
    def template(self) -> str:
        page_tile = self.F_pipeline.tag == "qr_tdm_sched"
        split = self.F_tile.F_kv_splits != 1
        tail = self.F_tile.F_query_tail_rows != 0
        assert not split or (page_tile and self.F_tile.F_kv_splits == 2)
        assert not tail or (split and self.F_tile.F_main_tile is not None)
        header = (
            FMHA_FWD_KERNEL_HEADER
            + (FMHA_BATCH_PREFILL_PAGE_TILE_INCLUDE if page_tile else "")
            + (FMHA_BATCH_PREFILL_SPLIT_MERGE_INCLUDE if split else "")
        )
        dtype = FWD_DTYPE_MAP[self.F_dtype]
        if tail:
            launch = FMHA_BATCH_PREFILL_PAGE_TILE_TAIL_LAUNCH.format(
                F_dtype=dtype, F_hdim=self.F_hdim, F_rows=self.F_tile.F_query_tail_rows
            )
        elif split:
            launch = FMHA_BATCH_PREFILL_PAGE_TILE_SPLIT_LAUNCH.format(
                F_dtype=dtype, F_hdim=self.F_hdim
            )
        elif page_tile:
            launch = FMHA_BATCH_PREFILL_PAGE_TILE_LAUNCH
        else:
            launch = FMHA_BATCH_PREFILL_LAUNCH
        fields = self._fields(launch)
        types = FMHA_FWD_KERNEL_TYPES.format(**fields)
        if tail:
            # The main kernel: the unsplit instance of F_main_tile.
            main = replace(self, F_idx=1, F_tile=self.F_tile.F_main_tile)
            types += FMHA_FWD_KERNEL_TYPES.format(**main._fields(""))
        return header + FMHA_FWD_KERNEL_BODY.format(
            F_arch_check=self._arch_check(),
            F_types=types,
            F_func=FMHA_FWD_KERNEL_FUNC.format(**fields),
        )

