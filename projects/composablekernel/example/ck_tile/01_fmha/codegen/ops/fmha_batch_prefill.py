def receipt_accepts(receipt, dtype: str, mode: str, pipeline: FmhaFwdPipeline) -> bool:
    # 2 - Flash attention integration
    if receipt in (2, 3):
        cond = dtype in ["fp16", "bf16"]
        cond &= pipeline.F_vlayout == "row"
        cond &= pipeline.F_bias in ["no", "alibi"]
        cond &= pipeline.F_qscale == "no"
        if not cond:
            return False
    # PyTorch integration
    elif receipt == 4:
        cond = dtype in ["fp16", "bf16"]
        cond &= pipeline.F_vlayout == "row"
        cond &= pipeline.F_bias in ["no", "bias"]
        cond &= pipeline.F_qscale == "no"
        if not cond:
            return False
    # Aiter(mha_fwd) integration
    elif receipt == 100:
        cond = dtype in ["fp16", "bf16"]
        cond &= mode == "batch"
        cond &= pipeline.F_vlayout == "row"
        cond &= pipeline.F_qscale == "no"
        if not cond:
            return False
    # Aiter(mha_batch_prefill) integration
    elif receipt == 200:
        cond = dtype in ["fp16", "bf16", "fp8bf16"]
        cond &= mode == "group"
        cond &= pipeline.F_vlayout == "row"
        if not cond:
            return False
    # aiter::mha_batch_prefill C++ api integration
    elif receipt == 600:
        cond = dtype in ["fp16", "bf16", "fp8bf16"]
        cond &= mode == "group"
        cond &= pipeline.F_vlayout == "row"
        cond &= pipeline.F_qscale == "no"
        if not cond:
            return False
    elif receipt == 700:
        return False  # TE does not use this API

    # fp32 only
    if receipt == 800 or receipt == 801:
        return dtype == "fp32"
    return True


class PageTileFactoryGfx125:
    """gfx125x page-tile kernel: BF16/FP16, D64/D128, linear or vectorized K/V pool, vLLM 2D or
    SGLang 1D page table, group mode, no mask or a causal/sliding window from either corner (optionally with sink
    tokens and per-head sink logits), optional tanh logits soft cap or elementwise bias or ALiBi,
    optional LSE."""

    arch = GFX125_ARCH

    # M64 tiles double the workgroups of grids that would place at most one M128
    # workgroup on each CU (measured on gfx1250 with 256 CUs: about 20 % less time on
    # such shapes). They come first, so the dispatch takes them while the constraint
    # holds and falls back to M128 otherwise. D64 M64 uses K64 PV stages (kK1 64, see
    # FmhaTdmSchedPolicyFor). P64 D64 M64 keeps a residual stale-fragment race on some
    # gfx1250 boards (see kDrainLdsBeforeTdmIssue).
    SMALL_GRID = CppConstraint("get_num_blocks(128) <= num_cus")

    # KV split (kKvSplits 2: partial kernel + merge), only with the caller's workspace.
    # The rule of the measured configuration on a 256-CU gfx1250, with
    # WG = get_num_blocks(128) (M128 workgroups) and KV = a.seqlen_k; the split arms
    # come first in their case, in this order:
    #   M128 tiles: KV >= 16384 and (128 < WG <= 256, or D64 with 512 < WG <= 576 and a
    #     partial last query tile), not for P128 D128; no mask, or a bottom-right mask
    #     without a left window (the kernel shifts the window of each split);
    #   M64 tiles, no mask: KV >= 4096 and (WG <= 128, or D64 with 512 < WG <= 576 and
    #     KV >= 16384).
    # The thresholds are written in CUs (num_cus = 256 there).
    WORKSPACE = "a.o_acc_ptr != nullptr && a.lse_acc_ptr != nullptr"
    WG = "get_num_blocks(128)"
    WG_256 = f"num_cus < 2 * {WG} && {WG} <= num_cus"
    WG_576 = f"2 * num_cus < {WG} && 4 * {WG} <= 9 * num_cus"
    SPLIT_MASK = (
        "t.mask_type == mask_enum::no_mask || "
        "(t.mask_type == mask_enum::mask_bottom_right && a.window_size_left < 0)"
    )
    SPLIT_M128_D64 = CppConstraint(
        f"{WORKSPACE} && ({SPLIT_MASK}) && a.seqlen_k >= 16384 && "
        f"(({WG_256}) || ({WG_576} && a.max_seqlen_q % 128 != 0))"
    )
    SPLIT_M128_D128 = CppConstraint(
        f"{WORKSPACE} && ({SPLIT_MASK}) && a.seqlen_k >= 16384 && {WG_256}"
    )
    SPLIT_M64_D64 = CppConstraint(
        f"{WORKSPACE} && a.seqlen_k >= 4096 && "
        f"(2 * {WG} <= num_cus || ({WG_576} && a.seqlen_k >= 16384))"
    )
    SPLIT_M64_D128 = CppConstraint(
        f"{WORKSPACE} && a.seqlen_k >= 4096 && 2 * {WG} <= num_cus"
    )
    # Query tail (D128 P64, one sequence; masked: as the M128 split): KV >= 16384 and
    # 512 < WG <= 576 with a partial last query tile. M128 tiles run the full query tiles, the
    # KV split (M64 tiles) the rows past them.
    TAIL_D128 = CppConstraint(
        f"{WORKSPACE} && a.batch == 1 && ({SPLIT_MASK}) && a.seqlen_k >= 16384 && "
        f"{WG_576} && a.max_seqlen_q % 128 != 0"
    )

    @staticmethod
    def get_hdim_tile_size_dict(dtype: str) -> Optional[dict]:
        if dtype in ["fp16", "bf16"]:
            F = PageTileFactoryGfx125
            small = F.SMALL_GRID
            m128_d128 = FmhaFwdTileSize(128, 128, 32, 128, 32, 128,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F_arch=GFX125_ARCH)  # fmt: skip
            return {
                64  : [FmhaFwdTileSize(128, 128, 32,  64, 32,  64,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F.SPLIT_M128_D64, GFX125_ARCH, 2),
                       FmhaFwdTileSize( 64, 128, 32,  64, 64,  64,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F.SPLIT_M64_D64, GFX125_ARCH, 2),
                       FmhaFwdTileSize( 64, 128, 32,  64, 64,  64,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, small, GFX125_ARCH),
                       FmhaFwdTileSize(128, 128, 32,  64, 32,  64,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F_arch=GFX125_ARCH)],
                128 : [FmhaFwdTileSize(128, 128, 32, 128, 32, 128,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F.SPLIT_M128_D128, GFX125_ARCH, 2),
                       FmhaFwdTileSize( 64, 128, 32, 128, 32, 128,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F.SPLIT_M64_D128, GFX125_ARCH, 2),
                       FmhaFwdTileSize( 64, 128, 32, 128, 32, 128,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, F.TAIL_D128, GFX125_ARCH, 2, 128, m128_d128),
                       FmhaFwdTileSize( 64, 128, 32, 128, 32, 128,  4, 1, 1,  4, 1, 1,  16, 16, 32,  16, 16, 32,  1, small, GFX125_ARCH),
                       m128_d128],
            }  # fmt: skip
        else:
            return None

    @staticmethod
    def accepts(
        dtype: str, tile: FmhaFwdTileSize, pipeline: FmhaFwdPipeline, page_size: int
    ) -> bool:
        # M64 and KV-split tiles only for the measured and tested set: BF16, vectorized
        # K/V with the vLLM block table, P64/P128 pages, no sink, bias, soft cap or LSE;
        # the M64 split for the unmasked case only, the M128 split not for P128 D128, the
        # query tail for P64 only.
        if tile.F_bm0 != 64 and tile.F_kv_splits == 1:
            return True
        measured_set = (
            dtype == "bf16"
            and page_size in (64, 128)
            and pipeline.F_kv_memory_layout == "vectorized"
            and pipeline.F_kv_lookup_table == "vllm"
            and pipeline.F_sink == "f"
            and pipeline.F_bias == "no"
            and pipeline.F_logits == "f"
            and pipeline.F_lse == "f"
        )
        if tile.F_kv_splits == 1:
            return measured_set
        if tile.F_query_tail_rows != 0:
            return measured_set and page_size == 64
        if tile.F_bm0 == 64:
            return measured_set and pipeline.F_mask == "s_no"
        return measured_set and not (page_size == 128 and tile.F_bn1 == 128)

    @staticmethod
    def get_pipelines(dtype, hdim, receipt, mask_impl) -> List[FmhaFwdPipeline]:
        # Simplified masks whatever mask_impl is: the kernel's stored-row mask predicate needs
        # them. The masked arm takes any window (causal, sliding, local) from either corner, like
        # the simplified-mask dispatch of the gfx9 kernels.
        pipelines = []
        for (
            logits,
            mask,
            bias,
            lse,
            sink,
            kv_memory_layout,
            kv_lookup_table,
        ) in itertools.product(
            ["t", "f"],
            ["s_no", "s_mask"],
            ["no", "bias", "alibi"],
            ["t", "f"],
            ["t", "f"],
            SUPPORTED_KV_MEMORY_LAYOUT,
            SUPPORTED_KV_LOOKUP_TABLE,
        ):
            # Sink tokens and sink logits share the sink instance and need a mask, as for gfx9.
            if sink == "t" and mask == "s_no":
                continue
            # The logits soft cap applies to unbiased scores, as for gfx9.
            if logits == "t" and bias != "no":
                continue
            pipelines.append(FmhaFwdPipeline("qr_tdm_sched", "row", "t", "t", "f", "f", logits, bias, lse, "f", "no", mask, sink, kv_memory_layout, kv_lookup_table))  # fmt: skip
        return pipelines


def get_fwd_blobs(
    kernel_filter: Optional[str],
    receipt,
    optdim_list,
    mask_impl,
    targets: Optional[List[str]] = None,
) -> Tuple[FmhaFwdApiPool, List[FmhaFwdKernel]]:
    # The gfx9 batch_prefill pipeline uses gfx9-specific async scatter-gather buffer addressing
    # (amd_buffer_addressing.hpp raw buffer loads) that is not compatible with
    # non-gfx9 architectures (gfx11/gfx12/gfx10 are wave32 and use different
    # buffer instruction formats). gfx125x uses the TDM page-tile kernel instead; any other
    # target gets no batch_prefill kernels.
    target_list = targets if targets is not None else ["gfx9"]
    has_gfx9 = any(t.startswith("gfx9") for t in target_list)
    has_page_tile = any(t.startswith(GFX125_ARCH.name) for t in target_list)
    has_unsupported = any(
        not (t.startswith("gfx9") or t.startswith(GFX125_ARCH.name))
        for t in target_list
    )
    # TODO: we don't support tuning yet, so pick up one value for vlayout/pipeline/pad
    #       support this in future

    gen = list()
    api_pool = FmhaFwdApiPool(mask_impl)

    if has_unsupported:
        return api_pool, gen

    for dtype in FWD_DTYPE_MAP.keys() if has_gfx9 else []:
        d = CustomFactory.get_hdim_tile_size_dict(dtype)
        if d is None:
            continue
        # for hdim_str, mode, mask, bias, lse in itertools.product(d.keys(), MODE_MAP.keys(), MASK_MAP.keys(), ["t", "f"], ["t", "f"]):
        for (hdim, tiles), mode in itertools.product(d.items(), MODE_MAP.keys()):
            # batch_prefill pipeline requires group mode (static_assert in pipeline problem)
            if mode != "group":
                continue
            if has_page_tile:
                # Keep the gfx9 kernels out of the gfx125x device pass and host dispatch.
                tiles = [
                    tile if tile.F_arch is not None else replace(tile, F_arch=GFX9_ARCH)
                    for tile in tiles
                ]
            for tile, pipeline in itertools.product(
                tiles, CustomFactory.get_pipelines(dtype, hdim, receipt, mask_impl)
            ):
                if mode == "group":
                    if pipeline.F_spad != "t" or pipeline.F_skpad != "t":
                        # in group mode, spad/skpad must be true, since we can't predict if seqlen of current batch need pad or not
                        continue
                if hdim == 192 and tile.F_bn1 == 128:
                    # NOTE: this is used to speedup deepseek prefill case, we don't gen training
                    if (
                        pipeline.F_bias != "no"
                        or pipeline.F_lse == "t"
                        or pipeline.F_dropout == "t"
                    ):
                        continue
                # logits_soft_cap is only allowed if no bias
                if not (
                    (pipeline.F_logits == "t" and pipeline.F_bias == "no")
                    or pipeline.F_logits == "f"
                ):
                    continue

                # Generate kernels for both page_size=16 and page_size=1024
                for page_size in SUPPORTED_PAGE_SIZE:
                    if page_size == 1 and pipeline.F_kv_memory_layout != "linear":
                        continue
                    # kv_blockscale requires page_size >= kN0 (tile.F_bn0)
                    # This ensures all tokens in a main loop iteration belong to the same page
                    if pipeline.F_qscale == "kv_blockscale" and page_size < tile.F_bn0:
                        continue
                    k = FmhaFwdKernel(
                        F_idx=0,
                        F_hdim=hdim,
                        F_dtype=dtype,
                        F_mode=mode,
                        F_tile=tile,
                        F_pipeline=pipeline,
                        mask_impl=mask_impl,
                        F_page_size=page_size,
                    )
                    if kernel_filter != "":
                        if not fnmatch.fnmatch(k.name, kernel_filter):
                            continue
                    if optdim_list != [-1]:
                        if hdim not in optdim_list:
                            continue
                    if not receipt_accepts(receipt, dtype, mode, pipeline):
                        continue

                    api_pool.register_traits(k.api_trait())
                    gen.append(k)

                    # For page_size < kN0 (tile.F_bn0), also generate a GLOBAL_LOAD_LDS
                    # variant for >2GB KV cache support. The default (BUFFER_LOAD) uses SRD
                    # buffer_load (fast, <2GB). GLOBAL_LOAD_LDS uses global_load_lds_*
                    # (slower, handles >2GB).
                    if page_size < tile.F_bn0:
                        k_global_load = FmhaFwdKernel(
                            F_idx=0,
                            F_hdim=hdim,
                            F_dtype=dtype,
                            F_mode=mode,
                            F_tile=tile,
                            F_pipeline=pipeline,
                            mask_impl=mask_impl,
                            F_page_size=page_size,
                            F_use_global_load=True,
                        )
                        api_pool.register_traits(k_global_load.api_trait())
                        gen.append(k_global_load)

    for dtype in FWD_DTYPE_MAP.keys() if has_page_tile else []:
        d = PageTileFactoryGfx125.get_hdim_tile_size_dict(dtype)
        if d is None:
            continue
        for hdim, tiles in d.items():
            pipelines = PageTileFactoryGfx125.get_pipelines(
                dtype, hdim, receipt, mask_impl
            )
            for tile, pipeline, page_size in itertools.product(
                tiles, pipelines, PAGE_TILE_SUPPORTED_PAGE_SIZE
            ):
                if not PageTileFactoryGfx125.accepts(dtype, tile, pipeline, page_size):
                    continue
                k = FmhaFwdKernel(
                    F_idx=0,
                    F_hdim=hdim,
                    F_dtype=dtype,
                    F_mode="group",
                    F_tile=tile,
                    F_pipeline=pipeline,
                    mask_impl=mask_impl,
                    F_page_size=page_size,
                )
                if kernel_filter != "":
                    if not fnmatch.fnmatch(k.name, kernel_filter):
                        continue
                if optdim_list != [-1]:
                    if hdim not in optdim_list:
                        continue
                if not receipt_accepts(receipt, dtype, "group", pipeline):
                    continue
                api_pool.register_traits(k.api_trait())
                gen.append(k)

    return (api_pool, gen)


def write_single_fwd_kernel(kernel: FmhaFwdKernel, autogen_dir: Path) -> None:
    update_file(autogen_dir / kernel.filename, kernel.template)


def write_fwd_api(api_pool: FmhaFwdApiPool, autogen_dir: Path) -> None:
    update_file(autogen_dir / FMHA_FWD_API_FILENAME, api_pool.api)


def write_blobs(
    targets: List[str],
    output_dir: Path,
    kernel_filter: str,
    receipt,
    optdim_list,
    mask_impl,
) -> None:
    api_pool, kernels = get_fwd_blobs(
        kernel_filter, receipt, optdim_list, mask_impl, targets
    )
    for kernel in kernels:
        write_single_fwd_kernel(kernel, output_dir)
    write_fwd_api(api_pool, output_dir)


def list_blobs(
    targets: List[str],
    file_path: Path,
    kernel_filter: str,
    receipt,
    optdim_list,
    mask_impl,
) -> None:
    with file_path.open("a") as f:
        _, kernels = get_fwd_blobs(
            kernel_filter, receipt, optdim_list, mask_impl, targets
        )
        for kernel in kernels:
            f.write((file_path.parent / GEN_DIR / kernel.filename).as_posix() + "\n")
        f.write((file_path.parent / GEN_DIR / FMHA_FWD_API_FILENAME).as_posix() + "\n")
