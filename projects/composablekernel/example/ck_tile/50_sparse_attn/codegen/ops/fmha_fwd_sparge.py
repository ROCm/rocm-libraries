class KernelComponentFactory:
    @staticmethod
    def get_hdim_tile_size_dict(dtype: str) -> Optional[dict]:
        if dtype == "fp16" or dtype == "bf16":
            return {
                (128, 128): [
                    FmhaFwdTileSize(
                        128,
                        128,
                        32,
                        128,
                        32,
                        128,
                        4,
                        1,
                        1,
                        4,
                        1,
                        1,
                        32,
                        32,
                        16,
                        32,
                        32,
                        16,
                        -1,
                    ),
                ],
            }
        else:
            return None

    @staticmethod
    def get_pipelines(dtype, hdim, hdim_v, receipt, mask_impl) -> List[FmhaFwdPipeline]:
        pipelines = []
        # ALIBI requires causal context; logits soft-cap requires NO_BIAS (pipeline static_assert).
        bias_modes = ["no", "elementwise", "alibi"]
        if dtype in ["fp16", "bf16"]:
            for logits, mask, bias in itertools.product(
                ["f", "t"],
                get_mask_map(mask_impl).keys(),
                bias_modes,
            ):
                if bias == "alibi" and mask in ("no", "s_no"):
                    continue
                pipelines.append(
                    FmhaFwdPipeline(
                        "qr_async_sparge",
                        "row",
                        "t",
                        "f",
                        "t",
                        "t",
                        logits,
                        mask,
                        F_bias=bias,
                    )
                )
                pipelines.append(
                    FmhaFwdPipeline(
                        "qr_async_sparge",
                        "row",
                        "t",
                        "t",
                        "t",
                        "t",
                        logits,
                        mask,
                        F_bias=bias,
                    )
                )
        else:
            assert False, f"unsupported dtype for sparge: {dtype}"
        return pipelines


def get_fwd_blobs(
    kernel_filter: Optional[str], receipt, optdim_list, mask_impl
) -> Tuple[FmhaFwdApiPool, List[FmhaFwdKernel]]:
    gen = list()
    api_pool = FmhaFwdApiPool(mask_impl)

    factory = KernelComponentFactory

    del receipt
    for dtype in ["fp16", "bf16"]:
        d = factory.get_hdim_tile_size_dict(dtype)
        if d is None:
            continue
        for ((hdim, hdim_v), tiles), mode in itertools.product(d.items(), MODE_MAP.keys()):
            for tile, pipeline in itertools.product(
                tiles, factory.get_pipelines(dtype, hdim, hdim_v, 0, mask_impl)
            ):
                k = FmhaFwdKernel(
                    F_idx=2,
                    F_hdim=hdim,
                    F_dtype=dtype,
                    F_mode=mode,
                    F_tile=tile,
                    F_pipeline=pipeline,
                    mask_impl=mask_impl,
                )
                if kernel_filter != "":
                    if not fnmatch.fnmatch(k.name, kernel_filter):
                        continue
                if optdim_list != [-1]:
                    if hdim not in optdim_list:
                        continue
                api_pool.register_traits(k.api_trait())
                gen.append(k)

    return (api_pool, gen)


def write_single_fwd_kernel(kernel: FmhaFwdKernel, autogen_dir: Path) -> None:
    update_file(autogen_dir / kernel.filename, kernel.template)


def write_fwd_api(api_pool: FmhaFwdApiPool, autogen_dir: Path) -> None:
    update_file(autogen_dir / FMHA_FWD_API_FILENAME, api_pool.api)


def write_blobs(
    output_dir: Path, kernel_filter: str, receipt, optdim_list, mask_impl
) -> None:
    api_pool, kernels = get_fwd_blobs(kernel_filter, receipt, optdim_list, mask_impl)
    for kernel in kernels:
        write_single_fwd_kernel(kernel, output_dir)
    write_fwd_api(api_pool, output_dir)


def list_blobs(
    file_path: Path, kernel_filter: str, receipt, optdim_list, mask_impl
) -> None:
    with file_path.open("a") as f:
        _, kernels = get_fwd_blobs(kernel_filter, receipt, optdim_list, mask_impl)
        for kernel in kernels:
            f.write(str(file_path.parent / GEN_DIR / kernel.filename) + "\n")
        f.write(str(file_path.parent / GEN_DIR / FMHA_FWD_API_FILENAME) + "\n")
