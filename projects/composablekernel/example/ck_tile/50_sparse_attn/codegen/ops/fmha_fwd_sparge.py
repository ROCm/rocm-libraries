@dataclass
class CppConstraint:
    bool_expr: str = None

    def __str__(self):
        if self.bool_expr is None:
            return "true"
        else:
            return f"{self.bool_expr}"

    def __and__(self, other):
        return CppConstraint(f"({str(self)}) && ({str(other)})")


@dataclass
class FmhaFwdApiTrait:
    pipeline_tag: str
    hdim: str
    dtype: str
    mode: str
    bm0: int
    bn0: int
    bk0: int
    bn1: int
    bk1: int
    bk0max: int
    vlayout: str
    logits: str
    mask: str
    bias: str
    spad: str
    skpad: str
    dpad: str
    dvpad: str
    constraint: CppConstraint

    @property
    def name(self) -> str:
        return (
            f"{self.hdim}-{self.dtype}-{self.mode}-{self.bm0}-{self.bn0}-{self.bk0}-{self.bn0}-{self.bk1}-{self.bk0max}-"
            + f"{self.vlayout}-{self.logits}-{self.mask}-{self.bias}-{self.spad}-{self.skpad}-{self.dpad}-{self.dvpad}"
        )

    @property
    def scheck(self) -> str:
        return "true"

    @property
    def seqtune(self) -> str:
        if self.bm0 == 128:
            return "true/*fall back to largest tile*/"
        else:
            return f"a.seqlen_q <= {self.bm0}"

    @property
    def skcheck(self) -> str:
        if self.skpad == "t":
            return f"a.seqlen_k == 0 || a.seqlen_k % {self.bn0} != 0"
        return f"a.seqlen_k != 0 && a.seqlen_k % {self.bn0} == 0"

    @property
    def dcheck(self) -> str:
        vec = int((32 * 4) / DTYPE_BITS[self.dtype])
        return f"a.hdim_q % {vec} == 0"

    @property
    def dvcheck(self) -> str:
        vec = int((32 * 4) / DTYPE_BITS[self.dtype])
        return f"a.hdim_v % {vec} == 0"


