def _main(argv) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Golden byte-file harness for the quant GEMM code generators."
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help="Regenerate the golden .hpp fixtures and manifest.json from the "
        "current generators, then exit.",
    )
    args = parser.parse_args(argv)

    if args.update:
        n = regenerate_goldens()
        uniq = len(list(_HPP_DIR.glob(f"*{_FIXTURE_EXT}")))
        print(
            f"Regenerated quant goldens: {n} matrix cases, {uniq} unique "
            f"{_FIXTURE_EXT} files under {_HPP_DIR}"
        )
        tn = regenerate_tripwire_goldens()
        tuniq = len(list(_TRIPWIRE_HPP_DIR.glob(f"*{_FIXTURE_EXT}")))
        print(
            f"Regenerated tripwire goldens: {tn} cases, {tuniq} unique "
            f"{_FIXTURE_EXT} files under {_TRIPWIRE_HPP_DIR}"
        )
        return 0

    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))
