# Matrix assembly
# --------------------------------------------------------------------------- #


def _default_config_factories(mod):
    """Return the sorted ``default_*_config`` callables exported by ``mod``."""
    names = [
        n
        for n in dir(mod)
        if n.startswith("default_")
        and n.endswith("_config")
        and callable(getattr(mod, n))
    ]
    return sorted(names)


def build_matrix():
    """Assemble the deterministic (module, factory, arch) case matrix.

    Yields dicts with everything a case needs: a stable ``case_id``, the
    codegen script path, the exact codegen-config dict, and the config's
    ``name`` (which is also the ``.hpp`` stem the generator writes).
    """
    cases = []
    for module_name in _UTILS_MODULES:
        mod = import_module(module_name)
        script = Path(getattr(mod, "_CODEGEN_SCRIPT"))
        for factory in _default_config_factories(mod):
            fn = getattr(mod, factory)
            for arch in _ARCHES:
                cfg = fn(gfx_arch=arch)
                cases.append(
                    {
                        "case_id": f"{module_name}::{factory}::{arch}",
                        "module": module_name,
                        "factory": factory,
                        "arch": arch,
                        "script": script,
                        "config_name": cfg.name,
                        "config": cfg.to_codegen_config(),
                    }
                )
    # Stable order regardless of dir()/import ordering quirks.
    cases.sort(key=lambda c: c["case_id"])
    return cases


def _config_json(config: dict) -> str:
    """Canonical (sorted-key) JSON for a codegen-config dict."""
    return json.dumps(config, sort_keys=True)


def generate_hpp_bytes(script: Path, config: dict, config_name: str) -> bytes:
    """Invoke a ``unified_*_codegen.py`` for one config; return the .hpp bytes.

    The generator CLI is identical across all eight scripts::

        python <script> --output-dir <dir> --config-json <json>

    and writes ``<dir>/<config_name>.hpp``.  Pure Python, no GPU needed.
    """
    with tempfile.TemporaryDirectory(prefix="ck_codegen_golden_") as td:
        cmd = [
            sys.executable,
            str(script),
            "--output-dir",
            td,
            "--config-json",
            _config_json(config),
        ]
        result = subprocess.run(
            cmd, capture_output=True, text=True, timeout=_CODEGEN_TIMEOUT
        )
        if result.returncode != 0:
            raise RuntimeError(
                f"codegen failed ({script.name}, {config_name}):\n{result.stderr}"
            )
        hpp = Path(td) / f"{config_name}.hpp"
        if not hpp.exists():
            raise RuntimeError(
                f"codegen produced no {config_name}.hpp ({script.name})\n"
                f"stderr:\n{result.stderr}"
            )
        return hpp.read_bytes()


# --------------------------------------------------------------------------- #
# Golden regeneration (also the module's __main__ --update entrypoint)
# --------------------------------------------------------------------------- #


def regenerate_goldens() -> int:
    """(Re)write every golden fixture and ``manifest.json``.  Returns case count.

    Fixtures are written with the ``.hpp.golden`` extension (see ``_FIXTURE_EXT``)
    so the CK CI clang-format sweep skips them.  Removes any stale fixtures first
    so a deleted/renamed kernel can't leave an orphan behind, then writes each
    unique kernel body once and records all cases in the manifest.
    """
    _HPP_DIR.mkdir(parents=True, exist_ok=True)

    for stale in _HPP_DIR.glob(f"*{_FIXTURE_EXT}"):
        stale.unlink()

    cases = build_matrix()
    manifest = {
        "_comment": (
            "Golden byte-hashes for the block-scale quant GEMM code generators. "
            "Regenerate intentionally with: python3 tests/test_codegen_golden.py "
            "--update"
        ),
        "arches": list(_ARCHES),
        "modules": list(_UTILS_MODULES),
        "case_count": len(cases),
        "cases": {},
    }

    written_hpp: dict = {}
    for case in cases:
        data = generate_hpp_bytes(case["script"], case["config"], case["config_name"])
        sha = hashlib.sha256(data).hexdigest()

        name = case["config_name"]
        prev = written_hpp.get(name)
        if prev is None:
            (_HPP_DIR / f"{name}{_FIXTURE_EXT}").write_bytes(data)
            written_hpp[name] = sha
        elif prev != sha:
            # Two cases share a config_name but produce different bytes: the
            # fixture filename can't disambiguate them.  This must never happen; if
            # it does, the naming contract is broken and we fail loudly.
            raise RuntimeError(
                f"config_name collision with differing bytes: {name} "
                f"(case {case['case_id']})"
            )

        manifest["cases"][case["case_id"]] = {
            "module": case["module"],
            "factory": case["factory"],
            "arch": case["arch"],
            "config_name": name,
            "sha256": sha,
            "config": case["config"],
        }

    _MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return len(cases)


def _load_manifest() -> dict:
    if not _MANIFEST.exists():
        raise FileNotFoundError(
            f"golden manifest missing: {_MANIFEST}\n"
            "Generate it with: python3 tests/test_codegen_golden.py --update"
        )
    return json.loads(_MANIFEST.read_text())


