_DISP = Path(__file__).resolve().parent.parent
_PY_DIR = _DISP / "python"
_CODEGEN_DIR = _DISP / "codegen"
for _p in (_PY_DIR, _CODEGEN_DIR):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

# On-disk fixture extension.  Deliberately NOT ``.hpp`` (nor any of the other
# C/C++ suffixes the CK CI "Static checks" clang-format sweep globs for:
# .h/.hpp/.cpp/.h.in/.hpp.in/.cpp.in/.inc/.cl) so CI never flags or reformats
# these generated goldens -- reformatting would break the byte-identity the
# test asserts.  The logical kernel name (the manifest key / stem) is unchanged;
# only the file suffix differs.
_FIXTURE_EXT = ".hpp.golden"

_GOLDEN_DIR = Path(__file__).resolve().parent / "golden" / "codegen"
_HPP_DIR = _GOLDEN_DIR / "hpp"
_MANIFEST = _GOLDEN_DIR / "manifest.json"

# --------------------------------------------------------------------------- #
# NON-QUANT TRIPWIRE (see the big block comment above the tripwire matrix
# further down).  Its goldens live in a *separate* subdir so they never mix
# with the quant goldens above.
# --------------------------------------------------------------------------- #

_TRIPWIRE_DIR = _GOLDEN_DIR / "tripwire"
_TRIPWIRE_HPP_DIR = _TRIPWIRE_DIR / "hpp"
_TRIPWIRE_MANIFEST = _TRIPWIRE_DIR / "manifest.json"

# The eight utils modules that own the eight generators.  Sorted for a stable
# walk order.
_UTILS_MODULES = (
    "gemm_aquant_utils",
    "gemm_abquant_utils",
    "gemm_bquant_utils",
    "gemm_rowcolquant_utils",
    "gemm_tensor_quant_utils",
    "grouped_gemm_aquant_utils",
    "grouped_gemm_abquant_utils",
    "grouped_gemm_bquant_utils",
)

# The two arches whose divergent arch-derived warp_tile_k is the key branch.
_ARCHES = ("gfx942", "gfx950")

_CODEGEN_TIMEOUT = 180


