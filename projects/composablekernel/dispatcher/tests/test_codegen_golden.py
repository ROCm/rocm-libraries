def _matrix_ids_and_cases():
    cases = build_matrix()
    return [c["case_id"] for c in cases], cases


_IDS, _CASES = _matrix_ids_and_cases()


def test_manifest_matches_matrix():
    """The frozen manifest must describe exactly the current config matrix.

    Catches a factory being added/removed/renamed (a change to the set of
    generated kernels) even before any byte comparison runs.
    """
    manifest = _load_manifest()
    frozen = set(manifest["cases"])
    live = {c["case_id"] for c in _CASES}
    missing = frozen - live
    extra = live - frozen
    assert not missing, (
        "goldens describe cases no longer in the matrix (regenerate goldens): "
        f"{sorted(missing)}"
    )
    assert not extra, (
        "matrix has cases with no golden (regenerate goldens): "
        f"{sorted(extra)}"
    )


@pytest.mark.parametrize("case", _CASES, ids=_IDS)
def test_codegen_bytes_match_golden(case):
    """Regenerated .hpp bytes must be byte-identical to the golden fixture."""
    manifest = _load_manifest()
    entry = manifest["cases"].get(case["case_id"])
    assert entry is not None, (
        f"no golden for {case['case_id']} -- regenerate goldens"
    )

    # 1) The (factory, arch) -> config_name mapping must be stable.
    assert entry["config_name"] == case["config_name"], (
        f"{case['case_id']}: config name drifted\n"
        f"  golden: {entry['config_name']}\n"
        f"  now:    {case['config_name']}"
    )
    # 2) The codegen-config dict fed to the generator must be stable.
    assert entry["config"] == case["config"], (
        f"{case['case_id']}: codegen-config dict drifted\n"
        f"  golden: {_config_json(entry['config'])}\n"
        f"  now:    {_config_json(case['config'])}"
    )

    golden_hpp = _HPP_DIR / f"{case['config_name']}{_FIXTURE_EXT}"
    assert golden_hpp.exists(), (
        f"golden fixture missing: {golden_hpp} -- regenerate goldens"
    )
    golden_bytes = golden_hpp.read_bytes()

    # 3) The sha256 recorded in the manifest must match the stored .hpp.
    stored_sha = hashlib.sha256(golden_bytes).hexdigest()
    assert stored_sha == entry["sha256"], (
        f"{case['case_id']}: manifest sha256 disagrees with stored "
        f"{golden_hpp.name} (corrupt/edited fixture) -- regenerate goldens"
    )

    # 4) The freshly generated bytes must equal the golden bytes.
    fresh_bytes = generate_hpp_bytes(
        case["script"], case["config"], case["config_name"]
    )
    if fresh_bytes != golden_bytes:
        diff = "\n".join(
            difflib.unified_diff(
                golden_bytes.decode("utf-8", "replace").splitlines(),
                fresh_bytes.decode("utf-8", "replace").splitlines(),
                fromfile=f"golden/{case['config_name']}{_FIXTURE_EXT}",
                tofile=f"generated/{case['config_name']}.hpp",
                lineterm="",
                n=3,
            )
        )
        snippet = "\n".join(diff.splitlines()[:60])
        pytest.fail(
            f"{case['case_id']}: generated bytes differ from golden "
            f"({case['config_name']}.hpp)\n"
            f"golden sha256={entry['sha256']}\n"
            f"fresh  sha256={hashlib.sha256(fresh_bytes).hexdigest()}\n"
            f"--- unified diff (first 60 lines) ---\n{snippet}"
        )


def test_generation_is_deterministic():
    """Re-running one generator twice yields byte-identical output.

    A cheap direct guard that the codegen path itself has no run-to-run
    nondeterminism (ordering, hashing, temp-path leakage) independent of the
    stored goldens.
    """
    case = _CASES[0]
    a = generate_hpp_bytes(case["script"], case["config"], case["config_name"])
    b = generate_hpp_bytes(case["script"], case["config"], case["config_name"])
    assert a == b, f"{case['case_id']}: codegen is nondeterministic"


# =========================================================================== #
# NON-QUANT TRIPWIRE
# =========================================================================== #
#
# Why this section exists
# -----------------------
# A follow-up refactor will fold the eight QUANT generators (exercised above)
# into a single quant-only engine.  That refactor MUST NOT change the behavior
# of the shared ``codegen/codegen_common.py`` module, because three NON-quant
# generators import it and depend on it:
#
#     unified_gemm_codegen.py          (gemm_universal)  -- heaviest user:
#         imports TileConfig, TraitConfigBase, CommonTypeMappings and drives
#         the kernel-name / namespace / header-preamble build through them.
#     unified_grouped_conv_codegen.py  (grouped conv)    -- imports TileConfig,
#         TraitConfigBase, parallel_generate.
#     codegen/fmha/codegen.py          (FMHA)            -- imports
#         parallel_generate (the shared fan-out helper).
#
# This section freezes golden bytes for those generators so that if the quant
# refactor accidentally perturbs anything shared in codegen_common (name
# formatting, TileConfig/TraitConfig semantics, the type maps, or the
# parallel_generate contract), one of these non-quant goldens drifts and the
# suite fails -- the tripwire.
#
# Two extra generators are covered as cheap bonus coverage even though they do
# NOT import codegen_common (they are fully independent):
#
#     unified_mx_gemm_codegen.py            (mx_gemm)
#     unified_batched_contraction_codegen.py(batched_contraction)
#
# They are driven exactly like the quant generators (a ``default_*_config``
# factory -> ``to_codegen_config()`` -> ``--config-json`` -> ``<name>.hpp``),
# so they come almost for free.
#
# Config sourcing (same discipline as the quant matrix)
# -----------------------------------------------------
# Every tripwire config is a real, valid config taken from the way each
# generator is actually invoked:
#   * mx_gemm / batched_contraction: the shipped ``default_*_config`` factories
#     in ``python/<op>_utils.py`` (identical mechanism to the quant families).
#   * gemm_universal: the generator's own ``--tile-config-json`` single-kernel
#     path, fed tile/trait dicts drawn from ``codegen/default_config.json``.
#   * grouped conv: the generator's own individual-kernel CLI (``--tile-m`` ...)
#     with the tile shape its ``main()`` documents as defaults.
#   * FMHA: the ``FmhaKernelConfig`` dataclass defaults in ``python/fmha_utils.py``
#     (its ``to_codegen_json()`` is what production uses to invoke the codegen).
#
# Determinism note for the directory-writing generators
# -----------------------------------------------------
# gemm_universal, grouped conv and FMHA write into an output *directory* using a
# generator-derived filename (not necessarily equal to any ``config_name`` we
# hold).  For FMHA in particular the emitted stem is canonicalized with a config
# hash.  So for these three we DISCOVER the single top-level kernel ``.hpp`` the
# generator emits (ignoring ``dispatcher_wrappers/``, ``register_all_*`` and
# ``include_all_*`` aggregation files) and record that emitted stem in the
# manifest -- a filename drift is therefore also caught.  With an explicit tile
# config the emitted bytes are arch-independent, so these cases pin a single
# arch each rather than a redundant arch cross-product.
# --------------------------------------------------------------------------- #

# Tile/trait dicts lifted from codegen/default_config.json (single-value lists
# select exactly one kernel on the generator's --tile-config-json path).
_GU_TILE_16 = {
    "tile_m": [128], "tile_n": [128], "tile_k": [32],
    "warp_m": [2], "warp_n": [2], "warp_k": [1],
    "warp_tile_m": [16], "warp_tile_n": [16], "warp_tile_k": [16],
}
_GU_TILE_32 = {
    "tile_m": [128], "tile_n": [128], "tile_k": [64],
    "warp_m": [2], "warp_n": [2], "warp_k": [1],
    "warp_tile_m": [32], "warp_tile_n": [32], "warp_tile_k": [16],
}
_GU_TILE_PERSIST = {
    "tile_m": [256], "tile_n": [256], "tile_k": [32],
    "warp_m": [2], "warp_n": [2], "warp_k": [1],
    "warp_tile_m": [16], "warp_tile_n": [16], "warp_tile_k": [16],
}


def _gu_trait(persistent=False):
    return {
        "pipeline": ["compv4"],
        "epilogue": ["cshuffle"],
        "scheduler": ["intrawave"],
        "pad_m": [False], "pad_n": [False], "pad_k": [False],
        "persistent": [persistent],
    }


def _gu_tile_config_json(tile, trait, multi_d=None):
    cfg = {"tile_config": tile, "trait_config": trait}
    if multi_d is not None:
        cfg["multi_d_config"] = multi_d
    return cfg


# The explicit, hand-picked tripwire matrix.  Each entry is fully self-describing
# so the manifest can freeze exactly how the generator was invoked.
def _build_tripwire_cases():
    cases = []

    # ---- gemm_universal: the most important tripwire (heaviest codegen_common
    # user).  A spread of dtype x layout x variant x trait that all flow through
    # codegen_common's TileConfig / TraitConfig / TypeMappings / name build. ----
    gu_script = str(_CODEGEN_DIR / "unified_gemm_codegen.py")
    gu_specs = [
        # (case_tag, datatype, layout, arch, variant, tile-config-json dict)
        ("fp16_rcr_standard", "fp16", "rcr", "gfx942", "standard",
         _gu_tile_config_json(_GU_TILE_16, _gu_trait())),
        ("bf16_rrr_standard", "bf16", "rrr", "gfx942", "standard",
         _gu_tile_config_json(_GU_TILE_16, _gu_trait())),
        ("fp8_rcr_standard_wtk32", "fp8", "rcr", "gfx950", "standard",
         _gu_tile_config_json(_GU_TILE_32, _gu_trait())),
        ("fp16_rcr_persistent", "fp16", "rcr", "gfx942", "standard",
         _gu_tile_config_json(_GU_TILE_PERSIST, _gu_trait(persistent=True))),
        ("fp16_multi_d_relu", "fp16", "rcr", "gfx942", "multi_d",
         _gu_tile_config_json(
             _GU_TILE_16, _gu_trait(),
             multi_d={"elementwise_ops": ["Relu"], "num_d_tensors": [1]},
         )),
    ]
    for tag, dtype, layout, arch, variant, tcfg in gu_specs:
        cases.append({
            "case_id": f"gemm_universal::{tag}",
            "generator": "gemm_universal",
            "op": "gemm_universal",
            "script": gu_script,
            "argv": [
                "--datatype", dtype,
                "--layout", layout,
                "--gpu-target", arch,
                "--variants", variant,
                "--no-parallel",
                "--tile-config-json", json.dumps(tcfg, sort_keys=True),
            ],
        })

    # ---- grouped conv: forward across dtype / ndim (bwd_* variants are arch-
    # filtered out for this tile shape, fp32 too; forward reliably yields one
    # kernel and still exercises the shared TileConfig / TraitConfig path). ----
    gc_script = str(_CODEGEN_DIR / "unified_grouped_conv_codegen.py")
    _GC_TILE = [
        "--tile-m", "128", "--tile-n", "128", "--tile-k", "64",
        "--warp-m", "2", "--warp-n", "2", "--warp-k", "1",
        "--warp-tile-m", "32", "--warp-tile-n", "32", "--warp-tile-k", "16",
        "--pipeline", "compv4", "--scheduler", "intrawave", "--epilogue", "cshuffle",
    ]
    gc_specs = [
        ("fwd_fp16_2d", "fp16", "forward", "2", "gfx942"),
        ("fwd_bf16_2d", "bf16", "forward", "2", "gfx942"),
        ("fwd_fp16_3d", "fp16", "forward", "3", "gfx942"),
    ]
    for tag, dtype, variant, ndim, arch in gc_specs:
        cases.append({
            "case_id": f"grouped_conv::{tag}",
            "generator": "grouped_conv",
            "op": "grouped_conv",
            "script": gc_script,
            # grouped conv's CLI names its output dir --output (-o), not
            # --output-dir like the other generators.
            "output_flag": "--output",
            "argv": [
                "-d", dtype, "-v", variant, "-n", ndim, "-a", arch, *_GC_TILE,
            ],
        })

    # ---- mx_gemm + batched_contraction: driven exactly like the quant families
    # (factory -> to_codegen_config -> --config-json -> <name>.hpp).  Independent
    # of codegen_common, but cheap bonus coverage of two more generators. ----
    for module_name, factories in (
        ("mx_gemm_utils", ("default_fp8_config", "default_fp4_config")),
        ("batched_contraction_utils", ("default_fp16_config",)),
    ):
        mod = import_module(module_name)
        script = str(getattr(mod, "_CODEGEN_SCRIPT"))
        for factory in factories:
            fn = getattr(mod, factory)
            for arch in _ARCHES:
                cfg = fn(gfx_arch=arch)
                cases.append({
                    "case_id": f"{module_name}::{factory}::{arch}",
                    "generator": "utils",
                    "op": module_name.replace("_utils", ""),
                    "script": script,
                    "argv": [
                        "--config-json",
                        json.dumps(cfg.to_codegen_config(), sort_keys=True),
                    ],
                    # For the utils path the emitted stem IS the config name.
                    "expect_config_name": cfg.name,
                })

    # ---- FMHA: the shared parallel_generate helper is the codegen_common tie.
    # Driven from FmhaKernelConfig defaults (production's to_codegen_json). ----
    fmha_script = str(_CODEGEN_DIR / "fmha" / "codegen.py")
    fmha_mod = import_module("fmha_utils")
    FmhaKernelConfig = getattr(fmha_mod, "FmhaKernelConfig")
    fmha_specs = [
        ("fwd_fp16_default", {}, "gfx950"),
        ("fwd_bf16_default", {"data_type": "bf16"}, "gfx950"),
    ]
    for tag, overrides, arch in fmha_specs:
        cfg = FmhaKernelConfig(**overrides)
        cases.append({
            "case_id": f"fmha::{tag}",
            "generator": "fmha",
            "op": "fmha",
            "script": fmha_script,
            "argv": [
                "--gpu-target", arch,
                "--no-parallel",
                "--config-json", cfg.to_codegen_json(),
            ],
        })

    cases.sort(key=lambda c: c["case_id"])
    return cases


_TRIPWIRE_CASES = _build_tripwire_cases()
_TRIPWIRE_IDS = [c["case_id"] for c in _TRIPWIRE_CASES]

# Top-level aggregation / wrapper files the directory-writing generators emit
# alongside the one real kernel header.  These are NOT the kernel under test.
_TRIPWIRE_HPP_IGNORE_PREFIXES = (
    "include_all_",
    "register_all_kernels",
    "register_all_grouped_conv_kernels",
    "dispatcher_wrapper_",
)


def _discover_kernel_hpp(out_dir: Path) -> Path:
    """Return the single top-level kernel ``.hpp`` a generator emitted.

    Ignores the ``dispatcher_wrappers/`` subdir and any top-level aggregation
    include / registration headers.  Exactly one kernel header must remain,
    otherwise the case is ambiguous and we fail loudly.
    """
    candidates = [
        p
        for p in out_dir.glob("*.hpp")
        if not any(p.name.startswith(pre) for pre in _TRIPWIRE_HPP_IGNORE_PREFIXES)
    ]
    if len(candidates) != 1:
        raise RuntimeError(
            f"expected exactly one top-level kernel .hpp in {out_dir}, "
            f"found {sorted(p.name for p in candidates)}"
        )
    return candidates[0]


def generate_tripwire_hpp(case: dict):
    """Run one tripwire generator; return ``(emitted_stem, hpp_bytes)``.

    All generators accept ``--output-dir <dir>`` plus the per-case ``argv``.
    ``utils`` cases write ``<config_name>.hpp`` directly; the directory-writing
    generators (gemm_universal / grouped_conv / fmha) have their single kernel
    header discovered.
    """
    with tempfile.TemporaryDirectory(prefix="ck_codegen_tripwire_") as td:
        output_flag = case.get("output_flag", "--output-dir")
        cmd = [sys.executable, case["script"], output_flag, td, *case["argv"]]
        result = subprocess.run(
            cmd, capture_output=True, text=True, timeout=_CODEGEN_TIMEOUT
        )
        if result.returncode != 0:
            raise RuntimeError(
                f"tripwire codegen failed ({case['case_id']}):\n{result.stderr}"
            )
        out_dir = Path(td)
        if case["generator"] == "utils":
            hpp = out_dir / f"{case['expect_config_name']}.hpp"
            if not hpp.exists():
                raise RuntimeError(
                    f"tripwire codegen produced no {hpp.name} "
                    f"({case['case_id']})\nstderr:\n{result.stderr}"
                )
        else:
            hpp = _discover_kernel_hpp(out_dir)
        return hpp.stem, hpp.read_bytes()


def regenerate_tripwire_goldens() -> int:
    """(Re)write every tripwire golden ``.hpp`` and its manifest.  Returns count."""
    _TRIPWIRE_HPP_DIR.mkdir(parents=True, exist_ok=True)
    for stale in _TRIPWIRE_HPP_DIR.glob(f"*{_FIXTURE_EXT}"):
        stale.unlink()

    manifest = {
        "_comment": (
            "NON-QUANT TRIPWIRE golden byte-hashes.  Freezes the output of the "
            "generators that share codegen/codegen_common.py (gemm_universal, "
            "grouped_conv, fmha) plus mx_gemm/batched_contraction bonus "
            "coverage, so the upcoming quant-engine refactor cannot silently "
            "perturb shared codegen behavior.  Regenerate intentionally with: "
            "python3 tests/test_codegen_golden.py --update"
        ),
        "case_count": len(_TRIPWIRE_CASES),
        "cases": {},
    }

    written: dict = {}
    for case in _TRIPWIRE_CASES:
        stem, data = generate_tripwire_hpp(case)
        sha = hashlib.sha256(data).hexdigest()
        prev = written.get(stem)
        if prev is None:
            (_TRIPWIRE_HPP_DIR / f"{stem}{_FIXTURE_EXT}").write_bytes(data)
            written[stem] = sha
        elif prev != sha:
            raise RuntimeError(
                f"tripwire emitted-stem collision with differing bytes: {stem} "
                f"(case {case['case_id']})"
            )
        manifest["cases"][case["case_id"]] = {
            "generator": case["generator"],
            "op": case["op"],
            "emitted_hpp": stem,
            "sha256": sha,
            "argv": case["argv"],
        }

    _TRIPWIRE_MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return len(_TRIPWIRE_CASES)


def _load_tripwire_manifest() -> dict:
    if not _TRIPWIRE_MANIFEST.exists():
        raise FileNotFoundError(
            f"tripwire manifest missing: {_TRIPWIRE_MANIFEST}\n"
            "Generate it with: python3 tests/test_codegen_golden.py --update"
        )
    return json.loads(_TRIPWIRE_MANIFEST.read_text())


def test_tripwire_manifest_matches_matrix():
    """The frozen tripwire manifest must describe exactly the current matrix."""
    manifest = _load_tripwire_manifest()
    frozen = set(manifest["cases"])
    live = {c["case_id"] for c in _TRIPWIRE_CASES}
    missing = frozen - live
    extra = live - frozen
    assert not missing, (
        "tripwire goldens describe cases no longer in the matrix "
        f"(regenerate goldens): {sorted(missing)}"
    )
    assert not extra, (
        "tripwire matrix has cases with no golden (regenerate goldens): "
        f"{sorted(extra)}"
    )


@pytest.mark.parametrize("case", _TRIPWIRE_CASES, ids=_TRIPWIRE_IDS)
def test_tripwire_bytes_match_golden(case):
    """Regenerated non-quant .hpp bytes must be byte-identical to the golden.

    This is the actual tripwire: if the quant-engine refactor changes shared
    codegen_common behavior, one of these non-quant generators drifts here.
    """
    manifest = _load_tripwire_manifest()
    entry = manifest["cases"].get(case["case_id"])
    assert entry is not None, (
        f"no tripwire golden for {case['case_id']} -- regenerate goldens"
    )
    # The exact invocation must be stable (argv drift == config drift).
    assert entry["argv"] == case["argv"], (
        f"{case['case_id']}: generator argv drifted\n"
        f"  golden: {entry['argv']}\n"
        f"  now:    {case['argv']}"
    )

    stem = entry["emitted_hpp"]
    golden_hpp = _TRIPWIRE_HPP_DIR / f"{stem}{_FIXTURE_EXT}"
    assert golden_hpp.exists(), (
        f"tripwire golden fixture missing: {golden_hpp} -- regenerate goldens"
    )
    golden_bytes = golden_hpp.read_bytes()

    stored_sha = hashlib.sha256(golden_bytes).hexdigest()
    assert stored_sha == entry["sha256"], (
        f"{case['case_id']}: manifest sha256 disagrees with stored "
        f"{golden_hpp.name} (corrupt/edited fixture) -- regenerate goldens"
    )

    fresh_stem, fresh_bytes = generate_tripwire_hpp(case)
    assert fresh_stem == stem, (
        f"{case['case_id']}: emitted .hpp stem drifted\n"
        f"  golden: {stem}\n"
        f"  now:    {fresh_stem}"
    )
    if fresh_bytes != golden_bytes:
        diff = "\n".join(
            difflib.unified_diff(
                golden_bytes.decode("utf-8", "replace").splitlines(),
                fresh_bytes.decode("utf-8", "replace").splitlines(),
                fromfile=f"golden/tripwire/{stem}{_FIXTURE_EXT}",
                tofile=f"generated/tripwire/{stem}.hpp",
                lineterm="",
                n=3,
            )
        )
        snippet = "\n".join(diff.splitlines()[:60])
        pytest.fail(
            f"{case['case_id']}: generated bytes differ from tripwire golden "
            f"({stem}.hpp) -- a shared codegen_common change likely leaked\n"
            f"golden sha256={entry['sha256']}\n"
            f"fresh  sha256={hashlib.sha256(fresh_bytes).hexdigest()}\n"
            f"--- unified diff (first 60 lines) ---\n{snippet}"
        )


def test_tripwire_exercises_codegen_common():
    """Sanity-check the tripwire really flows through shared codegen paths.

    Not a byte assertion -- a guard that the goldens we froze actually contain
    the shared header preamble + kernel-name/namespace format that a
    codegen_common change would perturb.  If a config silently stopped emitting
    a real kernel, this catches it independent of the byte goldens.
    """
    manifest = _load_tripwire_manifest()
    # gemm_universal is the heaviest codegen_common consumer; require at least
    # one such golden and assert its shared markers are present.
    gu = [
        e for e in manifest["cases"].values()
        if e["generator"] == "gemm_universal"
    ]
    assert gu, "no gemm_universal tripwire case present"
    for entry in gu:
        text = (
            _TRIPWIRE_HPP_DIR / f"{entry['emitted_hpp']}{_FIXTURE_EXT}"
        ).read_text(encoding="utf-8")
        assert "SPDX-License-Identifier: MIT" in text
        assert "Auto-generated CK Tile GEMM kernel" in text
        # codegen_common-built kernel name -> namespace + KERNEL_NAME literal.
        assert f'namespace ns_{entry["emitted_hpp"]}' in text
        assert f'KERNEL_NAME = "{entry["emitted_hpp"]}"' in text


