"""Byte-level golden-file test for the block-scale quant GEMM code generators.

This is a *safety net* for the upcoming refactor that folds the eight
``unified_*_codegen.py`` generators into a single engine.  It captures the
exact bytes each generator emits for a comprehensive config matrix and asserts
that a re-run produces byte-identical output.  If the follow-up rewrite changes
even one byte of any generated kernel header, this test fails and prints which
config drifted plus a unified-diff snippet.

Scope
-----
Eight generators are exercised (5 non-grouped + 3 grouped quant families)::

    unified_gemm_aquant_codegen.py          <- gemm_aquant_utils
    unified_gemm_abquant_codegen.py         <- gemm_abquant_utils
    unified_gemm_bquant_codegen.py          <- gemm_bquant_utils
    unified_gemm_rowcolquant_codegen.py     <- gemm_rowcolquant_utils
    unified_gemm_tensor_quant_codegen.py    <- gemm_tensor_quant_utils
    unified_grouped_gemm_aquant_codegen.py  <- grouped_gemm_aquant_utils
    unified_grouped_gemm_abquant_codegen.py <- grouped_gemm_abquant_utils
    unified_grouped_gemm_bquant_codegen.py  <- grouped_gemm_bquant_utils

The matrix is assembled from every ``default_*_config`` factory in each
``*_utils`` module, invoked for BOTH ``gfx942`` and ``gfx950`` (the arch-derived
``warp_tile_k`` 32/64-vs-128 branch is the key arch-dependent axis).  Each
factory covers a dtype/layout/variant family (fp8, bf8, fp8i4/bf8i4, fp4, the
MX bf16bf16/bf16bf8/bf16fp4 microscale variants for bquant, preshuffle-b /
preshuffle-quant / eight-waves / permute-n variants, grouped vs non-grouped).
Using the shipped factories as the source of valid configs guarantees we never
hand-build an invalid config that the generator would reject.

Determinism
-----------
The generated bytes are fully deterministic: the header preamble carries no
timestamp and no absolute path, the config JSON is serialized with
``sort_keys=True``, and the matrix is walked in a fixed (sorted) order.  The
generator runs pure-Python with no GPU / hipcc required, so this test runs on a
CPU-only box.

Fixture layout
--------------
``tests/golden/codegen/``::

    manifest.json                   # every (module, factory, arch) case ->
                                    #   config_name, sha256(hpp_bytes), and the
                                    #   exact codegen-config dict
    hpp/<config_name>.hpp.golden    # one full body per UNIQUE generated kernel

The fixtures are stored with a ``.hpp.golden`` extension (NOT ``.hpp``) so the
CK CI "Static checks" stage -- which runs clang-format-18 over every ``*.hpp``
(and ``*.h`` / ``*.cpp`` / ``*.inc`` / ``*.cl`` / ``*.*.in``) in the repo --
neither flags these generated goldens as unformatted nor reformats them (which
would break the byte-identity this test relies on).  ``.hpp.golden`` keeps the
readable stem while matching none of the CI find patterns.

The matrix has 140 (factory x arch) cases; 31 of them are arch-invariant (the
grouped families and the MX / fp4 variants hardcode ``warp_tile_k`` independent
of arch), so they collapse to 109 unique ``.hpp.golden`` files.  The manifest
stores all 140 cases (proving each arch axis was exercised) while the kernel
bodies are deduped by ``config_name``.  A byte change is caught two ways: the
full body comparison (with a diff) AND the per-case sha256 in the manifest.

Non-quant tripwire
------------------
A second, clearly-separated golden set lives under
``tests/golden/codegen/tripwire/`` (its own ``manifest.json`` + ``hpp/``).  It
freezes representative output of the NON-quant generators that share
``codegen/codegen_common.py`` -- ``unified_gemm_codegen.py`` (gemm_universal,
the heaviest consumer), ``unified_grouped_conv_codegen.py`` (grouped conv) and
``codegen/fmha/codegen.py`` (FMHA) -- plus cheap bonus coverage of
``unified_mx_gemm_codegen.py`` and ``unified_batched_contraction_codegen.py``
(both independent of codegen_common).  The upcoming quant-engine refactor must
not perturb codegen_common; if it does, one of these non-quant goldens drifts
and the suite fails.  See the big ``NON-QUANT TRIPWIRE`` block further down.

Regeneration
------------
Refresh the goldens intentionally after a deliberate generator change::

    python3 tests/test_codegen_golden.py --update

or::

    python3 -m tests.test_codegen_golden --update
"""

