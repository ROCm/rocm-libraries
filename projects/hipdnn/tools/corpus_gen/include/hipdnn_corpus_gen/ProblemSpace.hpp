/// The cross product of every categorical parameter's declared values.
///
/// Ordered so the product is reproducible: parameters in declaration order, values in the
/// order the metadata lists them. A corpus that enumerated dtypes in hash order would draw a
/// different subset each run whenever the cap bound.
inline std::vector<ProblemPoint>
    categoricalCombinations(const std::vector<Parameter>& parameters, size_t limit, size_t& total)
{
    std::vector<ProblemPoint> combinations{ProblemPoint{}};
    total = 1;

    for(const auto& parameter : parameters)
    {
        const auto values = parameter.enumerable();
        if(values.empty())
        {
            continue;
        }
        total *= values.size();

        std::vector<ProblemPoint> expanded;
        for(const auto& base : combinations)
        {
            for(const auto& value : values)
            {
                auto point = base;
                point[parameter.name] = value;
                expanded.push_back(std::move(point));
            }
        }
        combinations = std::move(expanded);

        if(combinations.size() > limit)
        {
            combinations.resize(limit);
        }
    }
    return combinations;
}

/// Whether @p point satisfies every relation @p metadata declares.
///
/// Checked before the oracle, so a candidate that is not a problem never costs a graph build.
/// A constraint that fails to evaluate is treated as unsatisfied rather than ignored: a
/// malformed relation that silently admitted everything would restore exactly the behaviour it
/// was added to prevent.
inline bool satisfiesConstraints(const OperationMetadata& metadata, const ProblemPoint& point)
{
    if(metadata.constraints.size() == 0)
    {
        return true;
    }

    const auto context = detail::contextFor(point);
    auto work = metadata.constraints.workspace();
    for(size_t i = 0; i < metadata.constraints.size(); ++i)
    {
        try
        {
            const auto& value = metadata.constraints.evaluate(i, context, work);
            const auto* held = std::get_if<bool>(&value.raw);
            if(held == nullptr || !*held)
            {
                return false;
            }
        }
        catch(const std::exception&)
        {
            return false;
        }
    }
    return true;
}

/// The skeleton of enumerated points a declaration already describes.
///
/// RFC 0019.13 §4.3.5's regime buckets are not only a stratification target -- they are the
/// operation's own statement of which values matter, and their cross product is valid by
/// construction in a way independent draws are not. A convolution declaring
/// `spatial: [7, 14, 28, 56, 112, 224]` and `filter: [1, 3, 5, 7]` has said that a 3x3 filter
/// on a 28x28 input is a real problem; sampling H and R independently from a shared range says
/// only that 83 might pair with 36, which the frontend then refuses.
///
/// This is the same instinct CK and rocKE follow -- powers of two, recorded model shapes,
/// deliberate edge cases -- with the difference that here it seeds a search rather than being
/// the whole corpus, because a curated list cannot say what an engine accepts that nobody
/// thought to list.
///
/// Parameters with no regime take their floor. That is deliberately unambitious: it makes the
/// skeleton valid (a padding of 0, a stride of 1) and leaves the walk to raise them, which is
/// what the walk is for.
inline std::vector<Shape> regimeSkeleton(const OperationMetadata& metadata,
                                         const std::vector<ShapeDimension>& window,
                                         const std::vector<std::string>& numericParameters,
                                         size_t limit,
                                         size_t& total)
{
    // Buckets per numeric parameter, in the declaration's order.
    std::vector<std::vector<int64_t>> choices;
    choices.reserve(numericParameters.size());
    total = 1;

    for(size_t i = 0; i < numericParameters.size(); ++i)
    {
        std::vector<int64_t> values;
        for(const auto& entry : metadata.regimes)
        {
            if(entry.second.parameter != numericParameters[i] || !entry.second.derived.empty())
            {
                continue;
            }
            for(const auto& bucket : entry.second.buckets)
            {
                if(bucket.is_number_integer())
                {
                    const auto value = bucket.get<int64_t>();
                    if(value >= window[i].low && value <= window[i].high)
                    {
                        values.push_back(value);
                    }
                }
            }
        }

        // §4.3.2's common_values are the other declared source: representative values from a
        // usage record, which is where a real model's shapes enter.
        if(const auto* parameter = metadata.find(numericParameters[i]))
        {
            for(const auto& value : parameter->commonValues)
            {
                if(const auto* held = std::get_if<int64_t>(&value))
                {
                    if(*held >= window[i].low && *held <= window[i].high)
                    {
                        values.push_back(*held);
                    }
                }
            }
        }

        if(values.empty())
        {
            values.push_back(window[i].low);
        }
        std::sort(values.begin(), values.end());
        values.erase(std::unique(values.begin(), values.end()), values.end());
        total *= values.size();
        choices.push_back(std::move(values));
    }

    std::vector<Shape> skeleton{Shape{}};
    for(const auto& values : choices)
    {
        std::vector<Shape> expanded;
        for(const auto& base : skeleton)
        {
            for(const auto value : values)
            {
                auto point = base;
                point.push_back(value);
                expanded.push_back(std::move(point));
            }
        }
        skeleton = std::move(expanded);
    }

    if(skeleton.size() > limit && limit > 0)
    {
        // Strided, not truncated. The product is generated in declaration order, so keeping a
        // prefix keeps the combinations where every early parameter is at its smallest value
        // -- a skeleton of nothing but tiny convolutions, chosen by an implementation detail.
        // Striding covers the same product evenly and stays deterministic.
        std::vector<Shape> sampled;
        sampled.reserve(limit);
        const auto step = static_cast<double>(skeleton.size()) / static_cast<double>(limit);
        for(size_t i = 0; i < limit; ++i)
        {
            sampled.push_back(skeleton[static_cast<size_t>(static_cast<double>(i) * step)]);
        }
        skeleton = std::move(sampled);
    }
    return skeleton;
}

/// A one-line rendering of a categorical assignment, for reporting what was skipped.
inline std::string describe(const ProblemPoint& point)
{
    std::string text;
    for(const auto& [name, value] : point)
    {
        if(!text.empty())
        {
            text += ",";
        }
        text += name + "=";
        std::visit(
            [&text](const auto& held) {
                using Held = std::decay_t<decltype(held)>;
                if constexpr(std::is_same_v<Held, std::string>)
                {
                    text += held;
                }
                else if constexpr(std::is_same_v<Held, bool>)
                {
                    text += held ? "true" : "false";
                }
                else
                {
                    text += std::to_string(held);
                }
            },
            value);
    }
    return text;
}

