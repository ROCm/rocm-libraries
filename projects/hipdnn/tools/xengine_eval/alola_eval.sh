# One shard of the cross-engine evaluation on the GPU of this job (alola_job.py batch, whole
# GPU, in the arch's hipDNN image). Reads what alola_build.sh produced for the arch.
#
#   alola_eval.sh <arch> <work dir> <shard K/N> [extra xengine_eval.py run flags...]
#
# Rows go to <work dir>/<arch>/runs/<run tag>/shard-<K>/rows.jsonl; re-running a shard resumes it.
# XENG_RUN_TAG names the run (default: the short source sha), so a later source gets its own rows.
set -euo pipefail

arch=${1:?arch}
work=$(cd "${2:?work dir}" && pwd)
shard=${3:?shard K/N}
shift 3

# shellcheck disable=SC1091
source "$work/$arch/env.sh"
src_sha=$(sed -n 's/^# Generated by alola_build.sh for [^ ]* from //p' "$work/$arch/env.sh")
tag=${XENG_RUN_TAG:-${src_sha:0:12}}
out="$work/$arch/runs/$tag/shard-${shard%%/*}"
mkdir -p "$out"

echo "== $arch shard $shard on $(hostname): $(rocm-smi --showproductname 2>/dev/null | grep -m1 -i 'card series' || true)"
python3 "$(dirname "$0")/xengine_eval.py" run \
    --bin "$XENG_PREFIX/bin/hipdnn_xengine_eval" \
    --plugin-dir "$XENG_PLUGIN_DIR" \
    --graphs "$work/$arch/corpus" \
    --out "$out" \
    --shard "$shard" \
    --source-sha "$src_sha" \
    "$@"
python3 "$(dirname "$0")/xengine_eval.py" report --rows "$out/rows.jsonl" \
    --out "$out/report.json" --md "$out/report.md"
echo "rows: $out/rows.jsonl"
