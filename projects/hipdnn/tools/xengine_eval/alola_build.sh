# Build hipDNN, the MIOpen provider and the HIP kernel provider (kernel ingestor with FlyDSL,
# conv, rocKE, ASM SDPA and HIP MLOps engines) for one GPU arch, with hipdnn_bench,
# hipdnn_corpus_gen and hipdnn_xengine_eval, into a prefix in the home directory. Meant to run
# inside the arch's hipDNN image on an alola node (alola_job.py login run / batch --arch <arch>);
# needs no GPU.
#
#   alola_build.sh <arch> <source tree> <work dir>
#
# Writes <work dir>/<arch>/{build,install}, <work dir>/venv (dvc), and <work dir>/<arch>/env.sh,
# which the evaluation sources. Environment:
#   XENG_COMPONENTS  superbuild components (default "hipdnn;miopen-provider;hip-kernel-provider")
#   XENG_JOBS        build parallelism (default $ALOLA_CORES, else nproc)
#   XENG_SKIP_DVC=1  skip `dvc pull` (descriptor content already present)
set -euo pipefail

arch=${1:?arch}
src=$(cd "${2:?source tree}" && pwd)
work=${3:?work dir}
mkdir -p "$work/$arch"
work=$(cd "$work" && pwd)
build="$work/$arch/build"
prefix="$work/$arch/install"
jobs=${XENG_JOBS:-${ALOLA_CORES:-$(nproc)}}
components=${XENG_COMPONENTS:-"hipdnn;miopen-provider;hip-kernel-provider"}

echo "== toolchain"
cat /opt/rocm/.info/version 2>/dev/null || ls -d /opt/rocm*
ls /opt/rocm/lib/libMIOpen.so* 2>/dev/null | head -1 || echo "no libMIOpen in /opt/rocm/lib"
cmake --version | head -1
python3 --version
echo "source: $src @ $(git -C "$src" rev-parse HEAD 2>/dev/null || echo unknown)"

# Python: the provider's configure needs pytest, zstandard and msgpack; descriptor content
# comes from DVC (anonymous S3 reads, .dvc/config).
venv="$work/venv"
if [[ ! -x $venv/bin/python ]]; then
    python3 -m venv "$venv"
fi
"$venv/bin/python" -m pip install --quiet --upgrade pip
"$venv/bin/python" -m pip install --quiet "dvc[s3]" pytest "zstandard>=0.20.0" msgpack flatbuffers numpy
export PATH="$venv/bin:$PATH"

if [[ ${XENG_SKIP_DVC:-0} != 1 ]]; then
    echo "== dvc pull"
    desc=dnn-providers/hip-kernel-provider/src/engines/kernel_ingestor_engine/descriptors
    (
        cd "$src"
        dvc pull -r ingestor --recursive "$desc"
    )
fi

comgr=""
for candidate in /opt/rocm/lib/libamd_comgr.so /opt/rocm/lib/libamd_comgr.so.*; do
    if [[ -f $candidate ]]; then
        comgr="-DHIPKERNELPROVIDER_ROCKE_COMGR_LIB=$candidate"
        break
    fi
done

echo "== configure ($components, $arch)"
cmake -S "$src" -B "$build" -G Ninja \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="$prefix" \
    -DCMAKE_PREFIX_PATH=/opt/rocm \
    -DROCM_PATH=/opt/rocm \
    -DCMAKE_C_COMPILER=/opt/rocm/llvm/bin/clang \
    -DCMAKE_CXX_COMPILER=/opt/rocm/llvm/bin/clang++ \
    -DPython3_EXECUTABLE="$venv/bin/python" \
    "-DROCM_LIBS_ENABLE_COMPONENTS=$components" \
    -DGPU_TARGETS="$arch" \
    -DCMAKE_HIP_ARCHITECTURES="$arch" \
    -DENABLE_CLANG_TIDY=OFF \
    -DENABLE_CLANG_FORMAT=OFF \
    -DHIPDNN_SKIP_TESTS=ON \
    -DHIPDNN_ENABLE_KERNEL_INGESTOR=ON \
    -DHIPDNN_ENABLE_SDPA=ON \
    -DHIPKERNELPROVIDER_ENABLE_TESTS=OFF \
    -DHIPKERNELPROVIDER_ENABLE_ROCKE=ON \
    -DHIPKERNELPROVIDER_KPACK_ALLOW_FETCH=ON \
    -DHIPKERNELPROVIDER_ENABLE_FLYDSL=ON \
    -DHIPKERNELPROVIDER_ENABLE_CONV=ON \
    -DENABLE_ASM_SDPA_ENGINE=ON \
    -DENABLE_HIP_MLOPS_ENGINE=ON \
    ${comgr:+"$comgr"} 2>&1 | tee "$work/$arch/configure.log"

# Content CMake left out (an un-pulled DVC bundle) is a warning, not an error: surface it.
grep -E "DVC output|not served|left out|dormant" "$work/$arch/configure.log" || true

echo "== build (-j $jobs)"
# ALL, not single targets: descriptor staging rides the ALL target.
cmake --build "$build" -j "$jobs"
cmake --install "$build"

plugins=$(dirname "$(find "$prefix" -name 'libhip_kernel_provider*.so' -path '*hipdnn_plugins/engines*' | head -1)")
cat >"$work/$arch/env.sh" <<EOF
# Generated by alola_build.sh for $arch from $(git -C "$src" rev-parse HEAD 2>/dev/null || echo unknown)
export XENG_PREFIX="$prefix"
export XENG_PLUGIN_DIR="$plugins"
export PATH="$prefix/bin:$venv/bin:\$PATH"
# Ahead of the image's own hipDNN in /opt/rocm/lib, which the tools' RUNPATH would otherwise find.
export LD_LIBRARY_PATH="$prefix/lib:$prefix/lib64:/opt/rocm/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
EOF
echo "== installed"
ls "$prefix/bin"
ls "$plugins"
echo "env: $work/$arch/env.sh"

# The evaluation graphs: every problem the operation declarations express (no engine filter,
# no GPU), generated once per arch so every shard of the evaluation reads the same set.
corpus="$work/$arch/corpus"
if [[ ! -f $corpus/counts.tsv ]]; then
    echo "== corpus (${XENG_CORPUS_COUNT:-40} per operation, seed ${XENG_CORPUS_SEED:-1})"
    # shellcheck disable=SC1091
    source "$work/$arch/env.sh"
    "$src/projects/hipdnn/tools/xengine_eval/make_corpus.sh" "$prefix/bin/hipdnn_corpus_gen" \
        "$corpus" "${XENG_CORPUS_COUNT:-40}" "${XENG_CORPUS_SEED:-1}"
fi
