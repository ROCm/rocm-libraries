"""Compile PyTorch's hipified cuDNN v0.x consumers against an installed hipDNN shim.

Usage: pytorch_compile_probe.py --pytorch-root DIR --pytorch-build DIR
       --hipdnn-prefix DIR --out DIR [--only ID]...

Preconditions: a PyTorch ROCm build of a tree with aten/src/ATen/hipdnn/, current
hipified copies and compile_commands.json; a hipDNN install with the cuDNN shim ON
(HIPDNN_ENABLE_CUDNN_COMPATIBILITY); on Windows, a vcvars64 environment. Writes only
under --out. Exit 0: all entries met their tier; 1: compile failure or PyTorch tree
changed; 2: preflight error.
"""

import argparse
import json
import os
import posixpath
import re
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

PROBE_DIR = Path(__file__).resolve().parent
OVERLAY_DIR = PROBE_DIR / "overlay"
MANIFEST = PROBE_DIR / "manifest.json"

TIERS = ("COMPILE", "COMPILE_ASIS", "XFAIL_COMPILE", "EXCLUDED")
FORCED_TIERS = ("COMPILE", "XFAIL_COMPILE")
HIPIFY_BANNER = "automatically generated by hipify"
HIPIFY_HINT = (
    "regenerate the hipified copies with the PyTorch ROCm build (its hipify step), "
    "then re-run the probe"
)
USE_CUDA_GATE = re.compile(
    r"^\s*#\s*(?:ifdef\s+USE_CUDA\b|if\b.*\bdefined\s*\(?\s*USE_CUDA\b)", re.MULTILINE
)
HIPDNN_INCLUDE_LEAVES = ("frontend", "data_sdk", "backend")
# Longest spellings first so a joined "-imsvc<dir>" is never read as "-I" + "msvc<dir>".
INCLUDE_FLAGS = ("-isystem", "-imsvc", "/imsvc", "-I", "/I")
DESCRIPTORS_BEGIN = "namespace at::native {"
DESCRIPTORS_END = "template <typename T, cudnnStatus_t (*dtor)(T*)>"
COMPILE_TIMEOUT_S = 900


class ProbeError(Exception):
    def __init__(self, code: str, message: str):
        super().__init__(f"{code}: {message}")


def norm(path) -> str:
    return os.path.normcase(os.path.normpath(os.path.abspath(path)))


def is_within(path, root) -> bool:
    path, root = norm(path), norm(root)
    return path == root or path.startswith(root.rstrip(os.sep) + os.sep)


def fwd(path) -> str:
    return str(path).replace("\\", "/")


def git(root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if result.returncode != 0:
        raise ProbeError(
            "P-TREE", f"git {' '.join(args)} failed: {result.stderr.strip()}"
        )
    return result.stdout


def tree_status(root: Path) -> list:
    # Submodules marked ignore = dirty would otherwise hide collateral rewrites.
    return git(root, "status", "--porcelain", "--ignore-submodules=none").splitlines()


def load_manifest() -> dict:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    seen = set()
    for entry in manifest["entries"]:
        missing = [k for k in ("id", "source", "compiled", "tier") if k not in entry]
        if missing:
            raise ProbeError("P-COMPLETE", f"manifest entry {entry} lacks {missing}")
        eid, tier = entry["id"], entry["tier"]
        if eid in seen:
            raise ProbeError("P-COMPLETE", f"duplicate manifest id '{eid}'")
        seen.add(eid)
        if tier not in TIERS:
            raise ProbeError("P-COMPLETE", f"'{eid}': unknown tier '{tier}'")
        if tier == "COMPILE" and not entry.get("canary"):
            raise ProbeError("P-COMPLETE", f"'{eid}': COMPILE requires a canary")
        if tier == "XFAIL_COMPILE" and not (
            entry.get("anchor") and entry.get("reason")
        ):
            raise ProbeError(
                "P-COMPLETE", f"'{eid}': XFAIL_COMPILE requires anchor and reason"
            )
        if tier == "EXCLUDED" and not entry.get("reason"):
            raise ProbeError("P-COMPLETE", f"'{eid}': EXCLUDED requires a reason")
    return manifest


def preflight_env() -> None:
    if os.name == "nt":
        unset = [v for v in ("INCLUDE", "LIB") if not os.environ.get(v)]
        if unset:
            raise ProbeError(
                "P-ENV",
                f"{' and '.join(unset)} not set; run from a vcvars64 environment "
                "(<vs-buildtools>/VC/Auxiliary/Build/vcvars64.bat)",
            )


def preflight_prefix(prefix: Path) -> dict:
    config = (
        prefix / "lib" / "cmake" / "hipdnn_frontend" / "hipdnn_frontendConfig.cmake"
    )
    if not config.is_file():
        raise ProbeError("P-PREFIX", f"{config} not found")
    text = config.read_text(encoding="utf-8")

    def flag(name: str) -> bool | None:
        match = re.search(rf"^\s*set\(\s*{name}\s+(ON|OFF)\s*\)", text, re.MULTILINE)
        return None if match is None else match.group(1) == "ON"

    if flag("hipdnn_frontend_cudnn_compatibility_FOUND") is not True:
        raise ProbeError(
            "P-PREFIX",
            f"{config} lacks cudnn_compatibility_FOUND ON (HIPDNN_ENABLE_CUDNN_COMPATIBILITY=OFF?)",
        )
    sdpa, skip_json = flag("HIPDNN_ENABLE_SDPA"), flag("HIPDNN_FRONTEND_SKIP_JSON_LIB")
    if sdpa is None or skip_json is None:
        raise ProbeError(
            "P-PREFIX",
            f"{config} lacks HIPDNN_ENABLE_SDPA or HIPDNN_FRONTEND_SKIP_JSON_LIB",
        )

    include_root = prefix / "include" / "hipdnn"
    for leaf in HIPDNN_INCLUDE_LEAVES:
        if not (include_root / leaf).is_dir():
            raise ProbeError("P-PREFIX", f"{include_root / leaf} not found")
    for overlay in sorted(OVERLAY_DIR.rglob("*.h")):
        for target in re.findall(
            r"#include <(hipdnn_compatibility/[^>]+)>",
            overlay.read_text(encoding="utf-8"),
        ):
            if not (include_root / "frontend" / target).is_file():
                raise ProbeError(
                    "P-PREFIX", f"{include_root / 'frontend' / target} not found"
                )
    return {"cudnn_compatibility": True, "sdpa": sdpa, "skip_json_lib": skip_json}


def preflight_tree(root: Path, build: Path, out: Path) -> None:
    compat = root / "aten" / "src" / "ATen" / "hipdnn" / "cudnn_compat.h"
    if not compat.is_file():
        raise ProbeError(
            "P-TREE", f"{compat} not found; the tree lacks the hipDNN integration"
        )
    hip_config = root / "aten" / "src" / "ATen" / "hip" / "HIPConfig.h"
    if not hip_config.is_file() or not re.search(
        r"#define\s+AT_HIPDNN_ENABLED\(\)\s+1", hip_config.read_text(encoding="utf-8")
    ):
        raise ProbeError(
            "P-TREE", f"{hip_config} does not define AT_HIPDNN_ENABLED() 1"
        )
    if not (build / "compile_commands.json").is_file():
        raise ProbeError("P-TREE", f"{build / 'compile_commands.json'} not found")
    for tree in (root, build):
        if is_within(out, tree):
            raise ProbeError("P-TREE", f"--out {out} lies inside {tree}")


def overlay_hip_redirects() -> list:
    # Overlay headers that forward an ATen include to its hipified copy, as
    # (label, source, compiled) paths relative to the PyTorch root.
    redirects = []
    for overlay in sorted(OVERLAY_DIR.rglob("*.h")):
        text = overlay.read_text(encoding="utf-8")
        for target in re.findall(r"#include <(ATen/[^>]*/hip/[^>]+)>", text):
            source = re.sub(r"/hip/([^/]+)$", r"/\1", target)
            label = fwd(overlay.relative_to(PROBE_DIR))
            redirects.append((label, f"aten/src/{source}", f"aten/src/{target}"))
    return redirects


def load_hipify(root: Path):
    # The tree's own hipify, imported without writing bytecode into the tree.
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(root / "torch" / "utils"))
    try:
        from hipify import hipify_python
    except Exception as error:  # noqa: BLE001 - any import failure is a preflight error
        raise ProbeError(
            "P-HIPIFY", f"cannot import {root}/torch/utils/hipify: {error}"
        ) from None
    finally:
        sys.path.pop(0)
    return hipify_python


def hipify_now(hipify, root: Path, scratch: Path, source_rel: str) -> tuple:
    # Hipifies a scratch copy of one source exactly as the tree's build does
    # (hip_clang_launch on, not an extension) and returns (hipified path, text).
    shutil.rmtree(scratch, ignore_errors=True)
    staged = scratch / source_rel
    staged.parent.mkdir(parents=True)
    shutil.copyfile(root / source_rel, staged)
    staged_path = fwd(staged)
    hipify.HIPIFY_FINAL_RESULT.clear()
    stats = {"unsupported_calls": [], "kernel_launches": []}
    ctx = hipify.GeneratedFileCleaner(keep_intermediates=True)
    hipify.preprocess_file_and_save_result(
        str(scratch), staged_path, [staged_path], [], stats, True, False, ctx, False
    )
    hip_rel = fwd(hipify.get_hip_file_path(source_rel))
    produced = scratch / hip_rel
    text = produced.read_text(encoding="utf-8") if produced.is_file() else None
    return hip_rel, text


def hipify_sources_of(hipify, root: Path, hip_rel: str) -> list:
    # Inverts the hipify path mapping for one hipified header (rel to root). Two sources
    # can map to one output (transformers/{cuda/,}sdp_utils.h); the cuda/ one comes first.
    directory, name = posixpath.split(hip_rel)
    stem, ext = posixpath.splitext(name)
    candidates = []
    cuda_dir = directory.replace("hip", "cuda").replace("HIP", "CUDA")
    cuda_stem = stem.replace("hip", "cuda").replace("HIP", "CUDA")
    for cuda_ext in (ext, ".cu") if ext == ".hip" else (ext,):
        candidates.append(posixpath.join(cuda_dir, cuda_stem + cuda_ext))
    if posixpath.basename(directory) == "hip":
        candidates.append(posixpath.join(posixpath.dirname(directory), name))
    return [
        c
        for c in dict.fromkeys(candidates)
        if (root / c).is_file() and fwd(hipify.get_hip_file_path(c)) == hip_rel
    ]


def is_hipified(path: Path) -> bool:
    with path.open(encoding="utf-8", errors="replace") as handle:
        return HIPIFY_BANNER in handle.readline()


def included_files(root: Path, path: Path) -> list:
    # Direct includes of one file that resolve inside the tree (aten/src, then root).
    found = []
    text = path.read_text(encoding="utf-8", errors="replace")
    for name in re.findall(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', text, re.MULTILINE):
        name = name.replace("\\", "/")
        for base in ("aten/src", ""):
            rel = posixpath.normpath(posixpath.join(base, name)) if base else name
            if (root / rel).is_file():
                found.append(rel)
                break
    return found


def preflight_hipify(root: Path, out: Path, entries: list) -> dict:
    probed = [
        (e["id"], e["source"], e["compiled"])
        for e in entries
        if e["tier"] != "EXCLUDED"
    ]
    if any(e["tier"] in FORCED_TIERS for e in entries):
        probed += overlay_hip_redirects()

    pairs = {}
    for label, source_rel, compiled_rel in probed:
        source, compiled = root / source_rel, root / compiled_rel
        if not source.is_file():
            raise ProbeError("P-COMPLETE", f"'{label}': source {source} not found")
        if not compiled.is_file():
            raise ProbeError(
                "P-HIPIFY", f"'{label}': {compiled} missing; {HIPIFY_HINT}"
            )
        text = compiled.read_text(encoding="utf-8", errors="replace")
        # A body gated on USE_CUDA compiles to nothing on ROCm, and a canary declared
        # in a shared header would not notice.
        if USE_CUDA_GATE.search(text):
            raise ProbeError(
                "P-HIPIFY",
                f"'{label}': {compiled} is gated on USE_CUDA, which a ROCm build never defines",
            )
        if compiled_rel == source_rel:
            continue
        if HIPIFY_BANNER not in text.split("\n", 1)[0]:
            raise ProbeError(
                "P-HIPIFY",
                f"'{label}': {compiled} has no hipify banner; {HIPIFY_HINT}",
            )
        # A hipify that maps cuDNN names to MIOpen would bypass the shim.
        if "miopen" in text:
            raise ProbeError(
                "P-HIPIFY",
                f"'{label}': {compiled} contains 'miopen'; hipify mapped cuDNN names",
            )
        pairs[compiled_rel] = (label, [source_rel])

    # Hipified headers reachable from the probed files through other hipified files.
    unverified = []
    hipify = load_hipify(root)
    queue = [rel for _, _, rel in probed]
    seen = set(queue)
    while queue:
        rel = queue.pop()
        for inc in included_files(root, root / rel):
            if inc in seen or not is_hipified(root / inc):
                continue
            seen.add(inc)
            queue.append(inc)
            sources = hipify_sources_of(hipify, root, inc)
            if not sources:
                unverified.append(inc)
            elif inc not in pairs:
                pairs[inc] = (f"included by {rel}", sources)

    checks = []
    scratch = out / "hipify_check"
    try:
        for compiled_rel, (label, sources) in sorted(pairs.items()):
            current = root / compiled_rel
            current_text = current.read_text(encoding="utf-8")
            matched = None
            for source_rel in sources:
                hip_rel, expected = hipify_now(hipify, root, scratch, source_rel)
                if hip_rel != compiled_rel:
                    raise ProbeError(
                        "P-HIPIFY",
                        f"'{label}': hipify maps {source_rel} to {hip_rel}, not {compiled_rel}",
                    )
                if expected == current_text:
                    matched = source_rel
                    break
            if matched is None:
                raise ProbeError(
                    "P-HIPIFY",
                    f"'{label}': {current} differs from what this tree's hipify produces "
                    f"from {' or '.join(sources)}; {HIPIFY_HINT}",
                )
            checks.append(
                {
                    "hipified": compiled_rel,
                    "source": matched,
                    "content_current": True,
                    "mtime_older_than_source": current.stat().st_mtime
                    < (root / matched).stat().st_mtime,
                }
            )
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    return {"checked": checks, "unverified_hipified_headers": sorted(unverified)}


def preflight_complete(root: Path, manifest: dict) -> None:
    sources = [e["source"] for e in manifest["entries"]]
    for source in sources:
        if not (root / source).is_file():
            raise ProbeError("P-COMPLETE", f"manifest source {source} not found")
    for scan_dir in manifest["scan_dirs"]:
        for cpp in sorted((root / scan_dir).glob("*.cpp")):
            rel = f"{scan_dir}/{cpp.name}"
            count = sources.count(rel)
            if count != 1:
                raise ProbeError(
                    "P-COMPLETE",
                    f"{rel} appears {count} times in manifest.json (need exactly 1)",
                )


def split_command(command: str) -> list:
    if os.name != "nt":
        return shlex.split(command)
    import ctypes
    from ctypes import wintypes

    to_argv = ctypes.windll.shell32.CommandLineToArgvW
    to_argv.argtypes = [wintypes.LPCWSTR, ctypes.POINTER(ctypes.c_int)]
    to_argv.restype = ctypes.POINTER(wintypes.LPWSTR)
    local_free = ctypes.windll.kernel32.LocalFree
    local_free.argtypes = [ctypes.c_void_p]
    argc = ctypes.c_int(0)
    argv = to_argv(command, ctypes.byref(argc))
    if not argv:
        raise ProbeError("E-CC", f"CommandLineToArgvW failed on: {command[:200]}")
    try:
        return [argv[i] for i in range(argc.value)]
    finally:
        local_free(ctypes.cast(argv, ctypes.c_void_p))


def find_entry(index: dict, root: Path, entry: dict) -> dict:
    matches = index.get(norm(root / entry["compiled"]), [])
    if len(matches) != 1:
        raise ProbeError(
            "E-CC",
            f"'{entry['id']}': {len(matches)} compile_commands.json entries for {entry['compiled']} (need 1)",
        )
    return matches[0]


def substitute_hipdnn_includes(args: list, prefix: Path, eid: str) -> list:
    out, hits, i = [], [], 0
    while i < len(args):
        arg = args[i]
        flag = next((f for f in INCLUDE_FLAGS if arg.startswith(f)), None)
        separate = flag is not None and arg == flag and i + 1 < len(args)
        value = args[i + 1] if separate else (arg[len(flag) :] if flag else None)
        parts = fwd(value).rstrip("/").split("/") if value else []
        if (
            len(parts) >= 2
            and parts[-2] == "hipdnn"
            and parts[-1] in HIPDNN_INCLUDE_LEAVES
        ):
            hits.append(parts[-1])
            new_value = fwd(prefix / "include" / "hipdnn" / parts[-1])
            out.extend([flag, new_value] if separate else [flag + new_value])
            i += 2 if separate else 1
            continue
        out.append(arg)
        i += 1
    if len(hits) != 3 or set(hits) != set(HIPDNN_INCLUDE_LEAVES):
        raise ProbeError(
            "E-INCLUDES",
            f"'{eid}': expected the 3 hipDNN include dirs once each, found {hits}",
        )
    return out


def rewrite_outputs(args: list, cc_dir: Path, out: Path, eid: str) -> tuple:
    obj_dir = out / "obj"
    rewritten, outputs, obj, i = [], [], None, 0
    while i < len(args):
        arg = args[i]
        if arg[:3] in ("/Fo", "-Fo"):
            obj = obj_dir / f"{eid}.obj"
            rewritten.append("/Fo" + fwd(obj))
        elif arg[:3] in ("/Fd", "-Fd"):
            rewritten.append("/Fd" + fwd(obj_dir) + "/")
            outputs.append(obj_dir)
        elif arg in ("-o", "-MF") and i + 1 < len(args):
            target = obj_dir / (f"{eid}.o" if arg == "-o" else f"{eid}.d")
            if arg == "-o":
                obj = target
            rewritten.extend([arg, fwd(target)])
            i += 1
        else:
            rewritten.append(arg)
        i += 1
    if obj is None:
        raise ProbeError("E-CC", f"'{eid}': no /Fo or -o in the compile command")
    for path in [obj, *outputs]:
        if not is_within(cc_dir / path, out):
            raise ProbeError("E-CC", f"'{eid}': output {path} escapes --out")
    return rewritten, obj


def generate_descriptors(root: Path, out: Path) -> None:
    real = root / "aten" / "src" / "ATen" / "cudnn" / "Descriptors.h"
    if not real.is_file():
        raise ProbeError("E-EXTRACT", f"{real} not found")
    lines = [line.rstrip("\r") for line in real.read_text(encoding="utf-8").split("\n")]
    stripped = [line.rstrip() for line in lines]
    try:
        begin = stripped.index(DESCRIPTORS_BEGIN)
        end = stripped.index(DESCRIPTORS_END, begin)
    except ValueError:
        raise ProbeError(
            "E-EXTRACT",
            f"{real}: anchors '{DESCRIPTORS_BEGIN}' .. '{DESCRIPTORS_END}' not found",
        ) from None
    header = [
        "#pragma once",
        f"// Generated by pytorch_compile_probe.py from {fwd(real)}; do not edit.",
        "#include <cstdint>",
        "#include <string>",
        "#include <vector>",
        "#include <ATen/cudnn/cudnn-wrapper.h>",
    ]
    target = out / "generated" / "ATen" / "cudnn" / "Descriptors.h"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "\n".join([*header, *lines[begin:end], "} // namespace at::native", ""]),
        encoding="utf-8",
    )


def write_wrapper(root: Path, out: Path, entry: dict) -> Path:
    lines = [
        "#if __has_include(<ATen/cuda/CUDAConfig.h>)",
        "#include <ATen/cuda/CUDAConfig.h>",
        "#endif",
        "#include <ATen/hip/HIPConfig.h>",
        "#undef AT_CUDNN_ENABLED",
        "#define AT_CUDNN_ENABLED() 1",
        f'#include "{fwd(root / entry["compiled"])}"',
        "#if !AT_CUDNN_ENABLED()",
        '#error "AT_CUDNN_ENABLED() was reset; the probed file compiled to nothing"',
        "#endif",
        "static_assert(sizeof(cudnn_frontend::ExecutionPlan) > 0);",
    ]
    if entry["tier"] == "COMPILE":
        lines.append(
            f"[[maybe_unused]] static const auto hipdnn_probe_canary = &{entry['canary']};"
        )
    wrapper = out / "wrappers" / f"{entry['id']}.cpp"
    wrapper.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return wrapper


def build_command(
    cc: dict, entry: dict, root: Path, prefix: Path, out: Path, config: dict
) -> tuple:
    args = list(cc["arguments"]) if "arguments" in cc else split_command(cc["command"])
    cc_dir = Path(cc["directory"])
    eid = entry["id"]
    args = substitute_hipdnn_includes(args, prefix, eid)
    if not config["sdpa"]:
        args = [
            a for a in args if a not in ("-DHIPDNN_ENABLE_SDPA", "/DHIPDNN_ENABLE_SDPA")
        ]
    extra = ["-DHIPDNN_FRONTEND_SKIP_JSON_LIB"] if config["skip_json_lib"] else []
    if entry["tier"] in FORCED_TIERS:
        extra += ["-I" + fwd(OVERLAY_DIR), "-I" + fwd(out / "generated")]
        source = norm(cc_dir / cc["file"])
        positions = [
            i for i, a in enumerate(args) if i > 0 and norm(cc_dir / a) == source
        ]
        if len(positions) != 1:
            raise ProbeError(
                "E-CC",
                f"'{eid}': source token for {cc['file']} found {len(positions)} times",
            )
        args[positions[0]] = fwd(write_wrapper(root, out, entry))
    args = [args[0], *extra, *args[1:]]
    args, obj = rewrite_outputs(args, cc_dir, out, eid)
    return args, cc_dir, obj


def compiler_version(compiler: str) -> str:
    try:
        result = subprocess.run(
            [compiler, "--version"], capture_output=True, text=True, errors="replace"
        )
    except OSError as error:
        return f"unavailable: {error}"
    return (result.stdout or result.stderr).strip().split("\n", 1)[0].strip()


def run_compile(entry: dict, args: list, cc_dir: Path, obj: Path, log: Path) -> dict:
    if obj.exists():
        obj.unlink()
    start = time.monotonic()
    try:
        result = subprocess.run(
            args,
            cwd=cc_dir,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=COMPILE_TIMEOUT_S,
        )
        output = result.stdout.decode("utf-8", errors="replace")
        ok = result.returncode == 0 and obj.is_file()
        note = f"exit code {result.returncode}"
    except subprocess.TimeoutExpired as error:
        output = (error.stdout or b"").decode("utf-8", errors="replace")
        ok, note = False, f"timed out after {COMPILE_TIMEOUT_S} s"
    except OSError as error:
        output, ok, note = "", False, f"could not run the compiler: {error}"
    seconds = round(time.monotonic() - start, 1)
    command = subprocess.list2cmdline(args) if os.name == "nt" else shlex.join(args)
    log.write_text(
        f"# cwd: {cc_dir}\n# command: {command}\n# result: {note}\n\n{output}",
        encoding="utf-8",
    )

    if entry["tier"] == "XFAIL_COMPILE":
        if ok:
            outcome = "xfail-now-passes"
        elif re.search(entry["anchor"], output):
            outcome = "xfail-still-failing"
        else:
            outcome = "compile-failed"
    else:
        outcome = "compiled" if ok else "compile-failed"
    result = {"outcome": outcome, "seconds": seconds, "note": note}
    if ok:
        result["object_bytes"] = obj.stat().st_size
    return result


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--pytorch-root", required=True, type=Path)
    parser.add_argument("--pytorch-build", required=True, type=Path)
    parser.add_argument("--hipdnn-prefix", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--only", action="append", default=[], metavar="ID")
    opts = parser.parse_args()
    root, build = opts.pytorch_root.resolve(), opts.pytorch_build.resolve()
    prefix, out = opts.hipdnn_prefix.resolve(), opts.out.resolve()

    try:
        manifest = load_manifest()
        ids = [e["id"] for e in manifest["entries"]]
        unknown = [i for i in opts.only if i not in ids]
        if unknown:
            raise ProbeError("P-COMPLETE", f"--only names unknown ids {unknown}")
        selected = [
            e for e in manifest["entries"] if not opts.only or e["id"] in opts.only
        ]

        preflight_env()
        config = preflight_prefix(prefix)
        preflight_tree(root, build, out)
        status_before = tree_status(root)
        hipify_checks = preflight_hipify(root, out, selected)
        preflight_complete(root, manifest)

        for entry in selected:
            if entry.get("requires_sdpa") and not config["sdpa"]:
                entry["tier"], entry["reason"] = (
                    "EXCLUDED",
                    "install built with HIPDNN_ENABLE_SDPA OFF",
                )

        for sub in ("obj", "logs", "wrappers", "generated"):
            (out / sub).mkdir(parents=True, exist_ok=True)
        to_run = [e for e in selected if e["tier"] != "EXCLUDED"]
        if any(e["tier"] in FORCED_TIERS for e in to_run):
            generate_descriptors(root, out)
        cc_db = json.loads(
            (build / "compile_commands.json").read_text(encoding="utf-8")
        )
        index = {}
        for cc in cc_db:
            index.setdefault(norm(Path(cc["directory"]) / cc["file"]), []).append(cc)
        commands = {
            e["id"]: build_command(
                find_entry(index, root, e), e, root, prefix, out, config
            )
            for e in to_run
        }

        head = git(root, "rev-parse", "HEAD").strip()
        blobs = git(root, "hash-object", "--", *[e["source"] for e in selected]).split()
    except ProbeError as error:
        print(error, file=sys.stderr)
        return 2

    compilers = {}
    report_entries = []
    for entry, blob in zip(selected, blobs):
        record = {
            k: entry[k] for k in ("id", "tier", "source", "compiled") if k in entry
        }
        record["source_blob"] = blob
        for key in ("canary", "anchor", "reason"):
            if key in entry:
                record[key] = entry[key]
        if entry["tier"] == "EXCLUDED":
            record.update(outcome="excluded", seconds=0.0)
        else:
            args, cc_dir, obj = commands[entry["id"]]
            if args[0] not in compilers:
                compilers[args[0]] = compiler_version(args[0])
            log = out / "logs" / f"{entry['id']}.log"
            record.update(run_compile(entry, args, cc_dir, obj, log))
            record["log"] = fwd(log)
        print(
            f"{record['outcome']:>20}  {entry['id']}  ({record['seconds']} s)",
            flush=True,
        )
        report_entries.append(record)

    try:
        status_after = tree_status(root)
    except ProbeError as error:
        print(error, file=sys.stderr)
        status_after = None
    expected = {
        "COMPILE": "compiled",
        "COMPILE_ASIS": "compiled",
        "XFAIL_COMPILE": "xfail-still-failing",
    }
    met = all(
        r["outcome"] == expected.get(r["tier"], "excluded") for r in report_entries
    )
    unchanged = status_before == status_after
    exit_code = 0 if met and unchanged else 1
    if status_after is None:
        exit_code = 2
    summary = {}
    for record in report_entries:
        summary[record["outcome"]] = summary.get(record["outcome"], 0) + 1
    report = {
        "pytorch_root": fwd(root),
        "pytorch_head": head,
        "pytorch_build": fwd(build),
        "hipdnn_prefix": fwd(prefix),
        "prefix_config": config,
        "compilers": compilers,
        "only": opts.only,
        "pytorch_status_before": status_before,
        "pytorch_status_after": status_after,
        "pytorch_tree_unchanged": unchanged,
        "hipify_checks": hipify_checks,
        "entries": report_entries,
        "summary": summary,
        "exit_code": exit_code,
    }
    (out / "report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    if status_after is not None and not unchanged:
        print("PyTorch tree status changed during the probe", file=sys.stderr)
    stale_mtimes = [
        c["hipified"] for c in hipify_checks["checked"] if c["mtime_older_than_source"]
    ]
    if stale_mtimes:
        print(f"note: content-current but older than their sources: {stale_mtimes}")
    print(f"summary: {summary}; report: {fwd(out / 'report.json')}")
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
